/**
 * Вердикты строк сравнительной таблицы — «да», «нет» или «ни то ни
 * другое» — отдельно от текста ячеек (этап C ТЗ
 * `docs-tz/TZ-Enterprise-Tutorial-Landing.md`, §3 Уровень 4).
 *
 * ## Почему не в словарях
 *
 * Вердикт — факт о продукте, а не текст: во всех пяти локалях он
 * одинаковый. Положить его в `dictionaries/*.json` значило бы завести
 * шесть одинаковых значений в пяти файлах и ждать, пока они разойдутся
 * при первом же переводе. Здесь он один.
 *
 * ## Почему не вычисляется из текста ячейки
 *
 * Соблазн «посмотреть, начинается ли ячейка со слова „Да“» разбивается
 * о пять языков: `Да / Так / Yes / Ja / Sí`. Хуже того, четыре ячейки из
 * двенадцати вердикта не имеют вовсе — «Обычно да», «Чаще слепок
 * вёрстки», «Обычно про свой собственный продукт», «Чаще интерактивное
 * демо». Это оговорки о КАТЕГОРИИ, а не ответы про конкретный продукт,
 * и знак рядом с ними превратил бы осторожную формулировку в
 * утверждение — ровно то, чего избегает доккомментарий
 * `CompetitorComparisonTable`. Поэтому `'none'` здесь не «забыли
 * заполнить», а содержательное значение.
 *
 * ## Связь с порядком строк
 *
 * Массив параллелен `siteTutorialLanding.compare.rows` словаря и
 * держится на порядке. Если в словаре появится седьмая строка, знаки
 * поедут — поэтому компонент сверяет длины и при расхождении не рисует
 * знаки вовсе (лучше без них, чем не у тех строк), а
 * `scripts/compare-verdicts.test.ts` роняет сборку.
 */

export type Verdict = 'yes' | 'no' | 'none';

export interface RowVerdict {
  us: Verdict;
  them: Verdict;
}

export const COMPARE_VERDICTS: readonly RowVerdict[] = [
  // Нужно расширение в браузере: у нас — нет; у них — «обычно да».
  { us: 'no', them: 'none' },
  // Реальные действия на живом сайте: да / «чаще слепок вёрстки».
  { us: 'yes', them: 'none' },
  // На выходе готовое видео: да / «чаще интерактивное демо».
  { us: 'yes', them: 'none' },
  // Несколько клиентских сайтов: да / «обычно про свой продукт».
  { us: 'yes', them: 'none' },
  // Аналитика вовлечённости — наш проигрыш, и он должен быть виден.
  { us: 'no', them: 'yes' },
  // Встраиваемый виджет — второй наш проигрыш.
  { us: 'no', them: 'yes' },
];
