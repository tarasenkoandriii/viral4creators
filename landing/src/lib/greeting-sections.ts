/**
 * Порядок секций страницы поздравлений (§5.2 ТЗ
 * `docs-tz/TZ-Greeting-2.0-Adaptive-Persona-Landing.md`) и выключатель
 * секции «Вы в кадре».
 *
 * ## Зачем порядок вынесен из разметки
 *
 * Ради одной секции — «Вы в кадре» (§5.2 п.5). Режим «Я в кадре» в коде
 * есть (этапы E–G), но в проде закрыт флагом `PERSONA_ENABLED` и до
 * юридического шлюза людям не открывается. Главное правило страницы —
 * ни одного обещания, которого нет в проде, — значит, секции не должно
 * быть в разметке вовсе, а не «спрятана стилем».
 *
 * Включается она ОДНОЙ константой, тем же приёмом, что
 * `GREETING_REAL_FRAME_LOCALES` у кадров: не человек по чек-листу, а
 * одно место. Страница строит секции по `greetingSectionOrder()`, и
 * пока константа `false`, идентификатора `persona` в списке нет —
 * проверяет `scripts/greeting-sections.test.ts`.
 *
 * Включать — в том же релизе, что и `PERSONA_ENABLED` на проде (правило
 * очерёдности §5.4: текст о возможности не раньше самой возможности).
 *
 * ## Этап J: секция построена, но выключена
 *
 * Разметка (`app/[locale]/greetings/PersonaSection.tsx`), тексты в пяти
 * словарях (`greetingsLanding.persona`) и схема `greet-persona.svg`
 * готовы заранее, чтобы после шлюза включение было одной строкой, а не
 * спешной вёрсткой. Пока константа `false`:
 *
 *  - секции нет в `<main>` — её нет в `greetingSectionOrder()`;
 *  - дополнений «Лицо» и «Голос» нет в «Данных и деликатных поводах» —
 *    `greetingPrivacyItems()` ниже отдаёт ровно `privacy.items`;
 *  - тексты раздела не попадают в HTML и через клиентский словарь:
 *    `clientDictionary()` вырезает `persona` всегда (см. get-dictionary.ts);
 *  - метаданные и OG-карточки берут только `meta` и `hero`.
 *
 * Перед включением — два открытых вопроса шлюза, о которых тексты
 * НАМЕРЕННО молчат: маркировка ИИ-контента в ролике с человеком (В-6 —
 * TBD, решает юрист; ни «ролик будет помечен», ни «без пометки» не
 * пишем) и окончательные сроки хранения и тарифы (В-1, В-3 — сейчас
 * «временно по рекомендации ТЗ»: 30 дней, голос с Standard). Поменялось
 * решение — поменять тексты раньше константы: тест текстов сверяет
 * «18», «30» и «Standard» с тем, что в коде бэкенда.
 */

/**
 * Секция «Вы в кадре» и её дополнения к «Данным». Выключена:
 * `PERSONA_ENABLED` в проде выключен, юридический шлюз §4.10 не пройден.
 * Тест секций проверяет, что здесь `false`, — включающий правит и его,
 * осознанно, в том же коммите.
 */
export const PERSONA_SECTION_ENABLED: boolean = false;

/**
 * Секция «Сравнение» — таблица «мы против КАТЕГОРИЙ альтернатив»
 * (§5.5 и В-8 ТЗ; обзор — `docs-tz/OBZOR-Konkurentov-Greetings.md`).
 * Выключена по умолчанию: утверждения о категориях («заказ у человека —
 * обычно дни ожидания» и т. п.) опираются на обзор рынка, а его факты
 * подтверждает владелец продукта. Тот же приём, что у «Вы в кадре»:
 * пока `false`, секции нет в `greetingSectionOrder()`, а тексты
 * `greetingsLanding.compare` не уходят в клиентский словарь (вырезаются
 * всегда — клиенту они не нужны). Держит
 * `scripts/greeting-compare.test.ts`; включающий меняет и его assert.
 *
 * Перед включением — перепроверить §3 обзора (цены и сроки чужих
 * сервисов меняются) и строку «цена» о нас: «режимы сейчас бесплатны»
 * верно только при выключенном `PLANS_BILLING_ENABLED`.
 */
export const COMPARE_SECTION_ENABLED: boolean = false;

/**
 * Все секции в порядке §5.2. Hero первым, финальный призыв последним;
 * футер — не секция `<main>`, он вне списка.
 */
export const GREETING_SECTIONS = [
  'hero',
  'samples',
  'how',
  'occasions',
  'persona',
  'features',
  'audience',
  'privacy',
  'compare',
  'price',
  'faq',
  'finalCta',
] as const;

export type GreetingSectionId = (typeof GREETING_SECTIONS)[number];

/**
 * Секции, которые страница рисует сейчас. Параметры — для теста.
 * «Сравнение» стоит перед ценой: таблица отвечает на «почему не открытка
 * и не заказ у знаменитости», и сразу за ней — сколько это стоит.
 */
export function greetingSectionOrder(
  personaEnabled: boolean = PERSONA_SECTION_ENABLED,
  compareEnabled: boolean = COMPARE_SECTION_ENABLED,
): GreetingSectionId[] {
  return GREETING_SECTIONS.filter(
    (id) =>
      (id !== 'persona' || personaEnabled) &&
      (id !== 'compare' || compareEnabled),
  );
}

/** Карточка «заголовок + текст» — форма пунктов «Данных» в словаре. */
export interface GreetingCopyItem {
  title: string;
  text: string;
}

/**
 * Пункты секции «Данные и деликатные поводы» (§5.1, строка «Ответ на
 * главное возражение»: «после Фазы 1Б — лицо и голос»).
 *
 * Лицо и голос дописываются В КОНЕЦ и той же константой, что сама
 * секция «Вы в кадре»: ответ «что будет с моим лицом» без режима, где
 * лицо вообще загружается, был бы обещанием о несуществующем. Тексты
 * дополнений живут в `greetingsLanding.persona.privacy`, а не в
 * `privacy.items` — так все тексты режима в одном разделе словаря, и
 * тест может запретить их везде вне него.
 */
export function greetingPrivacyItems(
  base: readonly GreetingCopyItem[],
  personaAdditions: readonly GreetingCopyItem[],
  personaEnabled: boolean = PERSONA_SECTION_ENABLED,
): GreetingCopyItem[] {
  return personaEnabled ? [...base, ...personaAdditions] : [...base];
}
