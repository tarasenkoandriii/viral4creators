/**
 * Г-3.2 (аудит round4, этап 64): `JSON.stringify` не экранирует `<`, а
 * значит и `</script>` внутри пользовательского значения (заголовок
 * ролика/статьи, название или описание товара — ни на одном из этих
 * полей нет фильтра на `<`) обрывает тег `<script type="application/
 * ld+json">` раньше времени и позволяет внедрить произвольный
 * `<script>` следом — XSS у каждого посетителя публичной страницы
 * (`/video/[id]`, `/[locale]/blog/[slug]`), без какой-либо модерации:
 * оператор в `/shared-videos` до этого этапа даже не видел
 * `productDescription`, чтобы заметить payload при одобрении.
 *
 * `<` — валидный JSON-экранированный `<` (не разрешённый в самом
 * schema.org JSON-LD, но здесь это HTML-контекст, а не JSON-парсер: то,
 * что видит парсер JS/HTML, — уже `<`, последовательность `</script>`
 * в исходном тексте так и не появляется).
 */
export function jsonLdScript(value: unknown): string {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}
