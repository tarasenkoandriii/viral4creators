/**
 * Откуда секция «Как это выглядит» берёт картинки — схемы или настоящие
 * кадры продукта (этап I ТЗ `docs-tz/TZ-Enterprise-Tutorial-Landing.md`).
 *
 * ## Зачем отдельный слой, а не просто заменить файлы
 *
 * Этап I меняет не только картинки. Настоящий кадр — вертикальный, а не
 * ландшафтный; ему нужен `alt` (схеме он не нужен — подпись под кадром
 * несёт весь смысл, дубль мешал бы скринридеру); и он делает НЕПРАВДОЙ
 * оговорку в тексте секции, которая сейчас честно говорит «ниже схемы
 * интерфейса, а не сам интерфейс». Всё это обязано переключаться ВМЕСТЕ.
 *
 * Отсюда правило, ради которого файл и существует: **картинки и текст
 * переключает один список, а не человек по чек-листу.** Пока локали нет
 * в `REAL_FRAME_LOCALES`, страница показывает схемы и старую оговорку;
 * как только локаль появилась — кадры, `alt` и новую оговорку. Ошибиться
 * в одну сторону (поменять картинки, забыть текст) физически негде.
 *
 * ## Почему список локалей, а не флаг на кадр
 *
 * Полусконвертированная секция — два настоящих кадра и две схемы рядом —
 * хуже обоих цельных состояний: оговорка в этом случае неверна для одной
 * половины и верна для другой, и сказать правду одним предложением уже
 * нельзя. Поэтому единица переключения — локаль целиком, и это
 * проверяется (`scripts/tutorial-frames.test.ts`, шов 17 в
 * `scripts/check-docs.mjs`).
 */
import type { Locale } from './i18n';

/** Сколько кадров в секции. Держится за длину `how.items` в словарях —
 *  проверяется тестом. */
export const FRAME_COUNT = 4;

/**
 * Локали, для которых сняты и закоммичены ВСЕ четыре настоящих кадра.
 *
 * Пусто до этапа I: кадры снимаются прогоном по живому сайту
 * (`doc/TUTORIAL-FRAMES-CAPTURE.md`), выдумать их нельзя — страница,
 * которая продаёт достоверность, не может показывать нарисованный
 * «снимок экрана».
 *
 * Добавлять локаль сюда — последним шагом, ПОСЛЕ того как четыре файла
 * `tutorial-shot-<locale>-{1..4}.avif` лежат в `public/illustrations/`.
 * Обратный порядок роняет сборку: шов 17 сверяет список с файлами.
 */
export const REAL_FRAME_LOCALES: readonly Locale[] = [];

export interface FrameImage {
  src: string;
  width: number;
  height: number;
  /** Настоящий снимок (вертикальный) против схемы (ландшафтной). */
  real: boolean;
}

/** Холст схемы — 3:2, см. находку И-13 в §11 ТЗ. */
const SCHEME = { width: 840, height: 540 } as const;

/**
 * Кадр обрезается по значимой зоне телефонного экрана 390×844: верхние
 * ~60%, где окно сайта и панель управления; низ уходит в градиентное
 * затухание средствами CSS. 780×1012 — та же зона при двойной
 * плотности.
 */
const SHOT = { width: 780, height: 1012 } as const;

export function hasRealFrames(locale: Locale): boolean {
  return REAL_FRAME_LOCALES.includes(locale);
}

export function frameImage(locale: Locale, index: number): FrameImage {
  if (hasRealFrames(locale)) {
    return {
      src: `/illustrations/tutorial-shot-${locale}-${index}.avif`,
      ...SHOT,
      real: true,
    };
  }
  return {
    src: `/illustrations/tutorial-frame-${index}.svg`,
    ...SCHEME,
    real: false,
  };
}

/**
 * Потолок ширины настоящего кадра на странице. **Держится за
 * `max-width` у `.frame-card-shot .frame-shot` в `globals.css`** —
 * согласие этих двух чисел проверяет шов 17 в `scripts/check-docs.mjs`.
 */
export const SHOT_CSS_WIDTH = 300;

/**
 * `sizes` нужен только настоящему кадру: у схемы это SVG, и браузеру
 * нечего выбирать.
 *
 * Значение КОНСТАНТНОЕ, и это не упрощение: снимок упирается в
 * `max-width: 300px` на любой ширине окна — и на телефоне, и на
 * десктопе он показывается одинаково (замерено 278px содержимого).
 * Медиазапросам здесь взяться неоткуда.
 *
 * Первая редакция подставляла сюда ширины ЛАНДШАФТНОЙ схемы из замеров
 * этапа A (481/664/342). Аудит поймал (А-И2): браузер верил и брал
 * вариант `w=640` под слот в 278 пикселей — вдвое больше нужного, на
 * каждой загрузке. Ровно то, ради предотвращения чего `sizes` и
 * существует.
 */
export function frameSizes(real: boolean): string | undefined {
  return real ? `${SHOT_CSS_WIDTH}px` : undefined;
}
