/**
 * Реферальная ссылка на лендинге — «Условно бесплатный Lite» §5.1, этап 134.
 *
 * Каноническая ссылка приглашения ведёт СЮДА, а не сразу в Telegram:
 * `https://<лендинг>/r/<код>`. Причина в §5.1 ТЗ и она простая — у
 * продукта два живых варианта (мини-апп и обычный фронтенд), а
 * `t.me/<бот>/app?startapp=…` честно работает только для первого: тому,
 * кто открыл её без Telegram, мессенджер показывает установочный экран.
 * Приглашение, которое половине получателей предлагает сперва поставить
 * чужое приложение, — плохое приглашение.
 *
 * Здесь — только чистые функции и один серверный вызов. Никакого
 * клиентского кода: переход считается на сервере, до всякого
 * JavaScript, поэтому счётчик не зависит от блокировщиков (§5.1).
 */

/** Тот же адрес API, что у блога и страницы ролика (`blog-api.ts`). */
const API_BASE_URL = process.env.API_BASE_URL ?? 'http://localhost:3000/api';

/**
 * Тот же алфавит и длина, что на сервере (`backend/src/common/referral.ts`)
 * и на клиенте (`frontend/src/lib/referral.ts`): base32 без похожих друг
 * на друга знаков, восемь символов.
 */
const CODE_RE = /^[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{8}$/;

/**
 * Сколько ждём отметку о переходе. Полторы секунды — это уже «сайт
 * подвис» для человека, пришедшего по ссылке из переписки, а счётчик
 * переходов не стоит того, чтобы ради него ждать дольше.
 */
const VISIT_TIMEOUT_MS = 1500;

/** Префикс `startapp`: Telegram отдаёт один параметр на все нужды. */
export const START_PARAM_PREFIX = 'r_';

/**
 * Нормализация адреса: регистр и пробелы человек приносит из мессенджера,
 * а вот всё остальное — уже не код. `null` означает «такого кода быть не
 * может», и страница на него отвечает 404, а не походом в API: маршрут
 * анонимный, и перебирать им форму кода не должно быть дёшево.
 */
export function normalizeCode(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const code = decodeURIComponent(raw).trim().toUpperCase();
  return CODE_RE.test(code) ? code : null;
}

/** «Открыть в Telegram» — та самая `t.me`-ссылка со `startapp`. */
export function telegramInviteLink(code: string, botUsername: string): string {
  return `https://t.me/${botUsername.replace(/^@/, '')}/app?startapp=${START_PARAM_PREFIX}${code}`;
}

/**
 * «Продолжить здесь» — обычный фронтенд, тем же query-параметром, каким
 * уже приходит `?fromShared=` (см. `frontend/src/lib/referral.ts`).
 */
export function appInviteLink(code: string, tmaUrl: string): string {
  return `${tmaUrl.replace(/\/+$/, '')}?ref=${code}`;
}

/**
 * Отметить переход (`POST /referrals/visit`, §5.2).
 *
 * Best-effort и молча: ответ бэкенда странице не нужен вообще — она
 * показывает одно и то же и для живого кода, и для протухшего, и знать,
 * существует ли чужой код, пришедшему незачем. Ошибка сети не должна
 * стоить человеку страницы, на которую его позвали, поэтому исключение
 * гасится здесь, а не всплывает в рендер.
 *
 * `cache: 'no-store'` обязателен: это POST-побочный эффект, а не данные
 * страницы — закешированный «переход» перестал бы считаться со второго
 * раза.
 */
export async function registerReferralVisit(code: string): Promise<void> {
  try {
    await fetch(`${API_BASE_URL}/referrals/visit`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ code }),
      cache: 'no-store',
      // Найдено аудитом этапа 134: без таймаута страница приглашения
      // ждала бы бэкенд СКОЛЬКО УГОДНО — счётчик считается до рендера,
      // и медленная база превращалась бы в белый экран у человека,
      // который только что нажал на чужую ссылку. Переход дороже
      // потерять, чем не посчитать, но не настолько.
      signal: AbortSignal.timeout(VISIT_TIMEOUT_MS),
    });
  } catch {
    // Бэкенд недоступен или не успел — человек всё равно должен
    // увидеть приглашение.
  }
}

/**
 * Агент, который открывает ссылку РАДИ ПРЕВЬЮ, а не ради человека.
 *
 * Зачем это здесь. Приглашение живёт в мессенджерах, и почти каждый из
 * них, увидев ссылку в переписке, сам сходит по ней за Open Graph-
 * карточкой — до того, как её кто-либо откроет. Без этой проверки
 * человек, отправивший ссылку в три чата, увидел бы у себя в кабинете
 * три перехода, которых не было, а §12.1 считает по этому числу долю
 * дошедших до ролика — то есть занижал бы её ровно на выдумку.
 *
 * Список именной и заведомо неполный: неизвестный сканер посчитается
 * переходом, и это правильный размен. Пропустить чужого робота —
 * ошибка в одну единицу; принять человека за робота — потерянный
 * переход у того, кто действительно привёл друга.
 */
const PREVIEW_AGENTS =
  /(bot|crawler|spider|preview|facebookexternalhit|whatsapp|telegram|slack|discord|vkshare|skypeuripreview|embedly|quora link preview|redditbot|applebot|yandex)/i;

export function isLinkPreviewAgent(userAgent: string | null | undefined): boolean {
  return !!userAgent && PREVIEW_AGENTS.test(userAgent);
}
