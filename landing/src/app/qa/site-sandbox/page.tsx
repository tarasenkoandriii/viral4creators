import type { Metadata } from 'next';
import { SandboxClient } from './SandboxClient';

/**
 * Полигон для разведчика чужих сайтов (`chromium-page-explorer.ts`),
 * 29.09.2026.
 *
 * ## Зачем нужна СВОЯ страница, а не наш настоящий лендинг
 *
 * Обучалка по сайту заказчика — единственная часть продукта, работающая
 * с DOM, которого мы не контролируем. Проверить её нечем: у чужого
 * сайта нет каталога хуков, нет фикстуры, и он меняется без нас. Взять
 * вместо него наш лендинг — заманчиво и почти бесполезно: на нём нет
 * ни одного `input[type=password]` (значит эвристика входа не
 * сработает), нет необратимых кнопок (значит стоп-лист не проверится),
 * нет куки-стены и ленивой подгрузки — то есть ровно тех сюрпризов,
 * ради которых разведчик и написан.
 *
 * Поэтому страница проектируется ПОД СЛУЧАИ, а не берётся та, что
 * случайно существует. Каждый блок ниже — отдельный режим отказа,
 * который в проде встретится на чужом сайте, а здесь встречается
 * предсказуемо:
 *
 *   - куки-баннер поверх содержимого — самый частый первый экран в
 *     Европе; пока он не закрыт, «кадр страницы» показывает не
 *     страницу;
 *   - форма с паролем — включает `looksLikeLogin` (§5.4) и путь
 *     живого входа;
 *   - кнопка с опасным словом — стоп-лист §8.3, который обязан
 *     ПРЕДУПРЕДИТЬ, но не заблокировать;
 *   - ленивый блок, появляющийся через секунду, — проверка того, что
 *     кадр снимается после `waitForNetworkIdle`, а не до;
 *   - переход по кнопке внутри того же origin — обычный раунд.
 *
 * ## Чего здесь СОЗНАТЕЛЬНО нет
 *
 * Внешних переходов и настоящих форм: замок `assertStillInside` обязан
 * держать разведчика внутри origin, и проверять это лучше на чужом
 * сайте, а не подсовывать себе выход наружу. И никакой серверной
 * логики: полигон — это разметка, а не приложение, иначе он начнёт
 * ломаться сам и станет вторым источником шума.
 *
 * ## Почему не в `public/`
 *
 * Статический файл не попал бы под middleware локалей и под общий
 * заголовок `noindex`, а главное — его нельзя было бы проверить швом:
 * `check-docs` читает исходники, а не сборку.
 */
export const metadata: Metadata = {
  title: 'QA sandbox — viral4creators',
  // Страница служебная: в выдаче ей делать нечего, а ссылок на неё нет
  // ниоткуда (в `sitemap.ts` она не перечислена, в `robots.ts` закрыта
  // отдельным `Disallow`). Три замка, а не один: любой из них могут
  // снять правкой в другом файле, и тогда останутся два.
  robots: { index: false, follow: false },
};

export default function QaSiteSandboxPage() {
  return <SandboxClient />;
}
