import type { MetadataRoute } from 'next';

/**
 * `robots.txt` — конвенция Next App Router: файл `robots.ts` в `app/`
 * отдаётся на `/robots.txt`, тот же приём, что уже есть в `landing/`.
 *
 * Появился по результатам боевой проверки: у маркетплейса были карты
 * сайта (`/sitemap.xml`, `/sitemap-news.xml`) и две ленты, но
 * `/robots.txt` отвечал 404. Для поисковика это не «разрешено всё» —
 * это отсутствие единственного файла, из которого он узнаёт, ГДЕ
 * карта сайта; дальше он ищет её только по угадыванию стандартного
 * имени и никогда не найдёт `sitemap-news.xml`.
 *
 * `/embed/*` закрыт намеренно. Это виджет портфолио для вставки на
 * чужой сайт (ТЗ §20 №5): тот же текст, что и на странице исполнителя,
 * но без навигации и с собственным адресом. В индексе он был бы
 * дублем настоящей страницы — и худшим из двух, потому что именно
 * туда вёл бы поиск. `noindex` на самой странице сработал бы тоже, но
 * виджет открывается в `<iframe>` с чужого домена, а не заходом
 * человека, — запрет обхода честнее описывает намерение.
 *
 * Статический маршрут: здесь, в отличие от `landing/`, ветвления по
 * хосту нет — у маркетплейса один домен.
 */
const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? 'http://localhost:3004';

export default function robots(): MetadataRoute.Robots {
  return {
    rules: { userAgent: '*', allow: '/', disallow: ['/embed/'] },
    sitemap: [`${SITE_URL}/sitemap.xml`, `${SITE_URL}/sitemap-news.xml`],
  };
}
