/**
 * Текст ответа → текст для озвучки (Э5, §4.10). ЧИСТЫЙ модуль.
 *
 * Озвучивается ровно то, что посетитель видит (маскированный текст из базы,
 * §4.7), без разметки: метки источников `[S1]`, markdown (`**`, `#`, `>`,
 * маркеры списков, обратные кавычки), ссылки — подписью без адреса, голые
 * URL — словом «ссылка» не читаются вовсе (на слух адрес бесполезен).
 * Длина — до VOICE_DEFAULTS.ttsMaxChars по границе предложения: дальше
 * посетитель дочитает глазами.
 */
export function speakableText(raw: string, maxChars: number): string {
  let t = raw
    // Метки источников: [S1], [S1, S2], [S12]
    .replace(/\[S\d+(?:\s*,\s*S\d+)*\]/g, '')
    // Картинки (фильтр стрима их и так вырезает) и ссылки → подпись.
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]+)\]\((?:[^()\s]+)\)/g, '$1')
    // Голые адреса и почта на слух бесполезны (почта и так маскирована).
    .replace(/\bhttps?:\/\/\S+/gi, '')
    // Заголовки, цитаты, маркеры списков в начале строки.
    .replace(/^\s{0,3}(?:#{1,6}\s+|>\s?|[-*+]\s+|\d{1,3}[.)]\s+)/gm, '')
    // Жирный/курсив/код.
    .replace(/[*_`~]+/g, '')
    .replace(/\s+/g, ' ')
    // Пробел, оставшийся на месте метки перед знаком препинания.
    .replace(/\s+([.,!?;:…])/g, '$1')
    .trim();
  if (t.length <= maxChars) return t;
  const cut = t.slice(0, maxChars);
  const end = Math.max(
    cut.lastIndexOf('. '),
    cut.lastIndexOf('! '),
    cut.lastIndexOf('? '),
    cut.lastIndexOf('… '),
  );
  t = end > maxChars / 2 ? cut.slice(0, end + 1) : cut;
  return t.trim();
}
