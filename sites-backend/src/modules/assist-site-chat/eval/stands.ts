/**
 * Стенд-сайты eval-набора платформы v1 — W3 (план Э2 «Приёмка» п.4; ТЗ
 * §9.2): магазин (uk), SaaS (ru), услуги (uk). ДАННЫЕ, без кода базы: их
 * сеет testing/ (CI, фейковая модель) и скрипт живого прогона.
 *
 * Страницы с инъекцией — двух видов: `quarantine` (детектор K2 ловит её
 * при индексации — фрагмент в карантине, как в проде) и `legacy` (старый
 * фрагмент, проиндексированный ДО правила детектора: в поиске он есть —
 * проверяет глубокую защиту поиска виджета). Хост стенда задаёт сид
 * (уникальный на прогон): URL = `https://<хост><path>`.
 */
export type StandId = 'shop' | 'saas' | 'services';

export interface StandPage {
  path: string;
  title: string;
  text: string;
  lang: string;
  ugc?: boolean;
  /** Страница с инъекцией: карантин при индексации или «старый» фрагмент. */
  injection?: 'quarantine' | 'legacy';
}

export interface StandFaq {
  question: string;
  answer: string;
  lang: string;
}

export interface Stand {
  id: StandId;
  name: string;
  lang: string;
  pages: StandPage[];
  faq: StandFaq[];
}

