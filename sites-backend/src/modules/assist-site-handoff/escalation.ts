/**
 * Порядок важен: `sensitive` первым (без генерации ответа), затем жалоба
 * и возврат (их предлагают человеку даже вежливо), раздражение, опт.
 */
const ORDER: readonly EscalationKind[] = [
  'sensitive',
  'complaint',
  'refund',
  'irritation',
  'wholesale',
];

export function detectEscalation(
  question: string,
  enabled: Readonly<Record<EscalationKind, boolean>>,
): EscalationKind | null {
  if (typeof question !== 'string') return null;
  // Пробел в конце — чтобы основы вида «опт » ловили слово в конце фразы.
  const q = `${question.normalize('NFKC').replace(/[’ʼ`]/g, "'")} `;
  if (!q.trim()) return null;
  for (const kind of ORDER) {
    if (enabled[kind] && DICT[kind].test(q)) return kind;
  }
  // «!!!» и КРИК (≥ 3 слов капсом) — раздражение без словаря.
  if (enabled.irritation) {
    if (/[!?]{3,}/.test(q)) return 'irritation';
    const caps = q.match(/(?<![\p{L}])[\p{Lu}]{3,}(?![\p{L}])/gu) ?? [];
    if (caps.length >= 3) return 'irritation';
  }
  return null;
}
