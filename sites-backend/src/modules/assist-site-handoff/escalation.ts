/**
 * Начало слова: перед совпадением не буква и не цифра (`\b` в JS — только
 * ASCII, кириллицу не понимает). Конец не проверяется — словари задают
 * ОСНОВЫ («жалоб» ловит «жалоба», «жалобу», «жалобой»).
 */
function stems(list: readonly string[]): RegExp {
  const body = list
    .map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/ /g, '\\s+'))
    .join('|');
  return new RegExp(`(?<![\\p{L}\\p{N}])(?:${body})`, 'iu');
}

