"""Build the isolated content panel without runtime eval or third-party libraries."""
from pathlib import Path
import sys
root = Path(__file__).resolve().parent.parent
source = root / 'tools/form-capture'
capture = (source / 'capture.js').read_text().replace('export function captureFormStructure', 'function captureFormStructure', 1)
audit = (source / 'quick-audit.js').read_text().replace('export function quickPageAudit', 'function quickPageAudit', 1)
result = '// Generated by scripts/build-form-workbench.py; do not edit.\n' + capture + '\n' + audit + '\n' + (source / 'workbench-ui.js').read_text()
out = source / 'workbench.js'
if '--check' in sys.argv:
    if not out.exists() or out.read_text() != result:
        raise SystemExit('Workbench differs: run python3 scripts/build-form-workbench.py')
else:
    out.write_text(result)
