/**
 * Умолчание для поля тегов панели публикации (этап 136).
 *
 * Проверяется то, ради чего правило вынесено из компонента: приоритет
 * источников (теги исходника важнее собранного из товара) и то, что
 * поле никогда не остаётся пустым, пока про ролик известно хоть что-то.
 * Пустое поле — это ровно тот случай, ради которого этап и делается:
 * теги главный рычаг разгона, а вписывать их с нуля никто не будет.
 */
import assert from 'node:assert/strict';
import {
  defaultTags,
  normalizeTags,
  tagsFromInput,
  tagsToInput,
} from '../src/lib/publish-tags';

// Теги исходника выигрывают у запасного источника.
assert.deepEqual(
  defaultTags({
    sourceTags: ['бег', 'кроссовки'],
    productName: 'Кружка Steel 500',
    category: 'термокружки',
  }),
  ['бег', 'кроссовки'],
  'когда теги исходника есть, они и есть умолчание'
);

// Запасной источник обязателен: без него этап не делает ничего для
// большинства роликов (файл вместо ссылки, автор не заполнил теги).
assert.deepEqual(
  defaultTags({ productName: 'Кружка Steel 500', category: 'термокружки' }),
  ['термокружки', 'Кружка Steel 500'],
  'без тегов исходника умолчание собирается из того, что известно'
);
assert.deepEqual(
  defaultTags({ sourceTags: [], productName: 'Кружка Steel 500' }),
  ['Кружка Steel 500'],
  'пустой список тегов исходника — тот же случай, что и их отсутствие'
);
assert.deepEqual(
  defaultTags({ sourceTags: ['   ', ''], category: 'термокружки' }),
  ['термокружки'],
  'список из одних пробелов не считается тегами исходника'
);
assert.deepEqual(
  defaultTags({}),
  [],
  'когда не известно ничего, поле остаётся пустым — выдумывать нечего'
);

// Нормализация совпадает с серверной (`uniqueTags`): человек должен
// видеть в поле ровно то, что уйдёт, а не то, что сервер потом урежет.
assert.deepEqual(
  normalizeTags([' #Shoes ', 'shoes', '', 'run']),
  ['Shoes', 'run'],
  'решётка снимается, регистр не создаёт дубля, пустые отбрасываются'
);
assert.equal(
  normalizeTags(Array.from({ length: 40 }, (_, i) => `t${i}`)).length,
  30,
  'список тегов ограничен тридцатью, как на сервере'
);
assert.equal(
  normalizeTags(['x'.repeat(80)])[0].length,
  60,
  'длина одного тега ограничена шестьюдесятью, как на сервере'
);

// Потолок YouTube на ВЕСЬ список — 500 символов (аудит этапа 136).
// Без него поле показывало бы человеку список, который YouTube потом
// отвергнет целиком: узнавать о потолке из проваленной публикации —
// худший из способов.
{
  const long = Array.from(
    { length: 30 },
    (_, i) => String(i).padStart(2, '0') + 'x'.repeat(58)
  );
  const out = normalizeTags(long);
  assert.ok(out.length < 30, 'список обрывается раньше тридцати штук');
  assert.ok(
    out.join('').length <= 500,
    'суммарная длина не выходит за потолок YouTube'
  );
  assert.deepEqual(
    out,
    long.slice(0, out.length),
    'берём с начала, пока влезает: выборочно выпавшую середину человек в поле не объяснит'
  );
  const spaced = Array.from(
    { length: 30 },
    (_, i) => String(i).padStart(2, '0') + ' ' + 'y'.repeat(47)
  );
  assert.ok(
    normalizeTags(spaced).reduce((n, t) => n + t.length + 2, 0) <= 500,
    'тег с пробелом стоит дороже на кавычки, которые YouTube вокруг него ставит'
  );
}

// Поле ввода и обратно.
assert.equal(tagsToInput(['бег', 'shoes']), 'бег, shoes');
assert.deepEqual(
  tagsFromInput('бег,  shoes\nrun , '),
  ['бег', 'shoes', 'run'],
  'запятая и перевод строки разделяют, пустые части отбрасываются'
);
assert.deepEqual(
  tagsFromInput(''),
  [],
  'пустое поле — пустой список, а не список из одной пустой строки'
);

console.log('publish-tags: ok');
