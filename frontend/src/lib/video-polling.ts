/**
 * Когда опрос статуса ролика можно прекращать (§15.4/§16.1, этап 37).
 *
 * Вынесено из `useWorkflow` отдельным модулем ровно потому, что здесь и
 * была ошибка: опрос гасился на `status === 'complete'`, то есть в ту
 * секунду, когда задача постобработки только создана. Обрезка и озвучка
 * оплачивались, готовый файл ложился в Blob и до пользователя не
 * доходил никогда — при том, что интерфейс обещал «ссылка обновится
 * сама».
 *
 * Правило одно и его стоит проговорить: **опрос ведёт два процесса, а не
 * один**. Рендер у Veo и следующая за ним постобработка — разные
 * операции с разными состояниями, и каждая имеет право продлить опрос.
 */

/**
 * Только те поля, от которых зависит решение.
 *
 * `null` наравне с `undefined` намеренно: строка списка постпрода
 * (`PostprodVideoSummary`) приходит с `postStatus: null` у роликов, у
 * которых постобработки не было вовсе, а состояние ролика из мастера —
 * с `undefined`. Это одно и то же «неизвестно/нечего ждать», и
 * приводить одно к другому в месте вызова значило бы разложить
 * знание об этом по экранам.
 */
export interface PollableVideo {
  status?: 'pending' | 'processing' | 'complete' | 'failed' | null;
  postStatus?: 'pending' | 'complete' | 'failed' | 'skipped' | null;
}

/** Ролик снят и его уже можно показывать — не дожидаясь постобработки. */
export function isVideoReady(video: PollableVideo | null | undefined): boolean {
  return video?.status === 'complete';
}

/** Постобработка идёт: ссылка на ролик ещё сменится. */
export function isPostProductionPending(
  video: PollableVideo | null | undefined
): boolean {
  return video?.postStatus === 'pending';
}

/**
 * Опрашивать дальше?
 *
 * Провал рендера — конец: постобработке нечего обрабатывать. Готовый
 * ролик сам по себе концом НЕ является: если постобработка идёт, ссылка
 * ещё сменится, и прекратить опрос значит выбросить оплаченный результат.
 */
export function shouldKeepPolling(
  video: PollableVideo | null | undefined
): boolean {
  if (!video) return true;
  if (video.status === 'failed') return false;
  if (video.status !== 'complete') return true;
  return isPostProductionPending(video);
}

/**
 * Обновить статусы уже показанных строк списка постпрода свежими
 * данными, НЕ трогая состав и порядок списка.
 *
 * Почему именно так, а не «перезагрузить список». Список
 * `createdAt DESC` и подгружается страницами со смещением, равным
 * числу реально показанных строк (см. доккомментарий `loadMore` в
 * `PostprodScreen`): ролик, доснявшийся, пока вкладка открыта, встал
 * бы новой первой строкой и сдвинул все остальные вниз — следующее
 * «Показать ещё» вернуло бы дубликат. Поэтому фоновое обновление
 * только ОСВЕЖАЕТ то, что человек уже видит, а новые ролики
 * появляются при обычной перезагрузке экрана. Это осознанный
 * компромисс: чинить бейдж «Обрабатывается» ценой поехавшей
 * пагинации — плохая сделка.
 */
export function mergeVideoStatuses<T extends { sessionId: string }>(
  shown: readonly T[],
  fresh: readonly T[]
): T[] {
  if (fresh.length === 0) return [...shown];
  const bySession = new Map(fresh.map((v) => [v.sessionId, v]));
  let changed = false;
  const merged = shown.map((item) => {
    const next = bySession.get(item.sessionId);
    if (!next || next === item) return item;
    changed = true;
    return next;
  });
  // Ссылка не меняется, если ничего не поменялось: лишний рендер
  // списка на каждом тике опроса — это дёрганье экрана на ровном месте.
  return changed ? merged : [...shown];
}

/** Что показывать на экране одного ролика. */
export type PostprodViewState = 'loading' | 'error' | 'empty' | 'ready';

/**
 * Решение «спиннер / ошибка / пусто / ролик» одним правилом.
 *
 * Заведено по находке 27.09.2026: на экране промигивало «Ролик не
 * найден». Причина не в данных — сервер 404 не отдавал ни разу. Дело в
 * порядке: `setLoading(true)` живёт ВНУТРИ эффекта, то есть случается
 * уже после первого рендера с новым `sessionId`. Один кадр рисуется со
 * старым `loading: false` и ещё не загруженной сессией — и попадает в
 * ветку «не найден». Пользователь видит вспышку «ролика нет» там, где
 * ролик есть.
 *
 * Лечится не таймингом, а признаком: экран знает, для КАКОЙ сессии у
 * него данные. Пока загруженный идентификатор не совпал с
 * запрошенным, показывать нечего, и это «ещё грузим», а не «пусто».
 *
 * Отдельная чистая функция, а не `if` в компоненте, ровно потому, что
 * ошибка была в порядке ветвлений: такое проверяется тестом только
 * если его есть на чём запустить.
 */
export function postprodViewState(input: {
  loading: boolean;
  error: unknown;
  /** Идентификатор, который экран показывает сейчас. */
  requestedId: string;
  /** Идентификатор, для которого данные реально загружены. */
  loadedId: string | null;
  /** Есть ли у загруженного ролика файл. */
  hasVideo: boolean;
}): PostprodViewState {
  if (input.loading) return 'loading';
  // Ошибка важнее «ещё не загрузили»: она относится к запрошенной
  // сессии и её надо показать, а не крутить спиннер вечно.
  if (input.error) return 'error';
  if (input.loadedId !== input.requestedId) return 'loading';
  return input.hasVideo ? 'ready' : 'empty';
}
