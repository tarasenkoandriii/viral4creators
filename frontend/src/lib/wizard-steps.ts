/**
 * Общий контракт шагов мастера — «Тонкая красная линия», этап 1
 * (docs-tz/TZ-Tonkaya-Krasnaya-Liniya.md §4.3).
 *
 * До этого контракт был ровно у одного мастера — товарки
 * (`stepTargets` в `hooks/useWorkflow.ts`): массив по индексам
 * степпера, где `null` означает «сюда нельзя». Форма хорошая, но жила
 * внутри одного хука, и обучалка с greeting получали бы её копией.
 *
 * ## Почему `currentId` может быть `null`
 *
 * Самый тонкий случай во всём модуле. У линейного мастера есть
 * состояние ПОСЛЕ последнего шага: ролик готов, делать больше нечего.
 * Сегодня товарка выражает его индексом `5` при пяти подписях
 * (`GenerationWizard.getStepIndex()`), то есть выходом за границу
 * массива — и `Stepper` рисует все шаги пройденными «случайно
 * правильно».
 *
 * Простой кламп в `[0, length - 1]` это состояние потерял бы: последний
 * шаг стал бы текущим вместо завершённого, и галочка с него исчезла бы.
 * Поэтому «всё пройдено» выражается явно — `currentId: null` даёт
 * `current === steps.length`. Кламп остаётся, но только для значений,
 * которых не должно быть вовсе.
 *
 * ## Почему `done` необязателен
 *
 * У линейного мастера позиционная завершённость (`i < current`) —
 * правда, и `Stepper` считает её сам. У greeting неправда: голос,
 * музыка, карточки заполняются в любом порядке. Поэтому шаг МОЖЕТ
 * объявить завершённость явно; если этого не сделал ни один, наружу
 * `done` не уходит вовсе, и `Stepper` остаётся при своём прежнем
 * поведении. Так товарка переезжает на общий контракт, не меняя ни
 * пикселя.
 *
 * ## Чего хелпер НЕ проверяет
 *
 * Уникальности идентификаторов. Два шага с одним `id` сделали бы второй
 * недостижимым (`findIndex` вернёт первый), и молча. Проверять это в
 * рантайме браузерного кода нечем — падать на рендере из-за опечатки в
 * списке шагов хуже самой опечатки, — поэтому уникальность закрыта
 * тестом на КАЖДЫЙ конкретный список шагов
 * (`scripts/wizard-steps.test.ts`), а не защитой внутри функции.
 */

export interface WizardStep<S extends string> {
  id: S;
  /** Готовая подпись из словаря — хелпер в словарь не ходит. */
  label: string;
  /** `null` — перейти нельзя; иначе — на какой шаг ведёт клик. */
  target: S | null;
  /**
   * Завершённость ПО СМЫСЛУ. Не задана ни у одного шага — считается
   * позиционно, силами `Stepper`.
   */
  done?: boolean;
}

export interface WizardStepsView<S extends string = string> {
  steps: string[];
  current: number;
  selectable: boolean[];
  /**
   * Куда ведёт клик по каждому шагу; `null` — никуда.
   *
   * Отдаётся наружу, а не схлопывается в `selectable`, потому что
   * навигация у мастеров разная: товарка ходит по индексу
   * (`goToStep(index)`), а обучалка и greeting будут ходить по адресу,
   * и им нужен именно ИДЕНТИФИКАТОР шага. Без этого поля каждый из них
   * заново выводил бы его из своего же списка — то есть держал бы
   * вторую копию правила «куда можно».
   */
  targets: Array<S | null>;
  /** `undefined` — завершённость считает `Stepper` позиционно. */
  done?: boolean[];
}

export function toStepsView<S extends string>(
  steps: readonly WizardStep<S>[],
  /** `null` — все шаги пройдены (см. шапку файла). */
  currentId: S | null
): WizardStepsView<S> {
  const found =
    currentId === null
      ? steps.length
      : steps.findIndex((s) => s.id === currentId);
  // Неизвестный идентификатор — это ошибка вызывающего, и молча
  // выходить за границы массива из-за неё нельзя: там начинается
  // «случайно правильное» поведение, которое однажды перестанет быть
  // правильным. Ведём себя как прежний `default: return 0`.
  const current = found < 0 ? 0 : Math.min(found, steps.length);

  const declaresDone = steps.some((s) => s.done !== undefined);
  return {
    steps: steps.map((s) => s.label),
    current,
    selectable: steps.map((s) => s.target !== null),
    targets: steps.map((s) => s.target),
    done: declaresDone ? steps.map((s, i) => s.done ?? i < current) : undefined,
  };
}
