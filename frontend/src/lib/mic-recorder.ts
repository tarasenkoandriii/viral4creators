/**
 * Отпустить микрофон (этап 119, В-5.17).
 *
 * Запись голоса живёт на двух разных экранах («Описание голосом» в
 * карточке товара и клонирование голоса в манифесте бренда), и на обоих
 * поток микрофона получали локальной переменной внутри `start()`:
 * добраться до его дорожек можно было ровно из одного места —
 * обработчика `onstop`, то есть только нажав «Стоп». Уход с экрана,
 * переход по степперу, вкладка внизу, «Отмена» рядом с «Стоп» — всё это
 * снимало компонент, но не запись: `MediaRecorder` продолжал работать
 * в никуда, а индикатор микрофона горел до конца сессии.
 *
 * Две тонкости, ради которых это отдельная функция с тестом. Первая:
 * обработчики снимаются ДО `stop()`, иначе `onstop` доживёт до вызова и
 * уедет доделывать работу снятого экрана. Вторая: запись, которую
 * человек уже остановил кнопкой «Стоп», не трогаем вовсе — её события
 * приходят асинхронно, и отмена в этом окне отняла бы у человека
 * законченную им запись.
 */

/** `MediaRecorder` в той части, которая нужна для остановки. */
export interface StoppableRecorder {
  state: string;
  onstop: unknown;
  ondataavailable: unknown;
  stop(): void;
}

/** `MediaStream` в той же минимальной части. */
export interface StoppableStream {
  getTracks(): Array<{ stop(): void }>;
}

/**
 * @returns `true`, если запись была ПРЕРВАНА этим вызовом, и `false`,
 * если прерывать было нечего: записи нет или её уже остановил человек
 * кнопкой «Стоп». Разница не косметическая — см. ниже.
 */
export function releaseMicrophone(
  recorder: StoppableRecorder | null | undefined,
  stream: StoppableStream | null | undefined
): boolean {
  // Запись, уже остановленную человеком, не трогаем: `stop()` у
  // `MediaRecorder` доставляет `dataavailable` и `onstop` АСИНХРОННО, и
  // между «Стоп» и этими событиями есть окно в десятки миллисекунд. Уход
  // с экрана в это окно не должен отменять расшифровку: человек свою
  // запись закончил и ждёт, что она сохранится (так это и работало до
  // появления уборки). Дорожки при этом всё равно останавливаем ниже —
  // микрофон держат они, а не `MediaRecorder`.
  const interrupted = !!recorder && recorder.state !== 'inactive';
  if (interrupted && recorder) {
    // Порядок важен: сначала снять обработчики, потом остановить. Иначе
    // `onstop` доживёт до вызова и уедет доделывать работу снятого
    // экрана — расшифровывать обрывок и писать результат в состояние,
    // которого больше нет.
    recorder.onstop = null;
    recorder.ondataavailable = null;
    recorder.stop();
  }
  // Дорожки трогаем только там, где их больше некому остановить. У
  // записи, которую человек завершил сам, дорожки останавливает её
  // собственный `onstop` — а обрывать их посреди доставки последнего
  // куска значило бы рискнуть самой записью ради секунды.
  if (interrupted || !recorder) {
    stream?.getTracks().forEach((track) => track.stop());
  }
  return interrupted;
}
