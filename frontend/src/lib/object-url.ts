/**
 * Отзыв `blob:`-ссылок (этап 119, хвост В-5.18…В-5.23).
 *
 * `URL.createObjectURL(file)` держит сам файл в памяти вкладки до
 * `revokeObjectURL` или до закрытия вкладки — сборщик мусора такую
 * ссылку не трогает, потому что живой её считает документ, а не
 * JavaScript. В мастере это фотографии товара до 10 МБ, и каждая
 * переснятая карточка оставляла ещё одну копию навсегда.
 *
 * Проверка на `blob:` — не перестраховка: в тех же полях лежат и ОБЫЧНЫЕ
 * ссылки (фото товара с сервера, восстановленный снимок сессии), а
 * `revokeObjectURL` от чужого адреса молча ничего не сделает — и это
 * хуже, чем шумная ошибка, потому что прячет опечатку в логике.
 */
export function revokeObjectUrl(url: string | null | undefined): void {
  if (typeof url === 'string' && url.startsWith('blob:')) {
    URL.revokeObjectURL(url);
  }
}
