/**
 * Открыватель справки — контекстом, а не пропом.
 *
 * Карточек мастера девять, и они вложены на разную глубину;
 * протаскивать колбэк через девять компонентов значило бы девять мест,
 * где его забудут передать новой карточке, — а забытый проп выглядит
 * как «у этой карточки просто нет кнопки», то есть молчит.
 *
 * Тем же хуком воспользуется голосовое управление (§4А.7.3 ТЗ
 * поздравления): «помощь» открывает тот же лист.
 *
 * Отдельным файлом от `HelpSheet.tsx` не по вкусу: в файле компонентов
 * не должно быть экспортов, кроме компонентов, иначе ломается
 * горячая перезагрузка (правило `react-refresh/only-export-components`).
 */

import { createContext, useContext } from 'react';

export const HelpContext = createContext<((topic: string) => void) | null>(
  null
);

export function useHelp(): ((topic: string) => void) | null {
  return useContext(HelpContext);
}
