/**
 * Деньги в админке (ТЗ §26).
 *
 * Бэкенд считает и хранит суммы в МИКРОДОЛЛАРАХ целым числом — сложение
 * float-долларов по десяткам тысяч строк даёт дрейф, а сумма расходов
 * это как раз та цифра, которой обязаны верить. В доллары пересчитываем
 * здесь, один раз, на готовой сумме.
 */

const USD = 1_000_000;

/**
 * «$12.34» для заметных сумм и «$0.0042» для мелких. Округлять расход
 * одного вызова до центов бессмысленно: почти все они дешевле цента, и
 * колонка превратилась бы в столбик нулей.
 */
export function usd(micro: number): string {
  const value = micro / USD;
  if (value === 0) return '$0';
  if (Math.abs(value) < 0.01) return `$${value.toFixed(4)}`;
  if (Math.abs(value) < 1000) return `$${value.toFixed(2)}`;
  return `$${value.toLocaleString('en-US', { maximumFractionDigits: 0 })}`;
}

/**
 * «12 345 симв.» — объём синтеза речи рядом с деньгами (этап F ТЗ
 * docs-tz/TZ-Tutorial-Video-Voiced.md). У TTS счёт идёт за символы, и
 * без них строка озвучки отвечает «сколько заплатили», но не «за
 * сколько текста». Пустая строка при нуле: у всего, что не синтез,
 * «0 симв.» было бы шумом в каждой строке таблицы.
 */
export function chars(count: number): string {
  if (!count) return '';
  return `${count.toLocaleString('ru-RU')} симв.`;
}

/** Доля в процентах — для полосок в разбивке. */
export function share(part: number, total: number): number {
  if (total <= 0) return 0;
  return Math.round((part / total) * 100);
}

/**
 * Человеческое название операции.
 *
 * Словарь приезжает С ОТЧЁТОМ (`CostReport.operationLabels`), а не
 * лежит здесь копией `AI_OPERATION_LABEL`. Копия здесь была: из сорока
 * операций в ней жило тринадцать, а остальные рисовались сырым ключом
 * — молча, потому что `?? key` выглядит как подпись. Новая операция
 * сборки обучающего видео так и показалась бы ключом (находка
 * повторного сквозного аудита A+B+C).
 *
 * `?? key` остаётся, но теперь это честный запасной ход на случай
 * строки из прайса старее текущего кода, а не половина словаря.
 */
export function operationLabel(
  key: string,
  // Обязательный, без умолчания. С `= {}` вызов без словаря выглядел
  // законным и молча рисовал сырой ключ: так карточка пользователя
  // показывала ключи вместо подписей у ВСЕХ операций с тех пор, как
  // копию словаря отсюда убрали (найдено аудитом этапа F). Та же
  // ловушка, что снята у третьего параметра `slideshowContentHash`.
  labels: Record<string, string>,
): string {
  return labels[key] ?? key;
}
