import { GREETING_OCCASION_SPECS } from '../../common/greeting-occasions';
import { GreetingOccasion, GreetingTone } from '../../common/types/greeting.types';

/**
 * Варианты визуального сеттинга для референс-кадра — фича №36
 * компаньон-ТЗ, прямое продолжение №6.
 *
 * ## Зачем, если сцена у повода уже есть
 *
 * Есть, но одна на всех: `sceneMood` в каталоге поводов принимает ровно
 * два значения — праздничное и сдержанное. То есть кадр к дню рождения,
 * свадьбе, новоселью и повышению описывается СЛОВО В СЛОВО одинаково, и
 * двадцать поводов дают одну и ту же картинку с разным поздравлением
 * поверх. Для страницы, которая обещает «персональное видео», это
 * ощутимо.
 *
 * Поэтому здесь просят модель предложить три РАЗНЫХ сеттинга под
 * конкретный повод и тон, и человек выбирает. Вызов текстовый и
 * дешёвый; дорогой шаг (картинка) остаётся один, как и был.
 *
 * ## Почему парсер такой недоверчивый
 *
 * Модель просят вернуть три строки. Она вернёт три строки в
 * большинстве случаев — и иногда вернёт четыре, пронумерует их,
 * обернёт в markdown-список или добавит вступление «Вот три варианта:».
 * Всё это нормальное поведение, а не сбой, и ловить его исключением
 * значило бы ронять фичу из-за косметики. Парсер вытаскивает, что
 * сможет, и если не смог — вызывающий откатывается на сеттинг из
 * каталога, то есть на поведение до этой фичи.
 */

/** Потолок длины одного варианта — он уходит в промпт картинки. */
export const MAX_SETTING_LENGTH = 160;

export function buildSettingsPrompt(
  occasion: GreetingOccasion,
  customOccasionText: string | null,
  tone: GreetingTone,
): string {
  const spec = GREETING_OCCASION_SPECS[occasion];
  const occasionText =
    occasion === 'OTHER' && customOccasionText?.trim()
      ? customOccasionText.trim()
      : spec.label;
  return [
    'Предложи ТРИ разных варианта визуального сеттинга для одного кадра',
    'видео-поздравления. Кадр статичный, в нём один человек, который',
    'обращается к зрителю.',
    `Повод: ${occasionText}.`,
    `Настроение: ${spec.festive ? 'праздничное' : 'сдержанное, без праздничной атрибутики'}.`,
    `Тон обращения: ${tone}.`,
    '',
    'Требования к ответу:',
    '— ровно три строки, по одному варианту в строке;',
    '— каждая строка — короткое описание ОБСТАНОВКИ на английском языке',
    `  (до ${MAX_SETTING_LENGTH} символов): место, свет, детали фона;`,
    '— варианты должны заметно отличаться друг от друга, а не быть',
    '  перефразировкой одного;',
    '— без нумерации, без маркеров списка, без кавычек, без пояснений;',
    '— не упоминай текст, надписи, логотипы и реальных людей.',
    spec.festive
      ? ''
      : '— никаких шаров, конфетти, тортов и подарков: это не праздник.',
  ]
    .filter(Boolean)
    .join('\n');
}

/**
 * Разобрать ответ модели в три варианта.
 *
 * Чистит нумерацию и маркеры, отбрасывает вступления (строки с
 * двоеточием на конце и без содержания), режет по длине и отдаёт не
 * больше трёх. Меньше трёх — тоже результат: два варианта лучше, чем
 * откат к одному общему.
 */
export function parseSettings(raw: string | null | undefined): string[] {
  const lines = (raw ?? '')
    .split('\n')
    .map((l) =>
      l
        .trim()
        // «1.», «1)», «- », «• », «— » в начале строки — оформление,
        // которого просили не делать, но которое приходит.
        .replace(/^[\s>*•—–-]*\d*[.)]?\s*/, '')
        .replace(/^["'«]|["'»]$/g, '')
        .trim(),
    )
    .filter((l) => l.length > 0);

  const out: string[] = [];
  for (const line of lines) {
    // Вступление вида «Вот три варианта:» — заканчивается двоеточием и
    // не описывает сцену.
    if (line.endsWith(':')) continue;
    // Слишком короткая строка — не описание обстановки, а обрывок.
    if (line.length < 12) continue;
    out.push(line.slice(0, MAX_SETTING_LENGTH).trim());
    if (out.length === 3) break;
  }
  return out;
}
