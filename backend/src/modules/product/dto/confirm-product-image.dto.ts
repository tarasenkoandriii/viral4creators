import { IsString, MaxLength, MinLength } from 'class-validator';

/**
 * Подтверждение загрузки фото товара (В-1.8 третьего аудита, этап 123).
 *
 * До этого этапа путь к фото записывался в сессию в момент ВЫДАЧИ
 * presigned-ссылки, то есть до самой загрузки. Сорвавшийся PUT (сеть в
 * метро, закрытая вкладка) оставлял сессию с путём, по которому ничего
 * не лежит: мастер при восстановлении показывал фото загруженным на
 * 100 %, а генерация упиралась в техническую ошибку скачивания. Денег
 * это не стоило, но выглядело как поломка — и непонятно было, что
 * делать.
 *
 * Тот же приём подтверждения уже используется в проекте для фото товара
 * в карточке и для кадров-превью: путь записывается только после того,
 * как файл реально нашёлся в хранилище.
 */
export class ConfirmProductImageRequestDto {
  /** Путь, который вернула выдача ссылки. Проверяется на принадлежность
   * этой сессии — иначе чужую сессию можно было бы заставить показывать
   * чужой файл. */
  @IsString()
  @MinLength(1)
  @MaxLength(512)
  pathname!: string;
}
