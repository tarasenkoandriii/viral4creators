/**
 * Кадры предпросмотра черновика: путь в Blob и разбор `data:`-URL —
 * §5.2 (`/finish`), §6.3 ТЗ (doc/CLIENT-SITE-TUTORIAL-SPEC.md), этап 113.
 *
 * ## Почему отдельный файл на три функции
 *
 * Обе задачи — сборка пути и разбор data-URL — ошибочны ровно один раз
 * и потом молча: путь, разошедшийся между `/finish`, `DELETE` и
 * админкой, оставляет файлы в Blob навсегда (§15 п.4 аудита ТЗ — ровно
 * эта находка), а неверный разбор data-URL кладёт в Blob «файл»,
 * который открывается как мусор, и видно это станет только на готовом
 * ролике. Ни то ни другое не требует ни БД, ни сети, значит должно
 * проверяться тестами без них.
 *
 * ## Почему путь ключуется `draftId`, а не `scenarioId`
 *
 * §5.2 ТЗ: у этого вида проекта нет строки `TutorialScenario` вообще.
 * Паттерн пути тот же, что у штатной обучалки
 * (`tutorial-video-frames/{owner}/{n}.jpg`), владелец другой — и это
 * сознательно: дальше по конвейеру оба вида кадров собирает один и тот
 * же внешний ffmpeg-api одной и той же командой.
 */

import { randomBytes } from 'crypto';

/** Общий префикс всех кадров одного черновика. Именно ПРЕФИКС, а не
 * список файлов: `/finish` обязан стереть то, что лежало здесь раньше,
 * включая «хвост» от прошлого, более длинного прогона (§15 п.4).
 *
 * Это КОРЕНЬ черновика: под ним лежат и старые кадры (до Ш0.6 — прямо
 * в нём), и новые (в подпапке-ключе, `draftFrameDir`). Листинг и
 * стирание по корню уносят обе раскладки разом; метла сирот
 * (`common/orphan-sweep.ts`) по-прежнему видит владельца первым
 * сегментом пути. */
export function draftFramePrefix(draftId: string): string {
  return `tutorial-video-frames/${draftId}/`;
}

/**
 * Случайный ключ папки кадров черновика (Ш0.6, риск В-2 аудита
 * docs-tz/AUDIT-Merge-Assistant-Tutorial-QA-2026-10-02.md).
 *
 * Кадры — снимки АВТОРИЗОВАННОГО кабинета заказчика (там бывают
 * персональные данные его клиентов), а Blob у проекта публичный:
 * файл открывается любым, кто знает адрес. До Ш0.6 адрес собирался из
 * `draftId` и номера кадра — то есть подбирался. 144 бита случайности
 * в пути делают его неугадываемым; листинга у публичного Blob нет.
 *
 * Свой ключ, а не `addRandomSuffix` хранилища: кадры читаются по
 * ПОСТРОЕННОМУ пути (`uploadFrames` копирует `round-N` в `N`, админка
 * сортирует по номеру), и случайный хвост у каждого файла сломал бы
 * ровно эти места. Один ключ на черновик — путь по-прежнему строится,
 * но только тем, кто знает ключ из строки БД.
 */
export function newFrameKey(): string {
  return randomBytes(18).toString('base64url');
}

/** Папка, куда пишутся кадры черновика: `{корень}{ключ}/`, а у
 * черновиков до Ш0.6 (`frameKey` пуст) — сам корень, как раньше: их
 * съёмочные кадры уже лежат там, и `uploadFrames` должен их найти. */
export function draftFrameDir(
  draftId: string,
  frameKey: string | null,
): string {
  return frameKey
    ? `${draftFramePrefix(draftId)}${frameKey}/`
    : draftFramePrefix(draftId);
}

/**
 * Расширение файла по типу его содержимого.
 *
 * Имя в хранилище обязано совпадать с байтами внутри. До 29.09.2026 оба
 * пути ниже были зашиты на `.jpg`, и это было верно ровно до того дня,
 * когда съёмочный кадр стал PNG: `.jpg` с PNG внутри открывается не
 * везде, а разбирать такую находку через полгода пришлось бы по
 * содержимому файла, а не по его имени.
 *
 * Список закрытый, с внятным отказом: `image/svg+xml` или `image/gif`
 * здесь не появляются ни при каких условиях (кадр снимает браузер), и
 * молча превратить неизвестный тип в `.bin` значило бы завести файл,
 * которого не ждёт ни сборка, ни админка.
 */
export function frameExtension(contentType: string): string {
  switch (contentType.toLowerCase()) {
    case 'image/png':
      return 'png';
    case 'image/jpeg':
      return 'jpg';
    case 'image/webp':
      return 'webp';
    default:
      throw new FrameDecodeError(
        `кадр в формате ${contentType} не кладётся в хранилище: браузер снимает только png, jpeg и webp`,
      );
  }
}

/**
 * Путь ИТОГОВОГО кадра ролика. Расширение — по типу содержимого, а не
 * по привычке: кадр приезжает либо из съёмочного (PNG), либо из
 * предпросмотра (JPEG), и эти два случая различаются именно им.
 */
export function draftFramePathname(
  draftId: string,
  index: number,
  contentType: string,
  frameKey: string | null = null,
): string {
  return `${draftFrameDir(draftId, frameKey)}${index}.${frameExtension(contentType)}`;
}

/**
 * Путь СЪЁМОЧНОГО кадра раунда (вариант А, 29.09.2026).
 *
 * Отдельное имя файла, а не `{n}.jpg`: под этим же префиксом
 * `/finish` раскладывает итоговые кадры ролика, и совпадение имён
 * означало бы, что незавершённый черновик уже выглядит завершённым —
 * а `previewFrameCount` ещё не выставлен, и админка считала бы кадры
 * по другому правилу, чем они лежат.
 *
 * Тот же префикс — намеренно: уборка черновика (`DELETE`, каскад
 * проекта) стирает его целиком и уносит обе разновидности разом, без
 * отдельного списка путей, который однажды отстал бы. А `/finish` —
 * НЕ целиком, только итоговые (`finalFrameIndex`): съёмочные кадры ему
 * ещё копировать (01.10.2026, см. там же).
 */
export function draftRoundFramePathname(
  draftId: string,
  index: number,
  contentType: string = VIDEO_FRAME_CONTENT_TYPE,
  frameKey: string | null = null,
): string {
  return `${draftFrameDir(draftId, frameKey)}round-${index}.${frameExtension(contentType)}`;
}

/**
 * Тип съёмочного кадра — PNG (29.09.2026, §11-седециес ТЗ).
 *
 * Замер на живых страницах: на форме — той самой, из которой состоит
 * личный кабинет заказчика, — PNG в плотности съёмки весит 58.7 КБ
 * против 63.2 у прежнего JPEG q80, то есть ДЕШЕВЛЕ, и при этом не мылит
 * буквы; на фото-странице PNG дороже втрое, но съёмочный кадр едет в
 * Blob, где вес не так дорог (это и записано у `VIDEO_FRAME_QUALITY`,
 * пока он был). Решающее — третье: `computeDHash` читает только PNG, и
 * пока кадр был JPEG, сверить его было нечем и не с чем. Кадры мастера
 * (`tutorial-video-frames/{assetId}/{шаг}.png`) и так PNG — здесь
 * убирается исключение, а не заводится новое.
 *
 * Предпросмотровый кадр остаётся JPEG: он едет в JSON-ответ и в
 * `jsonb`-колонку, а там PNG фото-страницы стоит 110 КБ вместо 27.
 */
export const VIDEO_FRAME_CONTENT_TYPE = 'image/png';

export class FrameDecodeError extends Error {}

/**
 * Разбирает `data:image/jpeg;base64,…` в байты.
 *
 * Строгий разбор, а не «отрезать всё до запятой»: содержимое приходит
 * из колонки БД, которую мог записать более старый код, и класть в Blob
 * неизвестно что под именем `.jpg` нельзя. Не-base64 и не-изображения
 * отклоняются с внятной ошибкой, а не превращаются в битый файл.
 */
export function decodeFrameDataUrl(dataUrl: string): {
  buffer: Buffer;
  contentType: string;
} {
  const match = /^data:(image\/[a-z0-9.+-]+);base64,([A-Za-z0-9+/=\s]*)$/i.exec(
    dataUrl ?? '',
  );
  if (!match) {
    throw new FrameDecodeError(
      'кадр предпросмотра не похож на data:image/...;base64 — залить его в хранилище нельзя',
    );
  }
  const buffer = Buffer.from(match[2], 'base64');
  if (buffer.length === 0) {
    throw new FrameDecodeError('кадр предпросмотра пуст');
  }
  return { buffer, contentType: match[1].toLowerCase() };
}

/**
 * Итоговые кадры черновика — по СПИСКУ файлов хранилища, а не по имени,
 * собранному из номера (29.09.2026).
 *
 * До этой правки расширение было одно на всех (`.jpg`), и админка
 * спокойно строила путь из счётчика в строке. Теперь расширение следует
 * за содержимым кадра: съёмочный кадр PNG, предпросмотровый JPEG, и у
 * одного черновика бывают оба. Угадать имя по номеру больше нельзя.
 *
 * Заодно уходит то, на что админка и так жаловалась в комментарии:
 * счётчик в строке мог разойтись с хранилищем после оборвавшегося
 * `/finish`, и путь строился на кадр, которого нет. Список знает правду.
 *
 * `round-*` под тем же префиксом — кадры РАУНДОВ, а не ролика
 * (`draftRoundFramePathname`). Они сюда не попадают: иначе незавершённый
 * черновик показывал бы оператору вдвое больше кадров, чем в ролике.
 */
export function orderedFramePathnames(
  draftId: string,
  pathnames: readonly string[],
): string[] {
  const numbered: Array<{ index: number; pathname: string }> = [];
  for (const pathname of pathnames) {
    const index = finalFrameIndex(draftId, pathname);
    if (index === null) continue;
    numbered.push({ index, pathname });
  }
  // По числу, а не по строке: иначе десятый кадр встал бы перед вторым.
  numbered.sort((a, b) => a.index - b.index);
  return numbered.map((n) => n.pathname);
}

/**
 * Номер ИТОГОВОГО кадра ролика по пути в хранилище, или `null`, если
 * это не итоговый кадр этого черновика (01.10.2026).
 *
 * Один фильтр на двух потребителей — админку (`orderedFramePathnames`)
 * и уборку перед `/finish` (`wipeFinalFrames` в сервисе) — и это не
 * вкус. До этой правки `/finish` стирал ВЕСЬ префикс, включая
 * съёмочные `round-N.png`, и следом копировал их в итоговые кадры из
 * уже удалённого: `copyBlob` отдавал `null`, ролик молча лишался
 * кадров, а одобрение падало на пустом слайд-шоу. Два независимых
 * определения «что есть итоговый кадр» однажды разошлись бы ровно так
 * же — поэтому определение одно.
 */
export function finalFrameIndex(
  draftId: string,
  pathname: string,
): number | null {
  const prefix = draftFramePrefix(draftId);
  if (!pathname.startsWith(prefix)) return null;
  // Номер и расширение, и ничего между ними: `12.png` — кадр,
  // `round-12.png` — не кадр, `12.thumb.png` — тоже не кадр. Перед
  // номером — необязательная папка-ключ (Ш0.6, `newFrameKey`): у
  // черновиков до неё кадры лежат прямо в корне.
  const m = /^(?:[A-Za-z0-9_-]{16,}\/)?(\d+)\.[a-z0-9]+$/i.exec(
    pathname.slice(prefix.length),
  );
  return m ? Number(m[1]) : null;
}
