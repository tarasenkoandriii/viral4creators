/**
 * Текстовый стоп-лист §8.3 ТЗ (doc/CLIENT-SITE-TUTORIAL-SPEC.md), этап 112.
 *
 * ## Что он делает и чего НЕ делает
 *
 * Визард нажимает кнопки на НАСТОЯЩЕМ сайте заказчика. Кнопка
 * «Оформить заказ» оформит настоящий заказ, «Удалить» — удалит. ТЗ
 * решает это не запретом («а мне и нужно показать процесс оплаты как
 * часть обучалки» — законный сценарий), а предупреждением: человек
 * должен увидеть «вы уверены?» ДО того, как шаг выполнится.
 *
 * ## Почему предупреждение живёт на ЭЛЕМЕНТЕ, а не только на раунде
 *
 * ТЗ описывает `PageExploration.dangerWarning`, то есть поле ответа на
 * уже выполненный `/step`. Само по себе это предупреждение опаздывает:
 * заказ к тому моменту оформлен. Но список кнопок с их видимым текстом
 * визард отдаёт клиенту РАУНДОМ РАНЬШЕ — в `elements[]` предыдущего
 * ответа. Поэтому метка ставится в первую очередь там
 * (`PageElement.danger`): фронтенд показывает «вы уверены?» в момент
 * ВЫБОРА кнопки, до отправки запроса, не тратя ни раунда лимита, ни
 * запуска Chromium на вопрос. `dangerWarning` на раунде остаётся и
 * заполняется по факту нажатия — он нужен не для вопроса, а для
 * оператора при модерации (§8.3: «видео с этим шагом не должно молча
 * уйти в публикацию»).
 *
 * Сервер при этом НИЧЕГО не блокирует — ровно как требует ТЗ.
 *
 * ## Почему это код, а не просьба к модели
 *
 * Тот же довод, что у фильтра `video`-действий консультанта
 * (`assistant/actions.ts`, этап 99): проверяемое кодом правило не
 * зависит от того, что сегодня ответила модель. Здесь модели нет вовсе —
 * текст кнопки приходит из DOM чужого сайта.
 */

/**
 * Слова и фразы, после которых на чужом сайте обычно происходит
 * необратимое. Три языка — те же, на которых говорят пользователи
 * продукта (§35), плюс английский как язык большинства шаблонных тем.
 *
 * Список намеренно КОРОТКИЙ и состоит из действий, а не из тревожных
 * слов вообще: каждая лишняя строка здесь — это ложное «вы уверены?» на
 * обычной кнопке, а предупреждение, которое срабатывает постоянно,
 * перестают читать.
 */
const DANGER_PATTERNS: Array<{ re: RegExp; what: string }> = [
  // `(?<!\p{L})` — совпадение только с НАЧАЛА слова. Без него
  // «Неоплаченные заказы» в меню сайта давало бы «похоже на оплату» на
  // каждом раунде, а предупреждение, которое горит всегда, перестают
  // читать — это хуже, чем его отсутствие.
  {
    re: /(?<!\p{L})(оплат|оплач|сплат|заплат|pay|payment|checkout)/iu,
    what: 'оплата',
  },
  {
    re: /(?<!\p{L})(удал|видал|вилуч|delete|remove|erase)/iu,
    what: 'удаление',
  },
  {
    re: /(?<!\p{L})(оформить заказ|подтвердить заказ|оформити замовлення|підтвердити замовлення|confirm order|place order|submit order|buy now|купить|купити)/iu,
    what: 'оформление заказа',
  },
  {
    re: /(?<!\p{L})(отправить письм|надіслати лист|send email|send message|отправить заявку|надіслати заявку|submit request)/iu,
    what: 'отправка сообщения',
  },
  {
    re: /(?<!\p{L})(отменить подписку|скасувати підписку|cancel subscription|unsubscribe)/iu,
    what: 'отмена подписки',
  },
];

/**
 * Возвращает человекочитаемое предупреждение, если видимый текст
 * элемента похож на необратимое действие, и `undefined` иначе.
 *
 * Текст берётся как есть с чужой страницы — пустой, нечитаемый или
 * километровый одинаково законны и одинаково не должны ничего ронять.
 */
export function dangerWarningFor(text: string | undefined): string | undefined {
  if (!text) return undefined;
  // Длинный текст обрезается до разумного: кнопка с абзацем внутри —
  // это не кнопка, а промах селектора, и гонять по ней пять регулярок
  // целиком незачем.
  const probe = text.slice(0, 300);
  const hits = DANGER_PATTERNS.filter((p) => p.re.test(probe)).map(
    (p) => p.what,
  );
  if (hits.length === 0) return undefined;
  const unique = [...new Set(hits)];
  return `Похоже на необратимое действие на сайте заказчика (${unique.join(', ')}). Шаг выполнится по-настоящему — убедитесь, что это тестовые данные.`;
}
