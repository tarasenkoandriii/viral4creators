/**
 * Типы «что мы увидели на странице заказчика» — §5.4 ТЗ
 * (doc/CLIENT-SITE-TUTORIAL-SPEC.md), этап 111.
 *
 * Отдельный файл с одними типами, потому что их читают три разные
 * стороны: сервис визарда, будущая браузерная реализация (этап 112) и
 * фронтенд TMA (§11), который получает ровно эту структуру ответом на
 * каждый раунд.
 */

export interface PageElement {
  /**
   * Стабильный CSS-селектор. Приоритет построения (§5.4): `#id` →
   * `[data-testid]`/`[data-test]` → `[name]` → `[aria-label]` → путь по
   * тегам с `:nth-of-type()` как последний, самый хрупкий вариант.
   * Устойчивость к вёрстке здесь важнее краткости: этот селектор
   * переживает в `draft.steps` и будет проигран заново при каждой
   * пересборке видео, возможно через недели после записи.
   */
  selector: string;
  tag: 'input' | 'select' | 'textarea' | 'button' | 'a';
  /** `input[type]` — 'text' | 'email' | 'password' | 'checkbox' | … */
  type?: string;
  /** Текст `<label for=…>`, `aria-label`, `placeholder` — в этом порядке. */
  label?: string;
  /** `innerText` для button/a — чтобы показать человеку «на какую кнопку нажать». */
  visibleText?: string;
  name?: string;
  /**
   * Атрибут `autocomplete` поля (нижним регистром): `username`, `email`,
   * `current-password`, `new-password`, … — по нему генератор сам находит
   * поля формы входа для учётки из реестра (Ш2-хвост (3),
   * `login-form-detect.ts`). Только у `input`/`textarea`.
   */
  autocomplete?: string;
  /**
   * Предупреждение стоп-листа §8.3 для ЭТОЙ кнопки («Оплатить»,
   * «Удалить»), проставленное по её видимому тексту (этап 112,
   * `danger-words.ts`). Стоит на элементе, а не только на раунде,
   * намеренно: список кнопок приходит клиенту РАУНДОМ РАНЬШЕ, чем
   * пользователь выберет одну из них, поэтому «вы уверены?» успевает
   * показаться ДО того, как шаг выполнится на настоящем сайте — не
   * тратя ни раунда лимита, ни запуска Chromium на сам вопрос.
   */
  danger?: string;
  /**
   * Варианты `<select>` — без них выпадающий список показывался бы
   * пустым текстовым полем, и человек вводил бы туда видимую надпись
   * («Москва»), а `fill` по `<select>` сопоставляет строку со
   * ЗНАЧЕНИЕМ опции. Угадать его из интерфейса невозможно (найдено
   * аудитом этапа 116, закрыто этапом 117). Только для `tag: 'select'`.
   */
  options?: Array<{ value: string; label: string }>;
  /**
   * Ш4(5)-хвост: ВСЕ уникальные кандидаты по приоритету (не только
   * выбранный `selector`) — генератор шлёт их в карту интерфейса сайта
   * (`ui-map`), и элемент узнаётся в снимках обхода/QA по любому из них.
   * Нет ни одного — поля нет.
   */
  candidates?: PageElementCandidate[];
}

/**
 * Ш4(5)-хвост: кандидат селектора элемента для общей карты интерфейса
 * сайта помощника. Вид — по приоритету §5.4: `id` → `test-id`
 * (`data-testid`/`data-test`) → `attr` (`[name]`) → `aria`
 * (`[aria-label]`, `name` — сама подпись). Каждый — ЕДИНСТВЕННЫЙ на
 * странице в момент снимка; css-путь сюда не входит (он хрупкий и уже
 * есть в `selector`, если других нет).
 */
export interface PageElementCandidate {
  kind: 'id' | 'test-id' | 'attr' | 'aria';
  selector: string;
  name?: string;
}

export interface PageExploration {
  currentUrl: string;
  /** `data:image/jpeg;base64,…` — не Blob-ссылка (§6.3 ТЗ: кадр раунда
   * живёт в строке БД вместе с шагами, иначе каждый `/undo` порождал бы
   * churn файлов в хранилище). */
  screenshotDataUrl: string;
  /**
   * Тот же кадр, снятый в съёмочном формате (вариант А, 29.09.2026) —
   * `data:image/jpeg;base64,…`, плотность `CAPTURE_DEVICE_SCALE_FACTOR`.
   *
   * Наружу, в ответ API, НЕ уходит и в строке БД не лежит: сервис
   * заливает его в Blob сразу и хранит только ссылку. Иначе правка
   * ровно того, ради чего всё затевалось — веса ответа и колонки, —
   * оказалась бы отменённой.
   *
   * Необязательный: кадр мог не сняться (мелкий сбой страницы,
   * нехватка памяти на второй снимок), и это не повод валить раунд —
   * ролик просто станет мягче на один кадр.
   */
  videoFrameDataUrl?: string;
  elements: PageElement[];
  /** Эвристика §5.4: на странице видим хотя бы один `input[type=password]`.
   * Фронтенд по этому признаку зовёт `/login`, а не `/step`. */
  looksLikeLogin: boolean;
  /** Предупреждение стоп-листа §8.3 — показывается человеку, но НЕ
   * блокирует раунд. */
  dangerWarning?: string;
  /**
   * Сайт открыл НЕ тот экран, который просили (01.10.2026, перенос
   * правок QA TMA): `goto` на `/cabinet` закончился на `/login` или на
   * дашборде. Внутри origin это не нарушение замка (§8.1), поэтому кадр
   * отдаётся всё равно, — но человек должен знать, что смотрит на
   * другой шаг (чаще всего — кончилась сессия). Только предупреждение,
   * раунд не блокирует.
   */
  redirectWarning?: string;
}
