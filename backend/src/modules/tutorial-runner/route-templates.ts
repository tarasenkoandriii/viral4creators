/**
 * Маршруты, которым исполнитель обязан ПОДСЕЯТЬ фикстурную сессию в
 * `localStorage` браузера до первой загрузки документа.
 *
 * Почему так, а не отдельным URL: во `frontend/src/lib/router.ts` у
 * мастера нет параметра сессии, и заводить его значило бы менять
 * продуктовый роутер и визард ради ночного прогона. Зато мастер УЖЕ
 * умеет возвращаться к сессии — ровно тем способом, которым это делает
 * вернувшийся человек: читает `localStorage.sessionId`
 * (`useWorkflow.ts`). Исполнитель делает то же самое, что браузер
 * человека, а не обходной путь мимо продукта.
 *
 * Ключ (`'sessionId'`) — копия литерала из `useWorkflow.ts`; как и у
 * `SPA_LOCALE_STORAGE_KEY`, копию держит шов `check-docs.mjs`.
 */
export const SEEDED_SESSION_ROUTES: ReadonlySet<string> = new Set([
  'generate-ready',
]);

/**
 * Имя маршрута, открывающего ЧИСТЫЙ мастер. Смешивать его с
 * `generate-ready` в одном сценарии нельзя: подсев сессии происходит до
 * загрузки документа и на весь прогон, значит после него «чистый»
 * `generate` чистым уже не будет — и сценарий упал бы не там, где
 * ошибся автор, а на следующем шаге с невнятной причиной.
 */
export const FRESH_WIZARD_ROUTE = 'generate';

/**
 * Резолвит имя маршрута в hash-путь. Возвращает путь БЕЗ `#` и без
 * домена — вызывающий (`tutorial-scenario-runner.service.ts`) склеивает
 * его с `TMA_PUBLIC_URL`.
 */
export function resolveScenarioRoute(
  routeName: string,
  ctx: FixtureRouteContext,
): RouteResolution {
  const builder = ROUTE_BUILDERS[routeName];
  if (!builder) {
    return {
      ok: false,
      // Прежняя формулировка утверждала «нет такого в
      // frontend/src/lib/router.ts» — и в половине случаев это была
      // неправда: маршрут там был, отстала ЭТА копия таблицы (см.
      // доккомментарий файла). Оператор шёл искать опечатку в сценарии
      // вместо того, чтобы дописать строку сюда.
      reason: `имя маршрута «${routeName}» не найдено в таблице route-templates.ts. Либо это выдумка генератора, либо маршрут во frontend/src/lib/router.ts появился позже, а копию здесь не дописали — проверьте оба места`,
    };
  }
  return builder(ctx);
}
