/**
 * Знает ли исполнитель такое имя маршрута.
 *
 * Отдельно от `ROUTE_DESCRIPTIONS` намеренно: описания — это то, что
 * ПРЕДЛАГАЕТСЯ модели, а здесь — то, что исполнитель умеет открыть.
 * Списки не совпадают: часть маршрутов резолвится, но не предлагается
 * (`testing` — фикстурный пользователь не тестировщик), и валидатор,
 * проверяющий по описаниям, отверг бы законный сценарий, написанный
 * оператором руками. Поздравление с 29.09.2026 и резолвится, и
 * предлагается: фикстура заводит три проекта четвёртого типа.
 *
 * `ROUTE_BUILDERS` наружу не отдаём: вопрос «знаешь ли такой маршрут»
 * — это всё, что нужно снаружи, а отданная таблица однажды окажется
 * вторым местом, где маршруты резолвят.
 */
export function isResolvableRoute(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(ROUTE_BUILDERS, name);
}

/**
 * Резолвит имя маршрута в hash-путь. Возвращает путь БЕЗ `#` и без
 * домена — вызывающий (`tutorial-scenario-runner.service.ts`) склеивает
 * его с `TMA_PUBLIC_URL`.
 */
export function resolveScenarioRoute(
  routeName: string,
  ctx: FixtureRouteContext,
): RouteResolution {
  const builder = ROUTE_BUILDERS[routeName];
  if (!builder) {
    return {
      ok: false,
      // Прежняя формулировка утверждала «нет такого в
      // frontend/src/lib/router.ts» — и в половине случаев это была
      // неправда: маршрут там был, отстала ЭТА копия таблицы (см.
      // доккомментарий файла). Оператор шёл искать опечатку в сценарии
      // вместо того, чтобы дописать строку сюда.
      reason: `имя маршрута «${routeName}» не найдено в таблице route-templates.ts. Либо это выдумка генератора, либо маршрут во frontend/src/lib/router.ts появился позже, а копию здесь не дописали — проверьте оба места`,
    };
  }
  return builder(ctx);
}
