/**
 * route-templates.ts — резолвер имени маршрута сценария (шаг `goto`,
 * §4.10 ТЗ) в настоящий hash-путь TMA (`frontend/src/lib/router.ts`),
 * этап 97 (§5 ТЗ).
 *
 * ## Почему список маршрутов ЗДЕСЬ, а не импорт из frontend
 *
 * `frontend` и `backend` — отдельные Node-проекты (свои package.json/
 * tsconfig, разные раннтаймы — Vite-бандл в браузере и Nest на Vercel
 * Functions), кросс-импорта между ними в проекте нет нигде. Копия
 * `routes`/`Route['name']` из `frontend/src/lib/router.ts` ЗДЕСЬ —
 * осознанное дублирование, не оплошность: при изменении маршрутов
 * фронтенда эту таблицу нужно поправить руками. Настоящий cross-package
 * импорт стоил бы дороже, чем изредка поправить одну таблицу.
 *
 * ## Что этот приём УЖЕ стоил — и почему таблица теперь полная
 *
 * «Изредка поправить» не случилось ни разу. К 26.09.2026 во фронтенде
 * было 26 имён маршрутов, здесь — 21: отстали `site-tutorial`,
 * `greeting-video`, `testing`, `api-keys` и `invite`, добавленные после
 * этапа 97. Хуже самого пропуска было сообщение об ошибке: резолвер
 * отвечал «нет такого в `frontend/src/lib/router.ts`» — и это была
 * неправда, маршрут там был. Оператор по такой подсказке идёт искать
 * опечатку в сценарии, а не устаревшую копию. Формулировка исправлена
 * (см. `resolveScenarioRoute` ниже): теперь она называет обе возможные
 * причины и указывает на этот файл первым.
 *
 * Таблица приведена в соответствие этапом F ТЗ
 * `docs-tz/TZ-Enterprise-Tutorial-Landing.md`: там она понадобилась,
 * чтобы снять настоящие кадры мастера обучалки для лендинга.
 *
 * ## Почему не ВСЕ 20 маршрутов фронтенда
 *
 * Поддерживаются только те, для которых у фикстурного пользователя
 * (`scripts/seed-fixture-user.ts`, §3.3 ТЗ) реально есть данные:
 * проект, товар, манифест бренда, сессия с готовым роликом. Маршруты
 * вложенных прогонов (`catalog-batch`/`ab-test`/`feed-import` — свои id
 * партии/прогона, которых у фикстуры нет и не будет: это одноразовые
 * сущности, а не постоянные данные) и `legal`/`not-found` (не относятся
 * к обучающим сценариям мастера генерации) намеренно не резолвятся —
 * `unsupported`, с понятной причиной, а не тихая заглушка.
 *
 * ## Fail loudly на неизвестном имени
 *
 * До этапа 106 промпт генератора (`tutorial-scenario-prompt.ts`) называл
 * `route` плейсхолдером и в качестве ПРИМЕРА приводил несуществующее имя
 * — модель регулярно писала что-то вроде "wizard.generation"/
 * "wizard.step-8", 9 из 9 сгенерированных сценариев падали на первом же
 * шаге при реальном прогоне на проде. Промпт с этапа 106 передаёт модели
 * именно `ROUTE_DESCRIPTIONS` ниже как закрытый список, так что новые
 * сценарии в норме не должны попадать сюда вовсе — но резолвер всё равно
 * не пытается угадать похожее имя по историческим или ручным сценариям:
 * он явно говорит "не знаю такой маршрут", а сломанный сценарий
 * оператор удаляет кнопкой «Удалить» на «Сценарии обучалки»
 * (`TutorialScenarioAdminService.remove`, этап 106) — не чинит на лету,
 * это одноразовая генерация, дешевле перегенерировать, чем редактировать
 * JSON шагов вручную.
 */

/** Реальные ID фикстурных данных, известные оператору только в рантайме
 * (заведены `seed-fixture-user.ts`, резолвятся сервисом-оркестратором
 * из БД по фикстурному пользователю — см. `tutorial-scenario-runner.
 * service.ts`, этот файл о самих ID ничего не знает). */
export interface FixtureRouteContext {
  /** Проект РЕКЛАМНОГО пайплайна (`SINGLE`/`LINE`) — тот, у которого
   *  есть товары. Не подставлять сюда проект другого типа: маршруты
   *  `project`/`item` строят путь к товару внутри него. */
  projectId?: string;
  itemId?: string;
  manifestId?: string;
  sessionId?: string;
  /**
   * Сессия НА ШАГЕ ПРОМПТА, промпт ещё не сгенерирован (разбор
   * достижимости 29.09.2026). Нужна не для удобства: карточка
   * релевантности и кнопка «Сгенерировать промпт» рисуются под
   * `!prompt`, и на сессии с готовым роликом их не бывает НИКОГДА.
   */
  promptPendingSessionId?: string;
  /**
   * Сессия с одобренным промптом и БЕЗ ролика. Карточка запуска
   * рендера скрыта условием `generatedVideo?.status !== 'complete'` —
   * то есть ровно тем, что делает первую сессию «готовой».
   */
  readyToRenderSessionId?: string;
  /**
   * Проекты-ПОЗДРАВЛЕНИЯ — три, по одному на состояние (29.09.2026).
   *
   * Не три сессии, как у мастера товара, а три ПРОЕКТА: мастер
   * поздравления берёт последнюю сессию проекта с сервера
   * (`sessions[0]`), а не из localStorage. Значит состояние экрана
   * задаётся адресом, и подсевать в браузер ничего не нужно — это
   * проще и надёжнее, чем у мастера товара.
   *
   * `greetingProjectId` — брифа хватает, сессии нет: только карточка
   * брифа и кнопка «начать».
   */
  greetingProjectId?: string;
  /** Сессия есть, сценарий ещё не собран: видны референсы и кнопка
   *  «собрать сценарий», которую прячет уже собранный сценарий. */
  greetingDraftingProjectId?: string;
  /** Сценарий собран: видны все девять карточек, включая голос,
   *  музыку, титры, наклейку, сцены и ролик. */
  greetingReadyProjectId?: string;
  /**
   * Ролик ГОТОВ: последняя сессия проекта с отрендеренным роликом
   * (этап I ТЗ Greeting 2.0, §5.3 — кадр «готовый ролик» для лендинга).
   *
   * Отдельным полем, а не частью «сценарий собран»: готовый ролик
   * прячет кнопку запуска рендера, и проект с роликом, попавший в
   * `greetingReadyProjectId`, молча сломал бы сценарий хука
   * `greeting-render`. Фикстура заводит под это отдельный проект, но
   * ролика в нём нет, пока оператор его не отрендерит
   * (`doc/GREETING-FRAMES-CAPTURE.md`), — поэтому модели этот маршрут
   * не предлагается (`ROUTE_DESCRIPTIONS`).
   */
  greetingDoneProjectId?: string;
  /** Проект-обучалка по сайту заказчика (`CLIENT_SITE`) — отдельный
   *  проект, а не тот же самый: у него нет товаров, а у рекламного нет
   *  черновика обучалки. */
  clientSiteProjectId?: string;
}

export type RouteResolution =
  | { ok: true; path: string }
  | { ok: false; reason: string };

type RouteBuilder = (ctx: FixtureRouteContext) => RouteResolution;

function missingFixtureData(what: string): RouteResolution {
  return {
    ok: false,
    reason: `для этого маршрута нужны фикстурные данные (${what}), которых нет у фикстурного пользователя — проверьте scripts/seed-fixture-user.ts`,
  };
}

function unsupported(reason: string): RouteResolution {
  return {
    ok: false,
    reason: `маршрут пока не поддержан исполнителем: ${reason}`,
  };
}

