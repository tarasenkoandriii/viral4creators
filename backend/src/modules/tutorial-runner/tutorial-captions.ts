/**
 * tutorial-captions.ts — подписи на кадрах обучающего ролика (§5 ТЗ
 * `docs-tz/TZ-Tutorial-Video-Voiced.md`, этап E).
 *
 * ## Зачем подписи вообще
 *
 * Обучающий ролик смотрят без звука чаще, чем со звуком, и подпись —
 * единственное, что в этом случае объясняет кадр. Поэтому выключатель
 * `postprod.tutorialCaptions` по умолчанию ВКЛЮЧЁН, в отличие от
 * самой озвучки: та по умолчанию выключена, потому что стоит ≈$6 за
 * набор, а подписи не стоят ни вызова провайдера. Хронометража они
 * стоят — там, где речи нет: см. `captionReadingSeconds`. Четвёртый
 * уровень отката §9 («подписи мешают») выключает их независимо от
 * звука.
 *
 * ## Почему свой генератор, а не `buildCardsAss`
 *
 * Тот (`common/greeting-cards.ts`) — не генератор подписей по
 * массиву, а рендер РОВНО ТРЁХ фиксированных событий (заголовок,
 * финал, титр музыки) с потолком `MAX_CARD_TEXT_LENGTH = 70` и
 * фиксированным `CARD_SECONDS`. Реплики до 220 символов и по одной на
 * каждый кадр он принять не может. Берём его как образец ФОРМЫ —
 * экранирование, стили, `Dialogue`-строки, — а не как вызов;
 * `escapeAssText` и `assTime` при этом переиспользуются буквально,
 * второй копии правил экранирования в проекте быть не должно.
 *
 * ## Почему `.ass`, а не `.srt`
 *
 * Тот же довод, что у карточек поздравления: только `.ass` несёт
 * стиль вместе с текстом. Подписи обучалки рисуются на кадре
 * 720×1560 и должны читаться на фоне светлого интерфейса — это
 * плашка и своя раскладка, а не «субтитры по умолчанию».
 *
 * ## Чего здесь НЕТ
 *
 * Подписи есть только у покадровых реплик (вариант Б, этап D). У
 * варианта А текст один на весь ролик — абзац в несколько сотен
 * символов, — и растянуть его на всю склейку значит показать не
 * подпись к кадру, а стену текста поверх всего ролика. Сценарий без
 * реплик остаётся без подписей, и это не пробел, а то же решение,
 * по которому вариант А вообще существует запасным путём.
 */

import { escapeAssText, assTime } from '../../common/greeting-cards';
import {
  CANVAS,
  frameSpansSeconds,
  narrationFrameSeconds,
  SlideshowMotion,
} from './tutorial-video-assembly';

/**
 * Скорость чтения подписи — символов в секунду.
 *
 * То же число, по которому §7.1 ТЗ прикидывает длину речи («≈15
 * символов в секунду»), и это нарочно: немой кадр с подписью держится
 * столько, сколько звучала бы его реплика, — ролик без звука идёт в
 * том же темпе, что и со звуком. Для СИНХРОНИЗАЦИИ с речью оценка по
 * символам не годится (§4.1: речь измеряется у файла), а здесь речи
 * нет, мерить нечего, и темп чтения — единственное, от чего зависеть.
 */
export const CAPTION_CHARS_PER_SECOND = 15;

/** Текст подписи ровно в том виде, в каком он ляжет на кадр: пробелы
 *  схлопнуты, края обрезаны. Одна функция на отрисовку и на время
 *  чтения — считать символы не той строки, что показана, значит
 *  ошибаться на отступах и переводах строк. */
function captionText(narration: string | null): string {
  return narration?.trim().replace(/\s+/g, ' ') ?? '';
}

/**
 * Сколько держать кадр, на котором подпись ЕСТЬ, а измеренной речи —
 * НЕТ: озвучка выключена (по умолчанию), дорожка шага не
 * синтезировалась или её длину не удалось измерить.
 *
 * Правка сквозного аудита A–G. Этап E включил подписи по умолчанию и
 * отвязал их от звука, а длительность такого кадра осталась от этапов
 * A и B: две секунды немого кадра (или полторы у кадра без дорожки при
 * варианте Б). Реплика в среднем ≈120 символов (§7.1) — это
 * шестьдесят символов в секунду, вчетверо быстрее, чем читают. То есть
 * в конфигурации по умолчанию подписи были, и прочитать их было
 * нельзя, — хотя довод за них ровно в том, что без звука подпись
 * «единственное, что объясняет кадр».
 *
 * Хвост и нижняя граница — те же, что у кадра с речью
 * (`narrationFrameSeconds`): правило одно, меняется только источник
 * длины. Пустая подпись — `null`: решать вызывающему, его прежнее
 * число остаётся в силе.
 */
export function captionReadingSeconds(narration: string | null): number | null {
  const text = captionText(narration);
  if (!text) return null;
  // По кодовым точкам, а не по UTF-16: символ вне BMP — один символ
  // для читающего, а не два.
  return narrationFrameSeconds(
    Array.from(text).length / CAPTION_CHARS_PER_SECOND,
  );
}

/**
 * Холст подписей. Короткая сторона 1080, как у карточек поздравления:
 * так кегль означает одно и то же независимо от того, к какому
 * реальному размеру кадр масштабируется.
 *
 * ВЫВОДИТСЯ из `CANVAS` сборки, а не переписан от руки. Пропорция
 * обязана совпадать — libass считает раскладку в своих единицах и
 * растянет текст, если они разойдутся, — а переписанное от руки
 * число расходится ровно тогда, когда холст сборки меняют и сюда не
 * заглядывают (находка аудита этапа E).
 */
const PLAY_RES = {
  x: 1080,
  y: Math.round((1080 * CANVAS.height) / CANVAS.width),
} as const;

/**
 * Кегль подписи.
 *
 * 44 при короткой стороне 1080 — это 4 % высоты кадра: крупнее
 * субтитров ролика (там 36–40), потому что подпись здесь несёт смысл
 * шага, а не дублирует речь актёра. Проверено на максимуме: реплика
 * в 220 символов укладывается в ШЕСТЬ строк и не выходит за кадр
 * (§11 п.18 требует проверять именно максимум, а не типичный
 * текст). Прежняя редакция комментария обещала пять — отрисовка
 * показала шесть.
 */
const FONT_SIZE = 44;

/** Поля. Боковые щедрые — иначе на переносе строки текст липнет к
 *  краю; нижнее держит подпись над самым низом кадра, где в мастере
 *  обычно кнопки. */
const MARGIN_SIDE = 90;

const MARGIN_BOTTOM = Math.round(PLAY_RES.y * 0.07);

/**
 * Время подписи — ВНИЗ до сотых, а не округлением.
 *
 * `.ass` пишет время сотыми, а кадры лежат на сетке 1/30: граница
 * вроде 2.6667 при округлении даёт 2.67, то есть конец подписи
 * оказывается ПОЗЖЕ смены кадра, и первый кадр следующего шага
 * успевает показаться со старой подписью. Проверено отрисовкой
 * (аудит этапа E).
 *
 * Вниз — и для начала, и для конца, одним правилом: тогда конец
 * предыдущей подписи и начало следующей совпадают в той же сотой, и
 * ни наложения, ни дыры не остаётся.
 */
function floorToCentis(seconds: number): number {
  return Math.floor(seconds * 100) / 100;
}

/** Кадр с репликой. `narration: null` — кадр молчит и подписи не
 *  получает (`waitFor`, `assertVisible`, `triggerPaidOperation`). */
export interface CaptionFrame {
  seconds: number;
  narration: string | null;
}

/** Есть ли что рисовать. Пусто — вызывающий не должен ни заливать
 *  файл, ни добавлять вход задачи: лишний вход это лишний скачанный
 *  файл на стороне чужого сервиса. */
export function hasCaptions(frames: readonly CaptionFrame[]): boolean {
  return frames.some((f) => (f.narration?.trim() ?? '') !== '');
}

/**
 * `.ass` с подписями по кадрам. Пустая строка — рисовать нечего.
 *
 * Таймкоды берутся из `frameSpansSeconds` — той же функции, по
 * которой считается длительность ролика. Свой расчёт здесь означал бы
 * два источника одной правды, и расходились бы они не сразу, а к
 * концу ролика: округление идёт покадрово, и ошибка накапливается.
 */
export function buildTutorialCaptionsAss(
  frames: readonly CaptionFrame[],
  /** Тот же режим движения, что уйдёт в `planSlideshow` (этап G).
   *  Переходы сдвигают начало каждого кадра, и подписи, посчитанные
   *  без них, к концу ролика висели бы над чужим экраном. */
  motion: SlideshowMotion,
): string {
  if (!hasCaptions(frames)) return '';
  const spans = frameSpansSeconds(frames, motion);

  const events: string[] = [];
  frames.forEach((frame, i) => {
    // Пробелы схлопываются, но текст НЕ обрезается по длине: реплика
    // уже прошла валидацию в 220 символов (`MAX_NARRATION_LENGTH`), и
    // резать её второй раз, другим правилом и в другом месте, значит
    // показать не то, что произнесено. §11 п.16 требует дословного
    // совпадения подписи с репликой.
    const text = captionText(frame.narration);
    if (!text) return;
    // Экранирование — ПЕРВЫМ, перенос — вторым, подменой метки: иначе
    // `\N`, написанный заранее, экранирование бы съело.
    const rendered = escapeAssText(breakLongWords(text))
      .split(BREAK_MARK)
      .join('\\N');
    const { start, end } = spans[i];
    events.push(
      `Dialogue: 0,${assTime(floorToCentis(start))},${assTime(floorToCentis(end))},caption,,0,0,0,,${rendered}`,
    );
  });

  return [
    '[Script Info]',
    'ScriptType: v4.00+',
    `PlayResX: ${PLAY_RES.x}`,
    `PlayResY: ${PLAY_RES.y}`,
    // Перенос по словам с выравниванием строк: реплика в пять строк
    // не должна выглядеть обрывком.
    'WrapStyle: 0',
    'ScaledBorderAndShadow: yes',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    // Плашка за текстом: `BorderStyle=3` + НЕНУЛЕВОЙ `Outline`, и
    // цвет её берётся из `OutlineColour`, а не из `BackColour`.
    //
    // Это проверено отрисовкой, а не вычитано: пара
    // «BorderStyle=3, BackColour=<цвет>, Outline=0» выглядит
    // правдоподобно и НЕ РИСУЕТ НИЧЕГО — libass при нулевой обводке
    // не строит коробку вовсе, а `BackColour` при этом стиле уходит
    // на тень. Белый текст оставался белым текстом на светлом экране
    // мастера, то есть подпись была нечитаема ровно там, ради чего
    // заводилась. `Outline` здесь — не толщина обводки букв, а поле
    // коробки вокруг строки.
    //
    // `&H30000000` — чёрный, альфа 0x30 (в ASS первый байт это
    // ПРОЗРАЧНОСТЬ, больше значит прозрачнее): почти непрозрачный.
    // У карточек поздравления плашка светлее, и это уместно там —
    // под ней лицо ведущего. Здесь под подписью текст интерфейса, и
    // просвечивать ему незачем: читать надо подпись.
    //
    // Поле коробки (`Outline`) написано ЧИСЛОМ, а не константой, и
    // это не небрежность: шов в `scripts/check-docs.mjs` читает поле
    // из текста стиля и на интерполяции слепнет — он честно
    // разбирал `${...}` и пропускал любое значение, включая ноль
    // (находка аудита этапа E). Числу в строке стиля он верить
    // может.
    //
    // Alignment 2 — низ по центру.
    `Style: caption,Arial,${FONT_SIZE},&H00FFFFFF,&H000000FF,&H30000000,&H00000000,0,0,0,0,100,100,0,0,3,6,0,2,${MARGIN_SIDE},${MARGIN_SIDE},${MARGIN_BOTTOM},1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
    ...events,
    '',
  ].join('\n');
}

/**
 * Максимум символов подряд без пробела, которые помещаются в строку
 * подписи. При кегле 44 и полях по 90 на холсте 1080 — около
 * двадцати восьми; берём с запасом.
 */
const MAX_UNBROKEN_RUN = 26;

/** Метка переноса на время экранирования. `\u0000` в тексте реплики
 *  появиться не может: он не проходит ни JSON от модели, ни
 *  валидацию, ни поле ввода админки. */
const BREAK_MARK = '\u0000';

/**
 * Рвёт «слова» длиннее строки принудительным переносом.
 *
 * `WrapStyle: 0` переносит ПО ПРОБЕЛАМ и длинное слово разорвать не
 * может: плашка растягивается на всю ширину кадра и текст срезается
 * по краям. Валидатор такой ввод пропускает — он смотрит на длину и
 * переводы строк, а не на пробелы, — и попасть туда может URL,
 * селектор или просто склеенное слово (находка аудита этапа E).
 *
 * Рвём жёстко, по символам: угадывать место переноса в чужом языке
 * (а локалей пять) нечем, а срезанный текст хуже некрасивого
 * переноса.
 *
 * Перенос ЖЁСТКИЙ (`\N`), а не «мягкий» нулевой пробел: U+200B
 * libass точкой переноса не считает вовсе — проверено отрисовкой,
 * строка с ним так же уезжает за оба края кадра. Метка ставится ДО
 * экранирования и подменяется ПОСЛЕ: экранирование превращает
 * обратный слэш в косую черту, и написанный заранее `\N` оно бы
 * испортило.
 */
function breakLongWords(text: string): string {
  return text
    .split(' ')
    .map((word) =>
      word.length <= MAX_UNBROKEN_RUN
        ? word
        : (
            word.match(new RegExp(`.{1,${MAX_UNBROKEN_RUN}}`, 'gu')) ?? [word]
          ).join(BREAK_MARK),
    )
    .join(' ');
}

/** Путь файла подписей — ПОД префиксом актива: файл транзитный,
 *  скачан внешним ffmpeg-api один раз и больше не нужен, и уборка
 *  кадров уносит его вместе с ними (§4.3 ТЗ и шов «все транзитные
 *  заливки под одним убираемым префиксом»). */
export function captionsPathname(framePrefix: string): string {
  return `${framePrefix}captions.ass`;
}
