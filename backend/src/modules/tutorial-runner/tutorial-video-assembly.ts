/**
 * tutorial-video-assembly.ts — собирает кадры сценария (`scenario-
 * runner.ts`'s `captureFrames`, этап 98) в один ролик-слайд-шоу через
 * уже существующий внешний ffmpeg-api (`postprod/ffmpeg-api.service.ts`,
 * этап 34) — тот же провайдер, что уже кроит кадр и переозвучивает
 * готовые рекламные ролики, не вторая инфраструктура (доккомментарий
 * `scenario-runner.ts` объясняет, почему локальный ffmpeg на Vercel не
 * вариант).
 *
 * Чистая функция: собирает `{inputs, outputs, commands}` — тот же
 * контракт, что уже принимает `FfmpegApiService.submit()`
 * (`common/reframe.ts`'s `planBatchReframe` — тот же приём для другой
 * задачи). Сеть/Blob/БД — на совести вызывающего кода
 * (`tutorial-scenario-runner.service.ts`), здесь только строится команда.
 *
 * ## Почему слайд-шоу, а не что-то умнее
 *
 * `-loop 1 -t N -i {{key}}` держит каждый кадр статичным N секунд, затем
 * `concat`-фильтр склеивает все кадры в один поток — простейший вид
 * видео, какой вообще можно собрать из отдельных кадров без реального
 * скринкаста. Никакой плавности/курсора/переходов — честно объявлено как
 * ограничение (см. `scenario-runner.ts`), не скрыто за словом «видео».
 *
 * Приведение каждого кадра к общему холсту (`CANVAS` ниже) — не только
 * защита от нечётных сторон, которых не принимает `libx264`/`yuv420p`.
 * Главное в другом: `concat` требует совпадения размеров ВСЕХ
 * сегментов, а кадры приходят от двух разных съёмок. До 27.09.2026
 * здесь стоял `scale=trunc(iw/2)*2:trunc(ih/2)*2`, который делал
 * стороны чётными, но между собой их не равнял, — и сборка держалась на
 * соглашении, что в одном прогоне вьюпорт один.
 */

/** Сколько секунд держим один кадр в кадре — достаточно, чтобы успеть
 * прочитать экран, не настолько долго, чтобы 10-шаговый сценарий
 * превращался в получасовой ролик. */
export const SECONDS_PER_FRAME = 2;

/**
 * Общий холст слайд-шоу. Кадры приходят от двух разных съёмок
 * (сценарный прогон и обучалка по сайту заказчика) и в принципе могут
 * различаться размером, а `concat` этого не прощает — см. комментарий
 * у `scaleFilters` ниже.
 *
 * 720×1560 — пропорция телефонного экрана 390×844, к которой ближе
 * всего оба источника, округлённая до чётных сторон, кратных 8 (H.264
 * любит такие).
 */
const CANVAS = { width: 720, height: 1560 } as const;

/**
 * Один кадр слайд-шоу: чей это шаг, что показать и сколько держать.
 *
 * Длительность стала полем кадра на этапе A ТЗ
 * `docs-tz/TZ-Tutorial-Video-Voiced.md`. До этого она была
 * константой `SECONDS_PER_FRAME` на все кадры сразу, и это
 * единственное, что мешало кадру длиться ровно столько, сколько
 * звучит реплика диктора. Сегодня все вызывающие передают ту же
 * константу на каждый кадр — поведение не меняется ни на кадр, —
 * но подпись функции больше не запрещает разное.
 *
 * `stepIndex` добавлен правкой аудита этапа A. Первая редакция
 * этапа довела номер шага от `runScenario` до имени файла в Blob и
 * там его потеряла: оба вызывающих сворачивали кадры обратно в
 * плоский `string[]`, и в план приезжал позиционный массив. То есть
 * инвариант «кадр i — это шаг i» жил внутри одной функции, а
 * снаружи держался на обещании. На этапе B к кадру привязывается
 * реплика — по номеру шага, иначе привязывать не к чему.
 */
export interface SlideshowFrame {
  /** Номер шага, ПОСЛЕ которого снят кадр (0-based). Строго
   *  возрастает по массиву; пропуски допустимы и означают ровно то,
   *  чем являются: кадра того шага нет. */
  stepIndex: number;
  url: string;
  /** Секунды. Дробные допустимы: длительность реплики измеряется, а
   *  не округляется (§4.1 ТЗ). */
  seconds: number;
}

/**
 * Длительность готового слайд-шоу в миллисекундах.
 *
 * Живёт РЯДОМ с планом, а не у того, кто пишет её в базу: до правки
 * 27.09.2026 писатель импортировал только `SECONDS_PER_FRAME` и
 * умножал сам. Сегодня это сходилось (переходов и звука в плане нет),
 * но тот, кто добавит `xfade`, получил бы верное видео и неверное
 * число в базе — а число это человек читает на экране мастера
 * («Длительность — около N с»).
 */
export function slideshowDurationMs(frames: readonly SlideshowFrame[]): number {
  return Math.round(frames.reduce((sum, f) => sum + f.seconds, 0) * 1000);
}

/**
 * Снятые кадры → кадры плана, все одной длины.
 *
 * Номер шага приходит С КАДРОМ и не трогается; функция добавляет
 * только длительность. Именно так обязан звать сценарный путь: там
 * кадр пропадает молча, и позиция в массиве — не номер шага.
 *
 * Существует ради того, чтобы `SECONDS_PER_FRAME` не пришлось
 * импортировать вызывающему: длительность кадра знает модуль плана и
 * только он (шов в `scripts/check-docs.mjs`). На этапе B здесь же
 * появится вариант с измеренными длительностями, и вызывающий
 * поменяет одну строку, а не формулу у себя.
 */
export function framesFromSteps(
  shots: readonly { stepIndex: number; url: string }[],
  seconds: number = SECONDS_PER_FRAME,
): SlideshowFrame[] {
  return shots.map(({ stepIndex, url }) => ({ stepIndex, url, seconds }));
}

/**
 * Кадры одинаковой длины, снятые ПОДРЯД, без пропусков: номер шага
 * совпадает с позицией в массиве.
 *
 * Это не «удобная обёртка на все случаи», а утверждение о входе, и
 * годится оно ровно там, где сплошная нумерация гарантирована
 * устройством пути. Сегодня такой путь один — обучалка по сайту
 * заказчика: кадры туда кладёт обход сайта
 * (`client-site-tutorial.service.ts`), а не `runScenario`, они
 * лежат под `draftFramePathname(id, 0..n-1)` и пропасть поодиночке
 * не могут. Сценарный путь так вызывать НЕЛЬЗЯ: там кадр снимается
 * best-effort и пропадает молча — номер шага надо брать у кадра
 * (`ScenarioFrame.stepIndex`), а не выводить из позиции.
 *
 * Отдельная функция, а не умолчание у `planSlideshow`: умолчание
 * пряталось бы в подписи и позволяло бы забыть и длительность, и
 * номер шага там, где они уже важны.
 */
export function uniformFrames(
  urls: readonly string[],
  seconds: number = SECONDS_PER_FRAME,
): SlideshowFrame[] {
  return framesFromSteps(
    urls.map((url, stepIndex) => ({ stepIndex, url })),
    seconds,
  );
}

/** Потолок числа кадров одного сценария — совпадает с `MAX_SCENARIO_
 * STEPS` (`scenario-steps.ts`, этап 94: до 30 шагов) плюс небольшой
 * запас; чисто оборонительная защита ffmpeg-команды от неограниченного
 * роста `-filter_complex`, не ожидается достигаться на практике. */
export const MAX_SLIDESHOW_FRAMES = 40;

export interface SlideshowPlan {
  inputs: Record<string, string>;
  outputs: string[];
  commands: string[];
  /**
   * Длительность собранного ролика в миллисекундах — считается ЗДЕСЬ
   * и отдаётся вместе с командой.
   *
   * Так, а не отдельной функцией у вызывающего: до этапа A писатель
   * умножал `frameCount × SECONDS_PER_FRAME` у себя, за три модуля от
   * места, где строится команда. Пока все кадры были одинаковой
   * длины, это сходилось; с разными длительностями разошлось бы
   * молча, а число это человек читает на экране («Длительность —
   * около N с»).
   */
  durationMs: number;
  /** Имя единственного выходного файла — то же значение, что
   * `outputs[0]`, отдельным полем ради читаемости на стороне вызывающего
   * кода (не нужно доставать из массива по индексу). */
  outputName: string;
}

/**
 * `frames` — кадры по порядку съёмки: публичная Blob-ссылка (PNG) и
 * сколько секунд держать. `null` — ТРИ случая, и вызывающий обязан
 * обработать их сам, не вызывая `submit()` с бессмысленной, опасно
 * большой или заведомо падающей командой:
 *
 * 1. собирать нечего (0 кадров);
 * 2. кадров больше потолка (`MAX_SLIDESHOW_FRAMES`);
 * 3. у кадра неположительная или неконечная длительность;
 * 4. номера шагов не возрастают строго.
 *
 * Третий случай появился вместе с покадровыми длительностями (этап A)
 * и до этапа B недостижим: все вызывающие передают константу. Зато с
 * этапа B длительность приходит измерением mp3 — и `0`, `NaN`,
 * `Infinity` становятся достижимыми входами, а не теорией.
 */
export function planSlideshow(
  frames: readonly SlideshowFrame[],
  outputName = 'tutorial.mp4',
): SlideshowPlan | null {
  if (frames.length === 0 || frames.length > MAX_SLIDESHOW_FRAMES) {
    return null;
  }
  // Неположительная длительность — это не «покажем мгновенно», а
  // испорченная команда: `-t 0` даёт сегмент без кадров, и `concat`
  // падает целиком. Отказ здесь дешевле разбирательства с внешним
  // сервисом (тот же принцип, что у потолка числа кадров выше).
  //
  // `Number.isFinite`, а не только `> 0`: `Infinity > 0` — правда, и
  // `-t Infinity` ушёл бы во внешний сервис как валидная команда,
  // которая никогда не завершится. С этапа B длительность приходит
  // измерением mp3, то есть делением, — `Infinity` и `NaN` там не
  // экзотика (найдено аудитом этапа A).
  if (frames.some((f) => !(Number.isFinite(f.seconds) && f.seconds > 0))) {
    return null;
  }
  // Номера шагов обязаны строго возрастать. Не педантизм: ключ входа
  // ниже строится из номера шага, а `inputs` — объект. Два кадра с
  // одним номером дали бы ОДИН ключ и ДВА `-i`, то есть команду, где
  // подставится не тот файл, — молча, без ошибки от ffmpeg-api.
  // Перепутанный порядок сломал бы хронологию ролика так же тихо.
  if (
    frames.some(
      (f, i) =>
        !Number.isInteger(f.stepIndex) ||
        f.stepIndex < 0 ||
        (i > 0 && f.stepIndex <= frames[i - 1].stepIndex),
    )
  ) {
    return null;
  }

  const inputs: Record<string, string> = {};
  const inputArgs: string[] = [];
  const scaleFilters: string[] = [];

  frames.forEach(({ url, seconds, stepIndex }, i) => {
    // Ключ входа и метка потока — по номеру ШАГА: команду читает
    // человек, разбирая неудачную сборку, и `frame3` обязано
    // означать третий шаг, а не третий уцелевший кадр. Пропавший
    // кадр оставляет дыру в нумерации — ровно как в именах файлов.
    //
    // А вот `[${i}:v]` — ПОЗИЦИОННЫЙ и таким останется: это индекс
    // входа в порядке аргументов `-i`, его нумерует сам ffmpeg, и
    // подставить туда номер шага значит сослаться на несуществующий
    // вход. Расхождение между `[${i}:v]` и `[v${stepIndex}]` в одной
    // строке нарочное, а не опечатка.
    const key = `frame${stepIndex}`;
    inputs[key] = url;
    inputArgs.push(`-loop 1 -t ${seconds} -i {{${key}}}`);
    // Приведение к ОБЩЕМУ холсту, а не просто к чётным сторонам.
    //
    // Найдено аудитом 27.09.2026. Прежний `scale=trunc(iw/2)*2:…`
    // делал стороны чётными, но размеры кадров между собой не
    // равнял, — а `concat` требует совпадения ширины и высоты. То,
    // что сборка работала, держалось на соглашении: сценарный путь
    // снимает одним вьюпортом, путь сайта заказчика — другим, но
    // внутри одного прогона одинаковым. Любой кадр иного размера
    // (сменили вьюпорт, досняли один экран отдельно, поменяли
    // плотность) ронял бы задачу ЦЕЛИКОМ, без частичного результата.
    //
    // `force_original_aspect_ratio=decrease` вписывает кадр внутрь
    // холста без обрезки, `pad` дополняет чёрным по центру. Кадр
    // никогда не растягивается: пропорции экрана важнее заполнения
    // холста, растянутый интерфейс выглядит поломкой.
    scaleFilters.push(
      `[${i}:v]scale=${CANVAS.width}:${CANVAS.height}:` +
        `force_original_aspect_ratio=decrease,` +
        `pad=${CANVAS.width}:${CANVAS.height}:(ow-iw)/2:(oh-ih)/2,` +
        `setsar=1[v${stepIndex}]`,
    );
  });

  const concatInputs = frames.map((f) => `[v${f.stepIndex}]`).join('');
  const filter = `${scaleFilters.join(';')};${concatInputs}concat=n=${
    frames.length
  }:v=1:a=0[outv]`;

  const command =
    `${inputArgs.join(' ')} -filter_complex "${filter}" -map "[outv]" ` +
    `-r 30 -pix_fmt yuv420p ${outputName}`;

  return {
    inputs,
    outputs: [outputName],
    commands: [command],
    outputName,
    durationMs: slideshowDurationMs(frames),
  };
}
