/**
 * tutorial-video-assembly.ts — собирает кадры сценария (`scenario-
 * runner.ts`'s `captureFrames`, этап 98) в один ролик-слайд-шоу через
 * уже существующий внешний ffmpeg-api (`postprod/ffmpeg-api.service.ts`,
 * этап 34) — тот же провайдер, что уже кроит кадр и переозвучивает
 * готовые рекламные ролики, не вторая инфраструктура (доккомментарий
 * `scenario-runner.ts` объясняет, почему локальный ffmpeg на Vercel не
 * вариант).
 *
 * Чистая функция: собирает `{inputs, outputs, commands}` — тот же
 * контракт, что уже принимает `FfmpegApiService.submit()`
 * (`common/reframe.ts`'s `planBatchReframe` — тот же приём для другой
 * задачи). Сеть/Blob/БД — на совести вызывающего кода
 * (`tutorial-scenario-runner.service.ts`), здесь только строится команда.
 *
 * ## Почему слайд-шоу, а не что-то умнее
 *
 * `-loop 1 -t N -i {{key}}` держит каждый кадр статичным N секунд, затем
 * `concat`-фильтр склеивает все кадры в один поток — простейший вид
 * видео, какой вообще можно собрать из отдельных кадров без реального
 * скринкаста. Никакой плавности/курсора/переходов — честно объявлено как
 * ограничение (см. `scenario-runner.ts`), не скрыто за словом «видео».
 *
 * Приведение каждого кадра к общему холсту (`CANVAS` ниже) — не только
 * защита от нечётных сторон, которых не принимает `libx264`/`yuv420p`.
 * Главное в другом: `concat` требует совпадения размеров ВСЕХ
 * сегментов, а кадры приходят от двух разных съёмок. До 27.09.2026
 * здесь стоял `scale=trunc(iw/2)*2:trunc(ih/2)*2`, который делал
 * стороны чётными, но между собой их не равнял, — и сборка держалась на
 * соглашении, что в одном прогоне вьюпорт один.
 */

import { createHash } from 'crypto';

/** Сколько секунд держим один кадр в кадре — достаточно, чтобы успеть
 * прочитать экран, не настолько долго, чтобы 10-шаговый сценарий
 * превращался в получасовой ролик. */
export const SECONDS_PER_FRAME = 2;

/** Пауза после реплики — чтобы кадр не сменялся на последнем слоге
 * (§4.1 ТЗ). */
export const FRAME_TAIL_SECONDS = 0.6;

/** Нижняя граница длительности кадра: кадр без реплики не должен
 * мелькать, а слишком короткая реплика — обрываться вместе с кадром
 * (§4.1 ТЗ). */
export const MIN_FRAME_SECONDS = 1.5;

/** Частота дискретизации звуковых сегментов. Одна на все сегменты и
 * названа константой не для красоты: `concat` требует совпадения
 * формата у ВСЕХ входов, а сегменты приходят из двух разных мест —
 * синтезированного mp3 и сгенерированной тишины. Разойдутся — задача
 * упадёт целиком, тот же класс отказа, что у размеров кадра. */
const AUDIO_RATE = 44_100;

/** Частота кадров — ОДНА на вход и на выход. Разойдутся — ffmpeg
 * квантует `-t` по частоте входа и отдаёт кадр длиннее заказанного
 * (см. `-framerate` в `planSlideshow`). */
const OUTPUT_FPS = 30;

/**
 * Сэмплов звука на один кадр видео: 44100 / 30 = 1470 — ЦЕЛОЕ число, и
 * на этом стоит точная длина звука (аудит этапа G).
 *
 * Звук, обрезанный секундами (`atrim=0:3.6333333333333333`), режется
 * вниз до сэмпла и теряет на каждом таком сегменте долю сэмпла. Сама по
 * себе потеря ничтожна, но `-shortest` кончает файл по КОРОТКОМУ потоку,
 * и звук, вышедший короче картинки хотя бы на сэмпл, отрезает у ролика
 * последний кадр целиком. Замерено настоящим ffmpeg: тридцать кадров с
 * переходами — 3615 кадров в файле при 3616 в плане; одна дорожка на
 * весь ролик — 186 при 187 всякий раз, когда `durationMs` округляется
 * вниз (это дефект этапа B, найденный аудитом этапа G). Резка целыми
 * сэмплами — `atrim=end_sample=` — даёт звук ровно той длины, что
 * картинка, и `-shortest` снова отрезает только хвост aac.
 */
const SAMPLES_PER_FRAME = AUDIO_RATE / OUTPUT_FPS;

/**
 * Хвост тишины в ОДИН кадр у звука, который собирается отдельно от
 * картинки (переходы и одна дорожка на весь ролик).
 *
 * Звук ровно в длину картинки — ещё не гарантия. `-shortest` в ffmpeg
 * 6.1 решает по границам aac-пакетов (1024 сэмпла), и на равных длинах
 * он всё равно ронял последний кадр: тридцать кадров с переходами при
 * звуке, точном до сэмпла, дали 3615 кадров при 3616 в плане. Звук на
 * кадр длиннее картинки делает её заведомо более коротким потоком, и
 * `-shortest` режет уже звук — в тишине хвоста, — а картинка и длина
 * файла совпадают с планом до кадра (замерено, см. запись этапа G в
 * ТЗ). 1470 сэмплов больше пакета, поэтому хватает одного кадра.
 */
const AUDIO_TAIL_SAMPLES = SAMPLES_PER_FRAME;
if (!Number.isInteger(SAMPLES_PER_FRAME)) {
  // Сменят частоту звука или кадров так, что деление перестанет быть
  // целым, — узнают об этом при старте, а не по съехавшему ролику.
  throw new Error(
    `AUDIO_RATE / OUTPUT_FPS обязано быть целым (${AUDIO_RATE} / ${OUTPUT_FPS})`,
  );
}

/**
 * Движение в слайд-шоу (§6 ТЗ, этап G): переходы между кадрами и лёгкий
 * зум внутри кадра.
 *
 * Три режима, а не два флага: зум без переходов не заказывал никто, и
 * лишняя комбинация была бы лишней строкой в каждом тесте и в каждой
 * фразе витрины. Режим — ОБЯЗАТЕЛЬНЫЙ параметр всех трёх потребителей
 * сетки времени: плана, подписей и отпечатка. Ни у одного из них нет
 * умолчания, и это не педантизм: переход укорачивает ролик на 0.3 с на
 * каждом стыке, и подписи, посчитанные без переходов поверх ролика с
 * переходами, к тридцатому кадру отставали бы на восемь с половиной
 * секунд. Ровно эту ловушку аудит этапа E снял у третьего параметра
 * `slideshowContentHash`.
 */
export const SLIDESHOW_MOTIONS = ['none', 'fade', 'fade+zoom'] as const;

export type SlideshowMotion = (typeof SLIDESHOW_MOTIONS)[number];

/**
 * Длина перехода — В КАДРАХ, а не в секундах: 9 кадров при 30 к/с —
 * это 0.3 с из §6 ТЗ. Кадрами потому, что вся сетка времени
 * (`frameSpansSeconds`) считается в целых кадрах, и переход, заданный
 * секундами, пришлось бы округлять на каждом стыке своим правилом.
 */
/**
 * Качество видео на выходе. То же число, что у проверенного пути
 * постобработки (`common/postprod.ts`): 18 — визуально без потерь.
 * Своё значение здесь означало бы, что ролики обучалки выглядят иначе
 * ролика пользователя без единой причины.
 */
export const OUTPUT_CRF = 18;

export const TRANSITION_FRAMES = 9;

/**
 * Тот же переход в СЕКУНДАХ — производное, а не второе число.
 *
 * Нужно за пределами этого модуля: время, которое стык съедает у
 * показа кадра, сверяется с хвостом кадра (`FRAME_TAIL_SECONDS`), и
 * на этой сверке держится то, что подпись успевают прочитать при
 * включённом движении (см. тест «переход съедает паузу, а не время
 * чтения»). Считать `TRANSITION_FRAMES / 30` на стороне вызывающего
 * значило бы развести знание о сетке кадров по модулям — ровно то,
 * что запрещает шов «сетку кадров знает только модуль плана».
 */
export const TRANSITION_SECONDS = TRANSITION_FRAMES / OUTPUT_FPS;

/**
 * Во сколько раз кадр приближается к концу своего показа — 1.00 → 1.04
 * (§6 ТЗ). Убирает ощущение презентации и при этом не уводит за край
 * ничего, что стоит читать: 4 % — это 14 пикселей по короткой стороне
 * холста с каждого края.
 */
export const ZOOM_TO = 1.04;

/**
 * Ролик длиннее этого — без зума, только с переходами.
 *
 * Зум — самая дорогая часть сборки: `perspective` с кубической
 * интерполяцией на холсте 720×1560 утраивает работу ffmpeg (замерено в
 * песочнице на двух ядрах: 120 с ролика — 60 с сборки с переходами и
 * 180 с — с переходами и зумом). У задачи внешнего сервиса потолок
 * `ASSEMBLY_DEADLINE_MS` — десять минут, и самый длинный ролик
 * сценарного пути (тридцать шагов по реплике в 220 символов, ≈470 с)
 * с зумом его бы превысил: задача оплачена, ролика нет. 180 с — это
 * вдвое ниже потолка по тому же замеру, и в пять раз длиннее обычного
 * ролика обучалки (§7.1: ≈35–40 с), то есть на живых сценариях
 * ограничение не срабатывает.
 *
 * Снимается только зум: он не двигает сетку времени, и подписи со
 * звуком, посчитанные с ним, остаются верными и без него.
 */
export const ZOOM_MAX_SECONDS = 180;

/**
 * Режим, который план ПРИМЕНИТ на самом деле: зум снимается у ролика
 * длиннее `ZOOM_MAX_SECONDS`. Сетку времени это не меняет — её
 * определяют только переходы.
 */
export function appliedMotion(
  frames: readonly { seconds: number }[],
  motion: SlideshowMotion,
): SlideshowMotion {
  if (motion !== 'fade+zoom') return motion;
  const spans = frameSpansSeconds(frames, motion);
  return (spans.at(-1)?.end ?? 0) > ZOOM_MAX_SECONDS ? 'fade' : motion;
}

/**
 * Сколько кадров на самом деле занимает переход при этом наборе кадров.
 *
 * Не всегда `TRANSITION_FRAMES`. Переход откусывает начало кадра
 * (въезд) и его конец (выезд); кадр короче двух переходов отдал бы
 * одни и те же кадры обоим, и `xfade` смешивал бы три экрана сразу.
 * На живых путях такого нет — самый короткий кадр полторы секунды
 * (`MIN_FRAME_SECONDS`, 45 кадров против 18), — но план обязан
 * получаться при любом входе, поэтому исход не отказ, а резкая смена
 * кадров: движение — улучшение, а не условие сборки.
 *
 * Одна функция на всех, кто считает время: и сетку (`frameSpansSeconds`),
 * и команду (`planSlideshow`). Реши они это порознь — подписи и речь
 * ушли бы от картинки ровно на тех роликах, где переходы отменились.
 */
export function transitionFrames(
  frames: readonly { seconds: number }[],
  motion: SlideshowMotion,
): number {
  if (motion === 'none' || frames.length < 2) return 0;
  const shortest = Math.min(
    ...frames.map((f) => Math.round(f.seconds * OUTPUT_FPS)),
  );
  return shortest >= 2 * TRANSITION_FRAMES ? TRANSITION_FRAMES : 0;
}

/**
 * Сколько держать кадр с репликой такой длительности.
 *
 * `durationSeconds` — измеренная длина mp3 из общего контракта TTS
 * (`tts.types.ts`). `null` значит «измерить не удалось», а НЕ «ноль
 * секунд»: на нуле `-t 0` уронил бы `concat` целиком, поэтому оба
 * случая и разведены в контракте.
 *
 * На `null` кадр берёт минимум — и **реплика будет обрезана** по
 * длине кадра (`atrim` в `planSlideshow`). Это не хвост: от
 * десятисекундного файла останется полторы секунды. Сделать иначе
 * нечем — растянуть кадр под неизвестную длину невозможно, а не
 * обрезать значит отдать `concat` сегменты разной длины и получить
 * уезжающий звук на всех следующих кадрах. Поэтому `null` здесь —
 * заметный, а не безобидный исход; §11 п.5 требует от него только
 * «сборка не падает».
 *
 * При включённых подписях этот исход мягче: исполнитель поднимает кадр
 * до времени чтения подписи (`captionReadingSeconds` в
 * `tutorial-captions.ts`, сквозной аудит A–G), и реплика получает
 * столько, сколько заняла бы при обычном темпе речи.
 */
export function narrationFrameSeconds(durationSeconds: number | null): number {
  if (durationSeconds === null || !Number.isFinite(durationSeconds)) {
    return MIN_FRAME_SECONDS;
  }
  return Math.max(durationSeconds + FRAME_TAIL_SECONDS, MIN_FRAME_SECONDS);
}

/**
 * Длительность кадра, когда речь одна на весь ролик (вариант А ТЗ,
 * §3): «длительность речи делим на N и раздаём кадрам поровну».
 *
 * Хвост (`FRAME_TAIL_SECONDS`) добавляется к ОБЩЕЙ длине, а не к
 * каждому кадру: пауза нужна одна — в конце, чтобы ролик не
 * обрывался на последнем слоге. Раздать её каждому кадру значило бы
 * растянуть видео на `N × 0.6` секунды тишины в середине речи.
 *
 * Прежняя константа возвращается в ЧЕТЫРЁХ случаях: длину mp3
 * измерить не удалось (`null`), измерение дало не число
 * (`NaN`/`Infinity`), дало ноль или меньше, либо кадров нет вовсе.
 * Все четыре значат одно: делить нечего, а ролик должен получиться
 * в любом случае. **Дорожка при этом обрежется**
 * по длине склейки (`2 с × N`): пятнадцать секунд речи на четырёх
 * кадрах превратятся в восемь, оборванных посреди фразы. Молча
 * этого не происходит — исполнитель пишет в лог, — но исход
 * заметный, и лечится он только починкой измерения, а не здесь.
 *
 * Второй неочевидный эффект — зажим `MIN_FRAME_SECONDS`: на тридцати
 * кадрах пятнадцать секунд речи дадут ролик в 45 секунд, из которых
 * тридцать немые. Речь не режется, но хвост длинный. Это цена
 * варианта А (одна дорожка на весь ролик) и ещё один довод за
 * покадровые реплики этапа D, где такого хвоста не бывает.
 *
 * ## С переходами (правка сквозного аудита A–G)
 *
 * `motion` обязателен, как у всех, кто считает время. Каждый стык
 * `xfade` съедает `TRANSITION_FRAMES` общей длины, а дорожка у
 * варианта А одна и режется по концу ролика. Этап G закрыл это для
 * покадровых реплик (там под нож идёт только пауза кадра) и не
 * тронул вариант А: на десяти кадрах ролик выходил на 2.7 с короче
 * склейки, а пауза в конце — 0.6 с, то есть последние две секунды
 * речи обрезались. Замерено настоящим ffmpeg: 30 с речи на десяти
 * кадрах, слышно до 27.95 с. Поэтому переходы добавляются к делимому:
 * ролик с переходами ровно той же длины по речи, что и без них.
 *
 * Прибавка — только когда переходы действительно будут. Кадр здесь
 * не короче `MIN_FRAME_SECONDS` (45 кадров), а `transitionFrames`
 * отменяет переходы лишь у кадров короче двух переходов (18), так что
 * при двух кадрах и больше они есть всегда. Режим `none` даёт прежнее
 * число символ в символ — отпечатки собранных роликов не меняются.
 */
export function evenFrameSeconds(
  speechSeconds: number | null,
  frameCount: number,
  motion: SlideshowMotion,
): number {
  if (
    speechSeconds === null ||
    !Number.isFinite(speechSeconds) ||
    speechSeconds <= 0 ||
    frameCount <= 0
  ) {
    return SECONDS_PER_FRAME;
  }
  const overlapSeconds =
    motion !== 'none' && frameCount >= 2
      ? (frameCount - 1) * TRANSITION_SECONDS
      : 0;
  return Math.max(
    (speechSeconds + FRAME_TAIL_SECONDS + overlapSeconds) / frameCount,
    MIN_FRAME_SECONDS,
  );
}

/**
 * Общий холст слайд-шоу. Кадры приходят от двух разных съёмок
 * (сценарный прогон и обучалка по сайту заказчика) и в принципе могут
 * различаться размером, а `concat` этого не прощает — см. комментарий
 * у `scaleFilters` ниже.
 *
 * 720×1560 — пропорция телефонного экрана 390×844, к которой ближе
 * всего оба источника, округлённая до чётных сторон, кратных 8 (H.264
 * любит такие).
 */
export const CANVAS = { width: 720, height: 1560 } as const;

/**
 * Один кадр слайд-шоу: чей это шаг, что показать и сколько держать.
 *
 * Длительность стала полем кадра на этапе A ТЗ
 * `docs-tz/TZ-Tutorial-Video-Voiced.md`. До этого она была
 * константой `SECONDS_PER_FRAME` на все кадры сразу, и это
 * единственное, что мешало кадру длиться ровно столько, сколько
 * звучит реплика диктора. С этапа B длительность приходит из
 * измеренной речи (`evenFrameSeconds`), то есть константой уже не
 * является; прежняя оговорка «все вызывающие передают ту же
 * константу» верна только для пути обучалки по сайту заказчика.
 *
 * `stepIndex` добавлен правкой аудита этапа A. Первая редакция
 * этапа довела номер шага от `runScenario` до имени файла в Blob и
 * там его потеряла: оба вызывающих сворачивали кадры обратно в
 * плоский `string[]`, и в план приезжал позиционный массив. То есть
 * инвариант «кадр i — это шаг i» жил внутри одной функции, а
 * снаружи держался на обещании. На этапе B к кадру привязывается
 * реплика — по номеру шага, иначе привязывать не к чему.
 */
export interface SlideshowFrame {
  /** Номер шага, ПОСЛЕ которого снят кадр (0-based). Строго
   *  возрастает по массиву; пропуски допустимы и означают ровно то,
   *  чем являются: кадра того шага нет. */
  stepIndex: number;
  url: string;
  /** Секунды. Дробные допустимы: длительность реплики измеряется, а
   *  не округляется (§4.1 ТЗ). */
  seconds: number;
  /**
   * Blob-ссылка на mp3 реплики ЭТОГО кадра, если она есть (этап B).
   *
   * Отсутствие — штатное состояние, а не недоделка: реплики нет у
   * `triggerPaidOperation` (произносить нечего), у шага, чья реплика
   * не прошла валидацию, и у всякого сценария, сгенерированного до
   * появления поля. Такой кадр получает тишину нужной длины
   * (`anullsrc`), а не выпадает из ролика: `concat` со звуком
   * требует звуковой поток у КАЖДОГО сегмента (§4.3 ТЗ).
   */
  audioUrl?: string | null;
  /**
   * Куда кликнет следующий шаг — доли ширины и высоты снимка (этап H).
   * Кружок рисуется в последнюю секунду этого кадра, перед сменой
   * экрана. Нет — кадр без указателя, команда прежняя символ в символ.
   */
  pointer?: { x: number; y: number } | null;
}

/**
 * Указатель клика (§6 ТЗ, этап H): сколько кадров он виден — последние
 * `POINTER_FRAMES` показа (1 с), но не больше половины кадра: на
 * коротком кадре указатель, висящий с самого начала, читался бы как
 * часть интерфейса, а не как «сейчас нажмём».
 */
export const POINTER_FRAMES = 30;

/** Размер кольца на холсте (720 по короткой стороне) — ≈13 % ширины,
 *  с кнопку мастера: меньше — теряется на телефоне, больше — закрывает
 *  подпись кнопки. */
const POINTER_SIZE = 96;

/**
 * Цвет кольца — тёплый оранжевый, а не акцент продукта: кнопки мастера
 * как раз акцентные (синие, `--accent` во `frontend/src/index.css`), и
 * кольцо их цвета на них бы потерялось.
 */
const POINTER_RGB = { r: 255, g: 106, b: 0 } as const;

/**
 * Источник кольца внутри `-filter_complex` — как `anullsrc` у тишины:
 * у внешнего сервиса входы — только ссылки, и готовой картинки
 * кружка ему не подать.
 *
 * Прозрачность — гауссово кольцо: мягкий край без ступенек. Заливки
 * внутри НЕТ, и это проверено на снимке: полупрозрачный оранжевый
 * поверх синей кнопки смешивался в грязно-серый и притемнял её
 * подпись, а указатель не должен мешать прочитать, КУДА жмём.
 * Выражение без запятых внутри значений нарочно: вместо `hypot(…,…)`
 * — сумма квадратов, иначе строку пришлось бы экранировать для чужого
 * разбора.
 */
function pointerRing(seconds: number): string {
  // Центр — середина картинки (47.5 при 96), а не пиксель 48: иначе
  // кольцо перекошено на полпикселя вправо-вниз (замерено при аудите
  // этапа H).
  const c = (POINTER_SIZE - 1) / 2;
  const radius = 36;
  const dist = `sqrt((X-${c})*(X-${c})+(Y-${c})*(Y-${c}))`;
  const ring = `255*exp(-(${dist}-${radius})*(${dist}-${radius})/10)`;
  return (
    `color=c=black@0:s=${POINTER_SIZE}x${POINTER_SIZE}:r=${OUTPUT_FPS}:d=${gridSeconds(
      seconds,
    )},format=rgba,` +
    `geq=r=${POINTER_RGB.r}:g=${POINTER_RGB.g}:b=${POINTER_RGB.b}:a=${ring}`
  );
}

/**
 * С какого момента показа кадра (секунды от его начала) виден
 * указатель. Порог — на полкадра раньше нужного: время кадра —
 * вещественное, и точный порог мог бы отдать первый кадр показа не той
 * стороне сравнения.
 */
function pointerFromSeconds(seconds: number): number {
  const length = Math.round(seconds * OUTPUT_FPS);
  const shown = Math.min(POINTER_FRAMES, Math.floor(length / 2));
  return Math.round(((length - shown - 0.5) / OUTPUT_FPS) * 10_000) / 10_000;
}

/**
 * Длительность готового слайд-шоу в миллисекундах.
 *
 * Живёт РЯДОМ с планом, а не у того, кто пишет её в базу: до правки
 * 27.09.2026 писатель импортировал только `SECONDS_PER_FRAME` и
 * умножал сам. Сегодня это сходилось (переходов и звука в плане нет),
 * но тот, кто добавит `xfade`, получил бы верное видео и неверное
 * число в базе — а число это человек читает на экране мастера
 * («Длительность — около N с»).
 *
 * ## Почему длина считается В КАДРАХ, посегментно
 *
 * `-t N` у входа `-loop 1` даёт не N секунд, а ближайшее ЦЕЛОЕ число
 * кадров при `-framerate 30`. Округление происходит у КАЖДОГО
 * сегмента отдельно, ДО `concat`, поэтому и считать надо посегментно:
 * сумма сырых длительностей врёт тем сильнее, чем больше кадров, и
 * врёт в обе стороны.
 *
 * До этапа D это почти не проявлялось: длительность была одна на все
 * кадры и часто попадала в сетку. Покадровые реплики (§3-бис) дают
 * произвольные вещественные длины — «измеренная речь плюс 0.6», — и
 * в сетку они не попадают никогда.
 *
 * Обе формулы проверены настоящим ffmpeg 6.1.1, и обе первые попытки
 * были неверны. Сумма сырых длительностей: план 14717 мс, файл
 * 14700 (441 кадр). Округление ВНИЗ: план 14733, файл 14767
 * (443 кадра) — ошибка просто сменила знак. Верно `Math.round`:
 * 108.906 → 109, 45 → 45, 289.151 → 289, итого 443, и это ровно то,
 * что показал `ffprobe`. Ровно `.5` здесь недостижимо на практике
 * (длина берётся измерением mp3), и какую сторону выбирает ffmpeg в
 * этой точке, не проверялось.
 */
export function slideshowDurationMs(
  frames: readonly SlideshowFrame[],
  motion: SlideshowMotion,
): number {
  const spans = frameSpansSeconds(frames, motion);
  return Math.round((spans.at(-1)?.end ?? 0) * 1000);
}

/**
 * Когда каждый кадр НА САМОМ ДЕЛЕ появляется и уходит, в секундах от
 * начала ролика.
 *
 * Один источник на две вещи сразу: отсюда считается длительность
 * ролика и отсюда же берутся таймкоды подписей (§5 ТЗ — «таймкоды
 * берутся из того же массива длительностей, что и кадры, — один
 * источник, не два»). Второй расчёт разошёлся бы с первым, и
 * расхождение накапливалось бы к концу ролика: подпись к десятому
 * кадру висела бы над девятым.
 *
 * Границы лежат на сетке кадров, а не на сырых `seconds`: `-t N` у
 * входа `-loop 1` даёт ближайшее ЦЕЛОЕ число кадров при
 * `-framerate 30`, и округление идёт у каждого сегмента отдельно, ДО
 * `concat`. Сверено настоящим ffmpeg (см. `slideshowDurationMs`).
 *
 * ## С переходами (этап G)
 *
 * `xfade` накладывает конец кадра i на начало кадра i+1, и каждый стык
 * съедает `TRANSITION_FRAMES` кадров общей длины. Кадр i+1 «начинается»
 * там, где начинается переход к нему, — в этот же миг меняются подпись
 * и речь. Не в середине перехода и не в конце: речь, начавшаяся позже
 * картинки, звучит как запоздание, а подпись обязана совпадать с речью
 * (§11 п.16). Конец кадра — начало следующего, конец последнего —
 * конец ролика. Итого ролик короче на `переход × (кадров − 1)`, и
 * именно это число `slideshowDurationMs` обязан отдать (§6 ТЗ: «xfade
 * укорачивает общую длину на время перехода — slideshowDurationMs
 * придётся поправить»).
 */
export function frameSpansSeconds(
  frames: readonly { seconds: number }[],
  motion: SlideshowMotion,
): { start: number; end: number }[] {
  const overlap = transitionFrames(frames, motion);
  const spans: { start: number; end: number }[] = [];
  let atFrame = 0;
  frames.forEach((frame, i) => {
    const start = atFrame;
    const length = Math.round(frame.seconds * OUTPUT_FPS);
    // Каждый кадр, кроме последнего, отдаёт переходу хвост: следующий
    // начинается раньше, чем этот кончился бы сам.
    atFrame += i < frames.length - 1 ? length - overlap : length;
    spans.push({ start: start / OUTPUT_FPS, end: atFrame / OUTPUT_FPS });
  });
  return spans;
}

/**
 * Сколько кадр держится НА САМОМ ДЕЛЕ — заказанные секунды,
 * притянутые к сетке 30 к/с.
 *
 * Отдельно от `frameSpansSeconds`, хотя правило то же: там границы
 * накапливаются, и длина кадра как разность двух накопленных чисел
 * тянет за собой погрешность сложения (3.6333333333333337 вместо
 * 3.6333333333333333). В команду ffmpeg уезжает именно это число, и
 * лишние знаки там — мусор, который вдобавок меняет
 * ключ идемпотентности задачи.
 */
export function gridSeconds(seconds: number): number {
  return Math.round(seconds * OUTPUT_FPS) / OUTPUT_FPS;
}

/**
 * Зум внутри кадра: 1.00 → `ZOOM_TO` за всё время показа, к центру.
 *
 * `perspective`, а не `zoompan`, хотя §6 ТЗ называет второй, — и это
 * решено замером, а не вкусом. `zoompan` кадрирует ЦЕЛЫМИ пикселями:
 * при зуме в 4 % за три секунды точка у края кадра движется на 0.13
 * пикселя за кадр, и `zoompan` на холсте 720×1560 из 90 кадров 61 раз
 * стоит на месте, а 12 раз дёргается НАЗАД на целый пиксель
 * (замерено ffmpeg 6.1.1 по вертикальной линии у края кадра). Это и
 * есть известное «дрожание zoompan», и на тексте интерфейса оно
 * читается как брак. Лечат его обычно увеличением перед `zoompan` —
 * вчетверо: дрожь меньше, но ступеньки остаются (34 остановки). А
 * `perspective` интерполирует с субпиксельной точностью: ни одной
 * остановки, ни одного шага назад, наибольший шаг 0.38 пикселя. Цена —
 * время сборки: в шесть раз дольше `zoompan`, см. запись этапа G в ТЗ.
 *
 * `in` — номер кадра НА ВХОДЕ этого фильтра, то есть свой у каждого
 * кадра слайд-шоу, от нуля. Выражения без запятых и кавычек нарочно:
 * строка уходит во внешний сервис внутри `-filter_complex "…"`, и
 * каждый лишний уровень экранирования — повод разойтись с тем, как
 * этот сервис разбирает команду.
 */
function zoomFilter(seconds: number): string {
  const last = Math.max(Math.round(seconds * OUTPUT_FPS) - 1, 1);
  // Доля, на которую каждая сторона источника уходит внутрь, — чтобы
  // видимая часть стала в `z` раз меньше: (1 − 1/z) / 2.
  // `toPrecision`: `1.04 - 1` в двоичной арифметике —
  // 0.040000000000000036, и этот хвост уехал бы в команду, а с ней в
  // ключ идемпотентности задачи.
  const gain = Number((ZOOM_TO - 1).toPrecision(6));
  const f = `((1-1/(1+${gain}*in/${last}))/2)`;
  const lo = (side: string) => `${side}*${f}`;
  const hi = (side: string) => `${side}*(1-${f})`;
  return (
    `perspective=x0=${lo('W')}:y0=${lo('H')}:x1=${hi('W')}:y1=${lo('H')}:` +
    `x2=${lo('W')}:y2=${hi('H')}:x3=${hi('W')}:y3=${hi('H')}:` +
    `interpolation=cubic:eval=frame`
  );
}

/**
 * Снятые кадры → кадры плана, все одной длины.
 *
 * Номер шага приходит С КАДРОМ и не трогается; функция добавляет
 * только длительность — ОДНУ на все кадры.
 *
 * Существует ради того, чтобы `SECONDS_PER_FRAME` не пришлось
 * импортировать вызывающему: длительность кадра знает модуль плана и
 * только он (шов в `scripts/check-docs.mjs`).
 *
 * Сценарный путь её больше НЕ зовёт, и прежняя строка «именно так
 * обязан звать сценарный путь» устарела на этапе D: с покадровыми
 * репликами каждый кадр висит столько, сколько звучит его реплика, и
 * одной длительности на всех больше не бывает — исполнитель собирает
 * `SlideshowFrame` сам. Живым вызывающим остался `uniformFrames`, то
 * есть обучалка по сайту заказчика: там кадры и правда все по две
 * секунды.
 */
export function framesFromSteps(
  shots: readonly { stepIndex: number; url: string }[],
  seconds: number = SECONDS_PER_FRAME,
): SlideshowFrame[] {
  return shots.map(({ stepIndex, url }) => ({ stepIndex, url, seconds }));
}

/**
 * Кадры одинаковой длины, снятые ПОДРЯД, без пропусков: номер шага
 * совпадает с позицией в массиве.
 *
 * Это не «удобная обёртка на все случаи», а утверждение о входе, и
 * годится оно ровно там, где сплошная нумерация гарантирована
 * устройством пути. Сегодня такой путь один — обучалка по сайту
 * заказчика: кадры туда кладёт обход сайта
 * (`client-site-tutorial.service.ts`), а не `runScenario`, они
 * лежат под `draftFramePathname(id, 0..n-1)` и пропасть поодиночке
 * не могут. Сценарный путь так вызывать НЕЛЬЗЯ: там кадр снимается
 * best-effort и пропадает молча — номер шага надо брать у кадра
 * (`ScenarioFrame.stepIndex`), а не выводить из позиции.
 *
 * Отдельная функция, а не умолчание у `planSlideshow`: умолчание
 * пряталось бы в подписи и позволяло бы забыть и длительность, и
 * номер шага там, где они уже важны.
 */
export function uniformFrames(
  urls: readonly string[],
  seconds: number = SECONDS_PER_FRAME,
): SlideshowFrame[] {
  return framesFromSteps(
    urls.map((url, stepIndex) => ({ stepIndex, url })),
    seconds,
  );
}

/** Потолок числа кадров одного сценария. Выше `MAX_SCENARIO_STEPS`
 * (`scenario-steps.ts`, этап 94: до 30 шагов), то есть на сценарном
 * пути недостижим в принципе — чисто оборонительная защита
 * ffmpeg-команды от неограниченного роста `-filter_complex` на
 * случай другого источника кадров. Прежняя формулировка
 * «совпадает… плюс небольшой запас» описывала 40 как 30. */
export const MAX_SLIDESHOW_FRAMES = 40;

export interface SlideshowPlan {
  inputs: Record<string, string>;
  outputs: string[];
  commands: string[];
  /**
   * Длительность собранного ролика в миллисекундах — считается ЗДЕСЬ
   * и отдаётся вместе с командой.
   *
   * Так, а не отдельной функцией у вызывающего: до этапа A писатель
   * умножал `frameCount × SECONDS_PER_FRAME` у себя, за три модуля от
   * места, где строится команда. Пока все кадры были одинаковой
   * длины, это сходилось; с разными длительностями разошлось бы
   * молча, а число это человек читает на экране («Длительность —
   * около N с»).
   */
  durationMs: number;
  /**
   * Режим движения, который план применил (этап G): может быть
   * скромнее заказанного — см. `appliedMotion`. Отдаётся наружу, чтобы
   * исполнитель сказал об этом в журнале, а не оставил оператора
   * гадать, почему зума нет.
   */
  motion: SlideshowMotion;
  /** Имя единственного выходного файла — то же значение, что
   * `outputs[0]`, отдельным полем ради читаемости на стороне вызывающего
   * кода (не нужно доставать из массива по индексу). */
  outputName: string;
}

/**
 * Отпечаток входов сборки — «из этого получится побайтово тот же
 * mp4».
 *
 * §7.2 ТЗ обещает: «ролики пересобираются, когда меняется интерфейс
 * или текст шага, а не по расписанию». Ночной прогон при этом идёт
 * по всем сценариям каждую ночь, и без отпечатка он отправлял
 * платную задачу ffmpeg каждый раз — на те же кадры, ту же
 * (закешированную) дорожку и тот же результат. Сравнивать было не с
 * чем: кадры транзитные, `blobUrl` — это выход, а не вход.
 *
 * Считается по БАЙТАМ кадров, а не по номеру версии сценария. Обе
 * причины пересборки из §7.2 обязаны сработать, а «изменился
 * интерфейс» номером версии сценария не ловится вовсе: шаги те же,
 * экран другой.
 *
 * В отпечаток входят и длительности, и ссылки на дорожки — общую
 * (вариант А) и покадровые (вариант Б, этап D): при той же картинке
 * другая речь — другой ролик. `\u0000` разделителем — тот же приём,
 * что у `voiceoverCachePathname`: без него склейка соседних полей
 * даёт совпадение там, где его нет.
 *
 * Покадровая дорожка обязана входить наравне с общей. Без неё правка
 * ОДНОЙ реплики не меняла бы отпечаток (кадры-то те же), пересборка
 * не заказывалась бы — и исправленный текст не звучал бы никогда,
 * молча.
 */
export function slideshowContentHash(
  frames: readonly {
    stepIndex: number;
    bytes: Uint8Array;
    seconds: number;
    audioUrl?: string | null;
    pointer?: { x: number; y: number } | null;
  }[],
  voiceoverUrl: string | null,
  /**
   * СОДЕРЖИМОЕ `.ass` с подписями, а не ссылка на него (этап E).
   *
   * Ссылка не годится: файл лежит под префиксом АКТИВА, то есть у
   * каждой сборки свой путь, и отпечаток не совпадал бы никогда —
   * ровно та ночная пересборка, которую отпечаток и заводился
   * прекращать. Содержимое же меняется тогда и только тогда, когда
   * меняется картинка: правка реплики, сдвиг длительностей,
   * выключение настройки (пустая строка).
   */
  captionsAss: string | null,
  /**
   * Движение (этап G) меняет картинку при тех же кадрах, звуке и
   * подписях — немой ролик без подписей иначе вообще не отличил бы
   * «с переходами» от «без». Не войди режим в отпечаток, переключатель
   * на витрине не менял бы уже собранные ролики никогда.
   *
   * Режим `none` в отпечаток НЕ пишется — нарочно. Иначе сам деплой
   * этапа сменил бы отпечаток у всех роликов разом, и первая же ночь
   * пересобрала бы весь набор (пятьдесят платных задач) ради того же
   * самого mp4: по умолчанию движение выключено, и видео не меняется.
   */
  motion: SlideshowMotion,
): string {
  const h = createHash('sha256');
  h.update(String(voiceoverUrl ?? ''));
  h.update('\u0000');
  h.update(String(captionsAss ?? ''));
  if (motion !== 'none') {
    h.update('\u0000motion:');
    h.update(motion);
  }
  for (const frame of frames) {
    h.update('\u0000');
    h.update(`${frame.stepIndex}:${frame.seconds}:${frame.audioUrl ?? ''}:`);
    // Указатель меняет картинку при тех же байтах снимка (этап H), и
    // без него в отпечатке выключатель указателя не трогал бы уже
    // собранные ролики. Пишется ТОЛЬКО когда он есть — отпечатки
    // роликов без указателя остаются прежними, и деплой этапа ничего
    // не пересобирает.
    if (frame.pointer) {
      h.update(`p${frame.pointer.x}/${frame.pointer.y}:`);
    }
    h.update(Buffer.from(frame.bytes));
  }
  return h.digest('hex');
}

/**
 * `frames` — кадры по порядку съёмки: публичная Blob-ссылка (PNG) и
 * сколько секунд держать. `null` — ПЯТЬ случаев, и вызывающий обязан
 * обработать их сам, не вызывая `submit()` с бессмысленной, опасно
 * большой или заведомо падающей командой:
 *
 * 1. собирать нечего (0 кадров);
 * 2. кадров больше потолка (`MAX_SLIDESHOW_FRAMES`);
 * 3. у кадра неположительная или неконечная длительность;
 * 4. номера шагов не возрастают строго;
 * 5. звук задан ДВАЖДЫ — и покадрово, и дорожкой на весь ролик.
 *
 * Третий случай появился вместе с покадровыми длительностями (этап A)
 * и до этапа B недостижим: все вызывающие передают константу. Зато с
 * этапа B длительность приходит измерением mp3 — и `0`, `NaN`,
 * `Infinity` становятся достижимыми входами, а не теорией.
 *
 * ## Три вида звука, и почему они не смешиваются
 *
 * - **Немой ролик** — ни у одного кадра нет `audioUrl`, `voiceoverUrl`
 *   не передан. `concat=…:a=0`, без `-c:a` и без `-shortest` —
 *   отличие от команды до этапа B ровно одно: явная частота входа
 *   (`-framerate`), которую добавили всем трём видам, чтобы длина
 *   файла сходилась с `durationMs`. Строка закреплена целиком
 *   тестом: путь обучалки по сайту заказчика меняться не должен.
 * - **Реплика на кадр** (вариант Б ТЗ, этап D) — у кадров свои
 *   `audioUrl`. Сегменты подаются попарно `[v][a]`, немым кадрам
 *   подставляется `anullsrc`: `concat` с `a=1` требует звуковой поток
 *   у КАЖДОГО сегмента, а входы кадров — PNG, звука у них нет в
 *   принципе (§4.3 ТЗ).
 * - **Одна дорожка на весь ролик** (вариант А ТЗ, этап B) —
 *   `voiceoverUrl`. Видео склеивается без звука, дорожка ложится
 *   поверх готовой склейки.
 *
 * Последние два вместе — отказ, а не «смешаем». Это два разных
 * ответа на вопрос «что звучит на кадре N», и молчаливый выбор одного
 * из них дал бы ролик, который никто не заказывал.
 *
 * ## Движение (этап G)
 *
 * `motion: 'none'` — команда ровно та же, что до этапа, символ в
 * символ: путь обучалки по сайту заказчика её и получает (§8 ТЗ —
 * «не трогает обучалку по сайту заказчика»), и строка закреплена
 * тестом целиком.
 *
 * С переходами кадры склеивает не `concat`, а цепочка `xfade`, и звук
 * уже не может ехать с картинкой одной парой `[v][a]` — у картинки
 * стыки внахлёст, у звука нет. Поэтому звук при переходах собирается
 * своим `concat` из сегментов длиной «от начала кадра до начала
 * следующего» по `frameSpansSeconds`: у озвученного кадра это речь
 * плюс пауза минус переход, то есть под нож идёт только тишина хвоста
 * (пауза 0.6 с против перехода 0.3), а речь не режется никогда.
 */
export function planSlideshow(
  frames: readonly SlideshowFrame[],
  opts: {
    outputName?: string;
    voiceoverUrl?: string | null;
    /** Ссылка на `.ass` с подписями (§5 ТЗ, этап E). `null` — ролик
     *  без подписей: настройка выключена или реплик нет. */
    captionsUrl?: string | null;
    /** Движение (этап G). Обязательно и без умолчания — см.
     *  `SlideshowMotion`. */
    motion: SlideshowMotion;
  },
): SlideshowPlan | null {
  const outputName = opts.outputName ?? 'tutorial.mp4';
  const motion = appliedMotion(frames, opts.motion);
  const voiceoverUrl = opts.voiceoverUrl ?? null;
  const captionsUrl = opts.captionsUrl ?? null;
  if (frames.length === 0 || frames.length > MAX_SLIDESHOW_FRAMES) {
    return null;
  }
  // Неположительная длительность — это не «покажем мгновенно», а
  // испорченная команда: `-t 0` даёт сегмент без кадров, и `concat`
  // падает целиком. Отказ здесь дешевле разбирательства с внешним
  // сервисом (тот же принцип, что у потолка числа кадров выше).
  //
  // `Number.isFinite`, а не только `> 0`: `Infinity > 0` — правда, и
  // `-t Infinity` ушёл бы во внешний сервис как валидная команда,
  // которая никогда не завершится. С этапа B длительность приходит
  // измерением mp3, то есть делением, — `Infinity` и `NaN` там не
  // экзотика (найдено аудитом этапа A).
  if (frames.some((f) => !(Number.isFinite(f.seconds) && f.seconds > 0))) {
    return null;
  }
  // Номера шагов обязаны строго возрастать. Не педантизм: ключ входа
  // ниже строится из номера шага, а `inputs` — объект. Два кадра с
  // одним номером дали бы ОДИН ключ и ДВА `-i`, то есть команду, где
  // подставится не тот файл, — молча, без ошибки от ffmpeg-api.
  // Перепутанный порядок сломал бы хронологию ролика так же тихо.
  if (
    frames.some(
      (f, i) =>
        !Number.isInteger(f.stepIndex) ||
        f.stepIndex < 0 ||
        (i > 0 && f.stepIndex <= frames[i - 1].stepIndex),
    )
  ) {
    return null;
  }
  const voiced = frames.filter((f) => !!f.audioUrl);
  if (voiced.length > 0 && voiceoverUrl) return null;

  const inputs: Record<string, string> = {};
  const inputArgs: string[] = [];
  const scaleFilters: string[] = [];

  frames.forEach(({ url, seconds, stepIndex, pointer }, i) => {
    // Ключ входа и метка потока — по номеру ШАГА: команду читает
    // человек, разбирая неудачную сборку, и `frame3` обязано
    // означать третий шаг, а не третий уцелевший кадр. Пропавший
    // кадр оставляет дыру в нумерации — ровно как в именах файлов.
    //
    // А вот `[${i}:v]` — ПОЗИЦИОННЫЙ и таким останется: это индекс
    // входа в порядке аргументов `-i`, его нумерует сам ffmpeg, и
    // подставить туда номер шага значит сослаться на несуществующий
    // вход. Расхождение между `[${i}:v]` и `[v${stepIndex}]` в одной
    // строке нарочное, а не опечатка.
    const key = `frame${stepIndex}`;
    inputs[key] = url;
    // `-framerate ${OUTPUT_FPS}` перед `-loop 1` — не украшение.
    // Без него ffmpeg берёт для PNG частоту входа 25 к/с, режет `-t`
    // по ней ВВЕРХ и выдаёт кадр длиннее заказанного: при `-t 2.7`
    // это 68 кадров, то есть 2.72 с. Пока длительности были целыми
    // двойками, 50 кадров при 25 к/с сходились точно; с дробными
    // длительностями этапа B каждый кадр добавлял до 40 мс, и ролик
    // из тридцати кадров разъезжался с `durationMs` на секунду с
    // лишним. Число это человек читает на экране мастера, а §11 п.4
    // требует сверять его `ffprobe`, а не на глаз. Найдено аудитом
    // этапа B и измерено: 7.367 с при объявленных 7.300.
    inputArgs.push(
      `-framerate ${OUTPUT_FPS} -loop 1 -t ${seconds} -i {{${key}}}`,
    );
    // Приведение к ОБЩЕМУ холсту, а не просто к чётным сторонам.
    //
    // Найдено аудитом 27.09.2026. Прежний `scale=trunc(iw/2)*2:…`
    // делал стороны чётными, но размеры кадров между собой не
    // равнял, — а `concat` требует совпадения ширины и высоты. То,
    // что сборка работала, держалось на соглашении: сценарный путь
    // снимает одним вьюпортом, путь сайта заказчика — другим, но
    // внутри одного прогона одинаковым. Любой кадр иного размера
    // (сменили вьюпорт, досняли один экран отдельно, поменяли
    // плотность) ронял бы задачу ЦЕЛИКОМ, без частичного результата.
    //
    // `force_original_aspect_ratio=decrease` вписывает кадр внутрь
    // холста без обрезки, `pad` дополняет чёрным по центру. Кадр
    // никогда не растягивается: пропорции экрана важнее заполнения
    // холста, растянутый интерфейс выглядит поломкой.
    const zoom = motion === 'fade+zoom' ? `,${zoomFilter(seconds)}` : '';
    if (!pointer) {
      scaleFilters.push(
        `[${i}:v]scale=${CANVAS.width}:${CANVAS.height}:` +
          `force_original_aspect_ratio=decrease,` +
          `pad=${CANVAS.width}:${CANVAS.height}:(ow-iw)/2:(oh-ih)/2,` +
          `setsar=1${zoom}[v${stepIndex}]`,
      );
      return;
    }
    // Указатель (этап H) ложится на снимок, уже вписанный в холст, но
    // ещё БЕЗ полей: `main_w`/`main_h` у `overlay` — это ровно размер
    // картинки снимка, и доли из замера переводятся в пиксели без
    // знания пропорций экрана. И ДО зума: приближение уводит кнопку к
    // краю, и кольцо обязано уезжать вместе с ней, а не висеть там,
    // где кнопка была в начале кадра.
    scaleFilters.push(
      `[${i}:v]scale=${CANVAS.width}:${CANVAS.height}:` +
        `force_original_aspect_ratio=decrease[sc${stepIndex}]`,
      `${pointerRing(seconds)}[pr${stepIndex}]`,
      // `+1` — не опечатка. `overlay` работает в yuv420 и кладёт
      // накладку по сетке цветности: положение округляется ВНИЗ до
      // чётного пикселя, то есть кольцо уезжало до двух пикселей
      // влево-вверх (замерено ffmpeg 6.1.1 при аудите этапа H).
      // Сдвиг на единицу делает это округлением к ближайшему чётному —
      // ошибка ±1 вместо от −2 до 0.
      `[sc${stepIndex}][pr${stepIndex}]overlay=` +
        `x=main_w*${pointer.x}-overlay_w/2+1:y=main_h*${pointer.y}-overlay_h/2+1:` +
        `enable=1+sgn(t-${pointerFromSeconds(seconds)}),` +
        `pad=${CANVAS.width}:${CANVAS.height}:(ow-iw)/2:(oh-ih)/2,` +
        `setsar=1${zoom}[v${stepIndex}]`,
    );
  });

  const overlap = transitionFrames(frames, motion);
  // Сетка времени — ОДНА на картинку, звук, подписи и длительность:
  // та же функция, по которой вызывающий построил `.ass`.
  const spans = frameSpansSeconds(frames, motion);

  // Звуковые входы идут ПОСЛЕ всех кадров — нумерацию входов ведёт
  // ffmpeg по порядку `-i`, и вставить mp3 между кадрами значило бы
  // сдвинуть все `[N:v]`.
  const audioFilters: string[] = [];
  let audioInputIndex = frames.length;
  // Длины сегментов — ПО СЕТКЕ КАДРОВ, той же, по которой считается
  // длительность ролика. Звук выравнивается не по заказанным
  // `seconds`, а по той длине, которую реально получит его кадр.
  //
  // Разница мелкая на кадр и убийственная на тридцати. `-t N` у
  // входа `-loop 1` даёт ближайшее ЦЕЛОЕ число кадров, а
  // `atrim=0:N` режет звук РОВНО по N: сегменты выходят разной
  // длины, `concat` берёт длину по самому длинному, и сдвиг
  // копится. Замерено настоящим ffmpeg: на десяти кадрах +33 мс, на
  // тридцати +133 мс, и к концу ролика подпись висела над
  // предыдущим кадром, а картинка отставала от речи (находка аудита
  // этапа E).
  //
  // С переходами (этап G) сегмент звука — не длина кадра, а отрезок
  // «от его начала до начала следующего»: кадры идут внахлёст, звук —
  // встык. И режется он ЦЕЛЫМИ СЭМПЛАМИ (`SAMPLES_PER_FRAME`), а не
  // секундами: у склейки звука отдельным `concat` нет пары `[v][a]`,
  // которая выравнивала бы каждый сегмент по картинке, и доли сэмпла,
  // потерянные на каждом стыке, копились бы в недостачу, по которой
  // `-shortest` отрезал бы последний кадр (замерено, см.
  // `SAMPLES_PER_FRAME`).
  //
  // Без переходов строка прежняя, символ в символ: там пара `[v][a]`
  // в общем `concat` выравнивает каждый сегмент сама, и настоящий
  // ffmpeg на тридцати кадрах дал длину, совпавшую с планом до кадра.
  const onGrid = frames.map((f) => gridSeconds(f.seconds));
  const segmentSamples = frames.map(
    (f, i) =>
      (Math.round(f.seconds * OUTPUT_FPS) -
        (i < frames.length - 1 ? overlap : 0)) *
      SAMPLES_PER_FRAME,
  );
  if (voiced.length > 0) {
    for (const [i, { stepIndex, audioUrl }] of frames.entries()) {
      const seconds = onGrid[i];
      if (audioUrl) {
        const key = `voice${stepIndex}`;
        inputs[key] = audioUrl;
        inputArgs.push(`-i {{${key}}}`);
        // `apad` + `atrim` вместо «как есть»: сегмент обязан длиться
        // РОВНО столько же, сколько его кадр. Реплика короче кадра
        // (кадр = реплика + пауза) — `apad` дотягивает тишиной;
        // длиннее (нераспознанный mp3 дал минимум, см.
        // `narrationFrameSeconds`) — `atrim` режет. Без выравнивания
        // `concat` берёт длину сегмента по САМОМУ ДЛИННОМУ потоку, и
        // звук начал бы уезжать от картинки, накапливая сдвиг от
        // кадра к кадру.
        //
        // `aresample`/`aformat` — приведение к общему формату: у
        // `concat` то же требование к звуку, что к видео.
        audioFilters.push(
          `[${audioInputIndex}:a]aresample=${AUDIO_RATE},` +
            `aformat=sample_fmts=fltp:channel_layouts=stereo,` +
            (overlap === 0
              ? `apad,atrim=0:${seconds}`
              : `apad,atrim=end_sample=${segmentSamples[i]}`) +
            `,asetpts=N/SR/TB[a${stepIndex}]`,
        );
        audioInputIndex++;
      } else {
        // Тишина СОЗДАЁТСЯ фильтром-источником, а не подаётся входом
        // `-f lavfi -i anullsrc`: входы у ffmpeg-api — это словарь
        // ссылок (`inputs: Record<string, string>`), и вход без
        // ссылки туда не кладётся. Как источник внутри
        // `-filter_complex` тот же `anullsrc` работает и ничего не
        // требует от вызывающего.
        audioFilters.push(
          `anullsrc=channel_layout=stereo:sample_rate=${AUDIO_RATE}` +
            (overlap === 0
              ? `:d=${seconds}`
              : `,atrim=end_sample=${segmentSamples[i]}`) +
            `[a${stepIndex}]`,
        );
      }
    }
  }

  const withFrameAudio = voiced.length > 0;
  const joins: string[] = [];
  if (overlap === 0) {
    // Без переходов — прежняя склейка; немой ролик — символ в символ
    // (путь обучалки по сайту заказчика), у звука — хвост в кадр.
    const concatInputs = frames
      .map((f) =>
        withFrameAudio
          ? `[v${f.stepIndex}][a${f.stepIndex}]`
          : `[v${f.stepIndex}]`,
      )
      .join('');
    joins.push(
      `${concatInputs}concat=n=${frames.length}:v=1:a=${
        withFrameAudio ? 1 : 0
      }[outv]${withFrameAudio ? '[acat]' : ''}`,
    );
    // Хвост в кадр и здесь (`AUDIO_TAIL_SAMPLES`): пара `[v][a]`
    // выравнивает сегменты между собой, но не конец ролика — звук
    // выходит на доли сэмпла короче картинки, и `-shortest` на части
    // раскладок срезал последний кадр. Замерено: 25 кадров с
    // репликами, 2065 кадров в файле при 2066 в плане (дефект этапа D,
    // найден аудитом этапа G на случайных раскладках).
    if (withFrameAudio) {
      joins.push(`[acat]apad=pad_len=${AUDIO_TAIL_SAMPLES}[outa]`);
    }
  } else {
    // Цепочка `xfade`: каждый следующий кадр въезжает поверх
    // накопленной склейки. `offset` — начало перехода, то есть начало
    // кадра по той же сетке (`spans`); секунды пишутся из ЦЕЛОГО
    // числа кадров, делённого один раз, иначе `xfade` пересчитал бы
    // мусорные знаки в метку времени и мог промахнуться на кадр.
    // Метки `[xf…]` — свои, чтобы не совпасть с `[v{шаг}]` кадров.
    let previous = `[v${frames[0].stepIndex}]`;
    for (let i = 1; i < frames.length; i++) {
      const out = i === frames.length - 1 ? '[outv]' : `[xf${i}]`;
      const offset = Math.round(spans[i].start * OUTPUT_FPS) / OUTPUT_FPS;
      joins.push(
        `${previous}[v${frames[i].stepIndex}]xfade=transition=fade:` +
          `duration=${overlap / OUTPUT_FPS}:offset=${offset}${out}`,
      );
      previous = out;
    }
    if (withFrameAudio) {
      joins.push(
        `${frames.map((f) => `[a${f.stepIndex}]`).join('')}` +
          `concat=n=${frames.length}:v=0:a=1,` +
          `apad=pad_len=${AUDIO_TAIL_SAMPLES}[outa]`,
      );
    }
  }

  const durationMs = slideshowDurationMs(frames, motion);
  const totalFrames = Math.round((spans.at(-1)?.end ?? 0) * OUTPUT_FPS);
  const parts = [...scaleFilters, ...audioFilters, ...joins];
  const maps = ['-map "[outv]"'];

  if (voiceoverUrl) {
    // Вариант А: одна дорожка поверх всей склейки. Выравнивается по
    // ОБЩЕЙ длине тем же приёмом, что покадровые сегменты, — речь
    // короче ролика дотягивается тишиной, длиннее обрезается. Иначе
    // длина файла разошлась бы с `durationMs`, который уже записан в
    // базу и показан человеку.
    inputs.voiceover = voiceoverUrl;
    inputArgs.push('-i {{voiceover}}');
    parts.push(
      `[${frames.length}:a]aresample=${AUDIO_RATE},` +
        `aformat=sample_fmts=fltp:channel_layouts=stereo,` +
        // Целыми сэмплами, а не `durationMs / 1000`: тот округлён до
        // миллисекунды и в трети раскладок выходит на долю
        // миллисекунды КОРОЧЕ картинки — и `-shortest` отрезал
        // последний кадр, а в базе оставалась длина на 33 мс больше
        // файла (дефект этапа B, найден аудитом этапа G на настоящем
        // ffmpeg: 186 кадров в файле при 187 в плане).
        // Плюс хвост в кадр — см. `AUDIO_TAIL_SAMPLES`.
        `apad,atrim=end_sample=${
          totalFrames * SAMPLES_PER_FRAME + AUDIO_TAIL_SAMPLES
        },asetpts=N/SR/TB[outa]`,
    );
  }

  const hasAudio = withFrameAudio || !!voiceoverUrl;

  // Подписи (§5 ТЗ, этап E) — ФИЛЬТР над готовой склейкой, а не
  // отдельный `-i`, и это не выбор из двух рабочих способов.
  // Хостед-сервис подставляет `{{ключ}}` ВЕЗДЕ в строке команды, а не
  // только после `-i` (`ffmpeg-api.service.ts`), а `subtitles=`
  // читает файл ПО ПУТИ, а не по номеру потока. Поданный входом
  // `.ass` стал бы для ffmpeg ещё одним потоком и сломал бы
  // нумерацию `[N:a]` у дорожек — молча, потому что номера остались
  // бы валидными, просто указывали бы не туда.
  //
  // Поверх `concat`, а не на каждый кадр: подпись живёт ровно свои
  // секунды по таймкодам внутри файла, и накладывать её покадрово
  // значило бы повторить ту же раскладку второй раз.
  if (captionsUrl) {
    inputs.captions = captionsUrl;
    parts.push(`[outv]subtitles={{captions}}[outc]`);
    maps[0] = '-map "[outc]"';
  }

  if (hasAudio) maps.push('-map "[outa]"');

  // `-shortest` только при звуке, и по той же причине, что
  // `-framerate` выше: aac пакует по 1024 сэмпла, поэтому звуковой
  // поток всегда чуть ДЛИННЕЕ заказанного (до 23 мс), и без
  // `-shortest` эта добавка попадала бы в длину файла. С ним файл
  // кончается там, где кончается видео, а видео теперь ровно
  // `durationMs`. Немому ролику `-shortest` не нужен: обрезать
  // нечем и не по чему.
  // Выход — ЧЕРЕЗ ПЛЕЙСХОЛДЕР `{{имя}}`, как входы (находка боевого
  // прогона 29.09.2026).
  //
  // Голым именем файла эта команда писала mp4 в рабочий каталог самого
  // ffmpeg, а хостед-сервис забирает выход по ТОМУ пути, который сам
  // подставил бы вместо `{{имя}}`. Он честно отвечал
  // «1 output upload(s) failed: tutorial.mp4: expected output was not
  // created» — то есть ffmpeg отработал, а забирать оказалось нечего.
  // Ни один ролик обучалки не собрался НИ РАЗУ, и заметить это по
  // коду было нельзя: команда валидна и локально даёт правильный mp4.
  //
  // Все остальные строители команд в проекте (`common/postprod.ts`,
  // `reframe.ts`, `watermark.ts`, `poster-frame.ts`) пишут выход
  // плейсхолдером с самого начала — это и есть контракт сервиса,
  // просто сборка обучалки его не соблюдала. Шов в
  // `scripts/check-docs.mjs` теперь сторожит правило целиком.
  //
  // `-c:v` ЯВНО, а не умолчанием ffmpeg: умолчание — это догадка о
  // чужом контейнере, о котором мы не знаем ничего. `veryfast` и
  // `crf 18` — те же, что у проверенного пути постобработки; на
  // статичных снимках экрана разница в размере невелика, а `medium`
  // по умолчанию вдвое дольше и ближе к таймауту сервиса.
  //
  // `+faststart` — тоже как у соседей: без него плеер не начнёт
  // играть, пока не скачает файл целиком.
  const command =
    `${inputArgs.join(' ')} -filter_complex "${parts.join(';')}" ` +
    `${maps.join(' ')} -r ${OUTPUT_FPS} ` +
    `-c:v libx264 -preset veryfast -crf ${OUTPUT_CRF} -pix_fmt yuv420p` +
    `${hasAudio ? ' -c:a aac -b:a 192k -shortest' : ''}` +
    ` -movflags +faststart {{${outputName}}}`;

  return {
    inputs,
    outputs: [outputName],
    commands: [command],
    outputName,
    durationMs,
    motion,
  };
}
