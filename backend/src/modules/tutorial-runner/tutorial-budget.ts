/**
 * Суточный денежный потолок ночной работы обучалки — находка сквозного
 * аудита 29.09.2026.
 *
 * ## Зачем
 *
 * До него потолков у подсистемы было три: `RUN_BATCH_LIMIT` (сколько
 * строк за тик), бюджеты времени у обоих кронов и `MAX_NARRATION_LENGTH`
 * (длина реплики). Все три честные и мягкие — при достижении пишут в
 * журнал и переносят остаток на следующую ночь. И все три считают штуки
 * и секунды. На вопрос «сколько денег мы готовы отдать за ночь» не
 * отвечал ни один: `AiUsageService.budget()` в этой подсистеме не
 * звался нигде.
 *
 * Это заметно только на фоне ТЗ. §7.2 закладывает ≈$1.50 на полный
 * набор из пятидесяти роликов и называет величину РАЗОВОЙ. Ночной же
 * прогон идёт каждую ночь, и в худшем случае — тридцать сценариев по
 * тридцать реплик — объём синтеза на порядок больше того, из которого
 * считали. Плюс до тридцати сборок. Ничто из этого не остановилось бы
 * само.
 *
 * ## Один потолок на три операции
 *
 * Генерация сценариев, синтез озвучки и сборка ролика тратят в разных
 * местах, но вопрос у них общий. Раздельные потолки позволили бы
 * каждому остаться в своих рамках при втрое большей сумме — то есть
 * ответили бы не на тот вопрос, который задан.
 *
 * ## Что он НЕ делает
 *
 * Не возвращает денег и не отменяет отправленного. Достигнутый потолок
 * значит «на сегодня хватит»: остаток переносится на следующую ночь тем
 * же механизмом, что при исчерпанном бюджете времени, а ротация
 * `lastRunAt asc nulls first` даёт отложенным пройти первыми.
 *
 * Не защищает от состязания двух процессов: потраченное считывается
 * один раз за тик и дальше ведётся в памяти (иначе перед каждой из
 * тридцати дорожек каждого из тридцати сценариев пришлось бы делать
 * агрегат по журналу — девятьсот поездок в базу ради одного числа).
 * Оба крона обучалки берут джоб-замок, то есть параллельных тиков в
 * норме не бывает, а потолок ловит убегание за ночь, а не гонку за
 * секунду.
 */

import { AiUsageService } from '../ai-usage/ai-usage.service';
import { PlatformSettingsService } from '../../common/platform-settings.service';
import {
  parseTutorialBudgetSetting,
  TUTORIAL_BUDGET_SETTING_KEY,
} from './tutorial-voice';

/**
 * Три операции, которые тратят деньги ночью. Список закрытый и живёт
 * здесь один: разойдись он с тем, что пишет `record()`, — и потолок
 * молча перестал бы видеть часть расхода.
 */
export const TUTORIAL_PAID_OPERATIONS = [
  'tutorial-scenario-generate',
  'tutorial-voiceover',
  'tutorial-video-assembly',
] as const;

/** Состояние потолка внутри одного тика. `limitMicroUsd: null` —
 *  потолок снят настройкой (`off`), считаем только для журнала. */
export interface TutorialBudget {
  limitMicroUsd: number | null;
  spentMicroUsd: number;
}

/**
 * Потолок выбран — дальше тратить нельзя.
 *
 * Отдельной функцией, а не сравнением по месту: у неё один смысл на
 * всех трёх вызывающих, и мутация «сравнить не в ту сторону» ловится
 * одним тестом, а не тремя.
 */
export function budgetExhausted(budget: TutorialBudget): boolean {
  return (
    budget.limitMicroUsd !== null &&
    budget.spentMicroUsd >= budget.limitMicroUsd
  );
}

/**
 * Открыть потолок на тик: прочитать настройку и уже потраченное за
 * сегодня.
 *
 * Оба чтения терпимы к отказу (`catch`): потолок — предохранитель, и
 * упавшая база не должна останавливать работу, которая в остальном
 * исправна. При недоступном журнале расходов считаем потраченным ноль
 * — то есть предохранитель на эту ночь не сработает, но и не соврёт в
 * другую сторону, остановив исправный прогон.
 */
export async function openTutorialBudget(
  settings: Pick<PlatformSettingsService, 'get'>,
  aiUsage: Pick<AiUsageService, 'spentTodayForOperation'>,
): Promise<TutorialBudget> {
  const limitUsd = parseTutorialBudgetSetting(
    await settings.get(TUTORIAL_BUDGET_SETTING_KEY).catch(() => null),
  );
  const spentMicroUsd = await aiUsage
    .spentTodayForOperation(TUTORIAL_PAID_OPERATIONS)
    .catch(() => 0);
  return {
    limitMicroUsd: limitUsd === null ? null : Math.round(limitUsd * 1_000_000),
    spentMicroUsd,
  };
}
