/**
 * Разбор выключателя подписей: `off` — выключено, всё остальное
 * (включая отсутствие настройки) — ВКЛЮЧЕНО.
 *
 * Умолчание обратное умолчанию озвучки, и это осознанно. Там тумблер
 * бережёт деньги: полный набор стоит ≈$0.79 синтеза на Resemble, и
 * включаться он
 * обязан решением человека. Подписи не стоят денег — ни вызова
 * провайдера, — а обучающий ролик смотрят без звука чаще, чем со
 * звуком, и подпись тогда единственное, что объясняет кадр (§5).
 * Хронометража они стоят: немой кадр с подписью держится, пока её
 * читают (`captionReadingSeconds`, сквозной аудит A–G), — и это цена
 * того, что подпись вообще можно прочесть. Выключать по умолчанию то, что бесплатно и
 * полезно, значит выпускать заведомо худший ролик и ждать, пока
 * кто-нибудь заметит настройку.
 *
 * Отсюда и терпимость к мусору в другую сторону, чем у озвучки: там
 * непонятное значение НЕ включает трату, здесь непонятное значение не
 * выключает пользу. В обоих случаях это одно правило — «не разобрали,
 * значит человек ничего не решил», — просто умолчания разные.
 */
export function parseTutorialCaptionsSetting(stored: string | null): boolean {
  return (stored ?? '').trim().toLowerCase() !== 'off';
}

/**
 * Суточный денежный потолок всей ночной работы обучалки (сквозной
 * аудит 29.09.2026).
 *
 * ## Зачем
 *
 * До него потолков было три — штук в партии, времени тика и длины
 * реплики, — и ни одного в деньгах: `AiUsageService.budget()` в этой
 * подсистеме не звался нигде. Все три останавливаются мягко и честно,
 * но ни один не отвечает на вопрос «сколько мы готовы потратить за
 * ночь». §7.2 ТЗ закладывает ≈$1.50 на полный набор и называет эту
 * величину разовой; худший случай без потолка — тридцать сценариев по
 * тридцать реплик, то есть на порядок больше, и повторяется он каждую
 * ночь.
 *
 * ## Почему настройкой, а не константой
 *
 * Тот же довод, что у остальных выключателей §9: потолок, который
 * нельзя поднять без деплоя, в неудачную ночь останавливает работу до
 * следующего выката. Значение читается перед КАЖДОЙ платной операцией,
 * а не раз за прогон: синтез тридцати дорожек внутри одного сценария —
 * это тридцать трат, и остановиться надо на той, которая перевалила.
 *
 * ## Чего он не делает
 *
 * Не возвращает деньги и не отменяет уже отправленное. Достигнутый
 * потолок означает «на сегодня хватит»: оставшиеся сценарии переносятся
 * на следующую ночь ровно тем же механизмом, что при исчерпанном
 * бюджете времени, — они просто не исполняются, и ротация
 * `lastRunAt asc` даёт им пройти первыми.
 *
 * Пустая настройка — потолок по умолчанию, а НЕ «без потолка»:
 * умолчание обязано быть безопасным. Явное `off` снимает его совсем и
 * записано словом, чтобы это было решением, а не опечаткой.
 */
export const TUTORIAL_BUDGET_SETTING_KEY = 'postprod.tutorialDailyBudgetUsd';

/** Умолчание суточного потолка, доллары. Втрое выше самой дорогой
 *  штатной ночи по §7.2 ТЗ (полный набор ≈$1.50 на Resemble): потолок
 *  должен ловить убегание, а не мешать нормальной работе. */
export const DEFAULT_TUTORIAL_DAILY_BUDGET_USD = 2;

/**
 * Разбор потолка: число — потолок в долларах, `off` — потолка нет,
 * всё остальное (включая пустую строку и мусор) — умолчание.
 *
 * Непонятное значение даёт УМОЛЧАНИЕ, а не «без потолка»: это то же
 * правило, что у озвучки («не разобрали — значит человек ничего не
 * решил»), и здесь оно особенно важно — опечатка в поле не должна
 * снимать ограничение расхода. Ноль и отрицательные значения
 * отвергаются: «потолок ноль» останавливал бы подсистему навсегда, и
 * отличить это от опечатки нельзя.
 */
export function parseTutorialBudgetSetting(
  stored: string | null,
): number | null {
  const raw = (stored ?? '').trim().toLowerCase();
  if (raw === 'off') return null;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || parsed <= 0) {
    return DEFAULT_TUTORIAL_DAILY_BUDGET_USD;
  }
  return parsed;
}

/**
 * Движение в слайд-шоу (§6 ТЗ, этап G): переходы между кадрами и
 * лёгкий зум. Уровень отката §9 «4-бис» — «движение мешает»: выключить
 * без деплоя, независимо от звука и подписей.
 *
 * Префикс `postprod.`, как у звука и подписей: решение о том, как
 * собирается файл.
 */
export const TUTORIAL_MOTION_SETTING_KEY = 'postprod.tutorialMotion';

/**
 * Разбор: `fade` — только переходы, `on` — переходы и зум, всё
 * остальное (включая отсутствие настройки) — БЕЗ движения.
 *
 * Умолчание — выключено, и довод не про деньги, как у озвучки, а про
 * то, что движение — косметика, которую ни один человек ещё не видел
 * на настоящих кадрах мастера (§6 ТЗ: «делается последней и только
 * если первые этапы приняты»). Включать её обязан тот, кто посмотрел.
 * Цена включения всё же есть: зум в разы удлиняет работу внешнего
 * ffmpeg над каждым роликом, а первая ночь после включения
 * пересоберёт весь набор, потому что режим входит в отпечаток сборки.
 *
 * Непонятное значение — тоже «без движения», по правилу озвучки, а не
 * подписей: «не разобрали — человек ничего не решил», а решение здесь
 * меняет и картинку, и время работы внешнего сервиса.
 */
export function parseTutorialMotionSetting(
  stored: string | null,
): SlideshowMotion {
  const value = (stored ?? '').trim().toLowerCase();
  if (value === 'on') return 'fade+zoom';
  if (value === 'fade') return 'fade';
  return 'none';
}

/**
 * Указатель клика (§6 ТЗ, этап H): оранжевое кольцо на кнопке, по
 * которой кликнет следующий шаг, в последнюю секунду кадра перед
 * сменой экрана. Уровень отката §9 «4-тер» — выключить без деплоя.
 */
export const TUTORIAL_POINTER_SETTING_KEY = 'postprod.tutorialPointer';

/**
 * `on` — включено, всё остальное (включая отсутствие настройки) —
 * выключено. Тот же довод, что у движения: косметика, которую никто
 * ещё не видел на настоящих кадрах, а переключение пересобирает все
 * ролики со щелчками. Непонятное значение — выключено: «не разобрали —
 * человек ничего не решил».
 */
export function parseTutorialPointerSetting(stored: string | null): boolean {
  return (stored ?? '').trim().toLowerCase() === 'on';
}

/** Обратное к `parseTutorialMotionSetting` — строка, которая ложится в
 *  базу. Своя функция, а не таблица у витрины: грамматику настройки
 *  знает только этот модуль. */
export function tutorialMotionSettingValue(motion: SlideshowMotion): string {
  return motion === 'fade+zoom' ? 'on' : motion === 'fade' ? 'fade' : 'off';
}
