/**
 * Требовать вычитку реплик перед озвучкой (§3-бис.5 ТЗ
 * docs-tz/TZ-Tutorial-Video-Voiced.md, этап D).
 *
 * Префикс `tutorial.`, а не `postprod.`: это решение о СОДЕРЖАНИИ
 * сценария (прочитал ли человек текст, который произнесут), а не о
 * том, как собирается файл, — тот же префикс, что у
 * `tutorial.scenarioLocales`. Рядом стоящая `postprod.tutorialVoice`
 * отвечает на другой вопрос — «озвучивать ли вообще».
 *
 * **По умолчанию ВЫКЛЮЧЕНО, и это осознанно обратное умолчание** по
 * сравнению с самой озвучкой. Там выключатель бережёт деньги: полный
 * набор стоит ≈$0.79 синтеза на Resemble, провайдере проекта (§7.2 ТЗ;
 * прежние редакции писали ≈$6 — это ставка ElevenLabs, см. поправку
 * сквозного аудита 29.09.2026), и включаться это обязано решением
 * человека. Здесь беречь нечего — реплика это подпись к кадру, а не
 * платёжное поручение: ошибка в ней стоит пересборки за ≈$0.02 на
 * Resemble (одна дорожка из кеша плюс вызов ffmpeg), а
 * шлагбаум стоит того, что роликов не будет вовсе, пока у оператора
 * не дойдут руки до пятидесяти текстов. Цена ошибки заметно ниже
 * цены задержки — ровно тот случай, когда осторожность по умолчанию
 * вредна.
 *
 * Включён — сценарий с НЕвычитанными репликами собирается немым (а не
 * пропускается и не подменяется вариантом А): регрессионный прогон
 * важнее озвучки и от неё не зависит.
 */
export const TUTORIAL_REQUIRE_NARRATION_REVIEW_KEY =
  'tutorial.requireNarrationReview';

/**
 * Разбор выключателя вычитки: `on` — включено, всё остальное
 * (включая опечатку и отсутствие настройки) — выключено.
 *
 * Терпимость к мусору здесь смотрит в ДРУГУЮ сторону, чем у
 * `parseTutorialVoiceSetting`: там непонятное значение выключает
 * трату, здесь — снимает шлагбаум. В обоих случаях опечатка ведёт к
 * состоянию по умолчанию, а умолчания у выключателей разные, и это
 * не противоречие, а один и тот же принцип: непонятное значение
 * значит «человек ничего не решил».
 */
export function parseRequireNarrationReview(stored: string | null): boolean {
  return (stored ?? '').trim().toLowerCase() === 'on';
}

export interface TutorialVoiceSetting {
  enabled: boolean;
  /** Голос провайдера. `null` — голос по умолчанию у провайдера. */
  voiceId: string | null;
}

const VOICE_OFF: TutorialVoiceSetting = { enabled: false, voiceId: null };

/**
 * Грамматика значения: `off` | `on` | `on:<voiceId>`.
 *
 * **По умолчанию выключено, и это не осторожность ради осторожности.**
 * Исполнитель сценариев — ночной крон по ВСЕМ сценариям сразу: полный
 * набор из пятидесяти роликов стоит ≈$0.79 синтеза на Resemble (§7.2
 * ТЗ; ≈$5.28 было бы на ElevenLabs), и
 * включиться это должно решением человека, а не фактом деплоя. Тот же
 * довод, по которому немой ролик остаётся рабочим исходом, а не
 * ошибкой: озвучка — улучшение, а не условие.
 *
 * Непонятное значение — тоже «выключено», а не «включено с голосом по
 * умолчанию»: опечатка в админке не должна начинать тратить деньги.
 * Обратное умолчание («не разобрали — значит включено») стоило бы
 * ровно столько, сколько стоит полный набор.
 */
export function parseTutorialVoiceSetting(
  stored: string | null,
): TutorialVoiceSetting {
  const raw = (stored ?? '').trim();
  if (raw === 'on') return { enabled: true, voiceId: null };
  if (raw.startsWith('on:')) {
    const voiceId = raw.slice('on:'.length).trim();
    return voiceId.length > 0
      ? { enabled: true, voiceId }
      : { enabled: true, voiceId: null };
  }
  return VOICE_OFF;
}

/**
 * Текст озвучки по варианту А ТЗ (§3): одна дорожка на весь ролик,
 * собранная из карточки шага обучалки — `title` плюс `text`.
 *
 * Почему вариант А, когда принят Б: реплики на каждый шаг сценария
 * (`narration`) появляются только на этапе D, вместе с правкой
 * генератора и промпта. Этап B обязан быть проверяемым раньше, а
 * вариант А остаётся ОБЯЗАТЕЛЬНЫМ запасным путём навсегда (§3): у
 * сценариев, сгенерированных до этапа D, реплик нет и не появится, и
 * немыми они остаться не должны.
 *
 * `null` — текста нет: `subjectKey` за пределами десяти шагов
 * обучалки (свободный ключ воркфлоу, §4.4
 * `doc/TMA-UI-SNAPSHOT-AND-TUTORIAL-VIDEO-SPEC.md` — НЕ этого ТЗ, у
 * него такого раздела нет) или локаль, которой нет в словаре. Тогда собирается немой ролик, как сегодня, — ровно тот
 * же принцип «ролик получается всегда», что у замены голоса.
 *
 * `title` включается в текст, а не отбрасывается: без него дорожка
 * начинается с середины мысли («Проект и товар: фото…»), потому что
 * `text` в карточке написан как продолжение заголовка, а не как
 * самостоятельный абзац.
 */
export function narrationTextForSubject(
  subjectKey: string,
  locale: string,
): string | null {
  const step = tutorialStepFor(subjectKey, locale);
  if (!step) return null;
  const parts = [step.title, step.text]
    .map((part) => part?.trim() ?? '')
    .filter((part) => part.length > 0);
  if (parts.length === 0) return null;
  return joinNarrationParts(parts);
}

/**
 * Склеивает части реплики, ставя точку на СТЫКЕ и только там.
 *
 * Точка после заголовка нужна диктору для паузы: без неё выйдет
 * «Заведите товар Проект и товар» одной фразой. Если заголовок уже
 * кончался точкой, второй не ставим.
 *
 * Отдельная экспортируемая функция, а не три строки внутри: правка
 * должна быть проверяема на входах, которых в словаре пока нет.
 * Первая редакция схлопывала точки `replace(/\.\.+/g, '.')` по ВСЕЙ
 * строке — то есть портила бы и многоточие внутри текста шага,
 * меняя и озвучку, и сам текст (находка аудита этапа B).
 */
export function joinNarrationParts(parts: readonly string[]): string {
  return parts.reduce((acc, part) =>
    acc.endsWith('.') ? `${acc} ${part}` : `${acc}. ${part}`,
  );
}

/**
 * Префикс кеша озвучки ОДНОГО сценария — (локаль, ключ шага
 * обучалки). Внутри него живут слоты (см. `voiceoverSlotPrefix`).
 *
 * До этапа D слот был один и файл лежал прямо здесь. Этап D включил
 * вариант Б — реплика на КАЖДЫЙ шаг сценария, — и файлов стало до
 * тридцати на пару. Уровень слота обязателен: без него промах по
 * одной реплике сносил бы весь префикс, то есть заставлял
 * пересинтезировать все тридцать. Оператор, поправивший одно слово,
 * платил бы за весь сценарий.
 */
export function voiceoverCachePrefix(
  subjectKey: string,
  locale: string,
): string {
  return `tutorial-voiceovers/${locale}/${subjectKey}/`;
}

/**
 * Слот кеша — «какую именно дорожку этого сценария мы храним».
 *
 * `VOICE_SLOT_WHOLE` — вариант А, одна дорожка на весь ролик
 * (§3, запасной путь). Номер шага — вариант Б, реплика к кадру
 * этого шага (§3-бис, этап D). Разные слоты не путаются даже когда
 * текст совпадает: в дорожке варианта А звучит склейка заголовка и
 * описания шага обучалки, в дорожке варианта Б — реплика сценария,
 * и подставлять одну вместо другой нельзя.
 *
 * Под слотом живёт ровно один файл: на промахе всё лишнее из
 * префикса сценария выметается (`сверка кеша` в исполнителе).
 */
export const VOICE_SLOT_WHOLE = 'all';

export function voiceoverSlotPrefix(
  subjectKey: string,
  locale: string,
  slot: string,
): string {
  return `${voiceoverCachePrefix(subjectKey, locale)}${slot}/`;
}

/** Всё, от чего зависит синтезированная дорожка. */
export interface TutorialVoiceKey {
  subjectKey: string;
  locale: string;
  /**
   * `VOICE_SLOT_WHOLE` или номер шага сценария строкой. В ПУТЬ
   * входит, а в хеш — нет: путь и так разводит слоты по каталогам, а
   * добавлять номер шага в хеш значило бы, что одинаковая реплика на
   * двух шагах синтезируется дважды за одни деньги.
   */
  slot: string;
  /** Ключ провайдера синтеза (`elevenlabs`, `resemble`). */
  provider: string;
  /** Голос провайдера; `null` — голос по умолчанию. */
  voiceId: string | null;
  text: string;
}

/**
 * Путь кеша синтезированной дорожки.
 *
 * Зачем кеш вообще. Исполнитель — ночной крон по ВСЕМ сценариям, и
 * без кеша он платил бы за синтез каждую ночь: ≈$0.47 за десять
 * русских роликов, ≈$2.5 за полный набор — ежесуточно. §7.2 ТЗ при
 * этом обещает «величина разовая: ролики пересобираются, когда
 * меняется интерфейс или текст шага, а не по расписанию». Без кеша
 * это было неправдой (находка аудита этапа B).
 *
 * В ключ входит ВСЁ, от чего дорожка зависит: шаг, локаль,
 * провайдер, голос и хеш текста. Первая редакция брала только шаг,
 * локаль и текст — и смена голоса в админке не меняла ничего в уже
 * собранных шагах, а переключение провайдера на `veo` (второй
 * уровень отката §9, обещающий немые ролики) оставляло их
 * озвученными старой дорожкой ElevenLabs (находка сквозного аудита
 * A+B+C).
 *
 * Хеш — от текста, а не от шага: поправили текст шага на лендинге,
 * сменился хеш, дорожка пересинтезируется сама. Именно то поведение,
 * которое ТЗ и описывает.
 *
 * Почему это не «вторая яма с сиротами», против которой §4.3.
 * Транзитные файлы сборки живут под префиксом актива и метутся
 * целиком; кеш живёт вне его НАМЕРЕННО — он и должен пережить
 * сборку, иначе он не кеш. Расти ему некуда: на промахе исполнитель
 * сносит всё, что лежит под `voiceoverCachePrefix`, и кладёт один
 * новый файл. Потолок — десять шагов × пять локалей = пятьдесят
 * файлов по ≈200 КБ.
 */
export function voiceoverCachePathname(
  key: TutorialVoiceKey,
  /**
   * Измеренная длина дорожки в миллисекундах — В ИМЯ ФАЙЛА.
   *
   * Это не второй источник правды, хотя выглядит похоже. Имя
   * содержит хеш текста, то есть адресует конкретные байты: под этим
   * именем лежит ровно тот файл, который при записи и измерили, и
   * изменить его, не сменив имени, нельзя. Длина, записанная рядом с
   * таким адресом, разойтись с файлом не может.
   *
   * Заведено аудитом этапа D, и вот зачем. `cachedNarration`
   * СКАЧИВАЛА mp3 целиком только ради `mp3DurationSeconds`. Пока
   * дорожка была одна на ролик, это было одно скачивание на сценарий
   * за ночь. Вариант Б сделал их до тридцати — шесть мегабайт и
   * десятки секунд внутри четырёхминутного бюджета прогона, который
   * этап D не трогал. С длиной в имени попадание в кеш стоит одного
   * `head`.
   *
   * `null` — длину измерить не удалось; пишем `x`, чтобы отличать
   * «не измеряли» от «ноль», как того требует контракт TTS.
   */
  durationMs: number | null = null,
): string {
  const hash = createHash('sha256')
    // Разделитель, которого нет в кодах локалей, ключах провайдеров и
    // id голосов: без него `on:ab`+`c` и `on:a`+`bc` дали бы один
    // хеш.
    .update([key.provider, key.voiceId ?? '', key.text].join('\u0000'))
    .digest('hex')
    .slice(0, 16);
  const stamp = durationMs === null ? 'x' : String(Math.round(durationMs));
  return `${voiceoverSlotPrefix(key.subjectKey, key.locale, key.slot)}${hash}-${stamp}.mp3`;
}

/**
 * Длина дорожки, прочитанная из её же имени.
 *
 * `null` — имя не того вида или длину при записи измерить не
 * удалось. Оба случая ведут в одно и то же место
 * (`narrationFrameSeconds(null)` — минимальная длина кадра), и это
 * верно: доверять неизвестному числу хуже, чем признать, что его нет.
 */
export function voiceoverDurationMsFromPathname(
  pathname: string,
): number | null {
  const m = /-(\d+)\.mp3$/.exec(pathname);
  if (!m) return null;
  const ms = Number(m[1]);
  return Number.isFinite(ms) && ms > 0 ? ms : null;
}

/**
 * Есть ли под этим слотом файл с нужным хешем — и какой именно.
 *
 * Поиск по ПРЕФИКСУ слота, а не по точному пути: длина в имени
 * заранее неизвестна тому, кто спрашивает у кеша. Под слотом файл
 * всегда один (всё лишнее выметает сверка кеша), так что «первый
 * подходящий» — он же единственный.
 */
export function matchesVoiceKey(
  pathname: string,
  key: TutorialVoiceKey,
): boolean {
  const prefix = voiceoverSlotPrefix(key.subjectKey, key.locale, key.slot);
  if (!pathname.startsWith(prefix)) return false;
  const hash = createHash('sha256')
    .update([key.provider, key.voiceId ?? '', key.text].join('\u0000'))
    .digest('hex')
    .slice(0, 16);
  return pathname.slice(prefix.length).startsWith(`${hash}-`);
}

