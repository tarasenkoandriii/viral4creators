/**
 * Ключи словаря в записях опыта — «Тонкая красная линия» §6.7, этап 9.
 *
 * ## Правило, ради которого это существует
 *
 * Записи опыта НЕ называют элементы интерфейса словами. В тексте стоит
 * ключ — `{{clientSiteWizard.liveButton}}`, — и подпись подставляется
 * при ОТДАЧЕ, на нужной локали.
 *
 * Подстановка при отдаче, а не при сохранении, — не мелочь. Подписи в
 * словаре меняются; вмороженное в базу название кнопки пережило бы
 * правку словаря молча, а с этапа 11 ещё и разъехалось бы по пяти
 * замороженным переводам разом.
 *
 * ## Почему подпись едет в «ёлочках»
 *
 * Правило 5 преамбулы промпта (`hintRules`) велит модели переносить
 * текст в «ёлочках» дословно. Подставляя подпись именно так, мы
 * получаем ровно то, что нужно: человек слышит надпись, которую видит
 * на экране, а не пересказ модели.
 */

import { WIZARD_UI_STRINGS } from './ui-strings.generated';

/**
 * `{{раздел.ключ}}`. Точка обязательна: одиночное слово в фигурных
 * скобках встречается в обычном тексте (шаблоны, формулы), и считать
 * его ключом значило бы ломать записи, в которых никаких ключей нет.
 */
export const UI_KEY_PATTERN = /\{\{([a-zA-Z0-9_]+(?:\.[a-zA-Z0-9_]+)+)\}\}/g;

/** Какие ключи упомянуты в тексте. Без повторов, в порядке появления. */
export function uiKeysOf(text: string): string[] {
  const out: string[] = [];
  for (const m of text.matchAll(UI_KEY_PATTERN)) {
    if (!out.includes(m[1])) out.push(m[1]);
  }
  return out;
}

/** Известен ли ключ хотя бы на одной локали. */
export function isKnownUiKey(key: string): boolean {
  return Object.values(WIZARD_UI_STRINGS).some((m) => key in m);
}

export interface RenderedText {
  text: string;
  /**
   * Ключи, которых нет в словаре этой локали.
   *
   * Непустой список означает, что текст НЕЛЬЗЯ показывать: подставить
   * нечего, а оставить `{{…}}` на экране — то же самое, что показать
   * человеку кусок нашего шаблона. Приёмка этапа 9 требует, чтобы такая
   * ситуация помечалась в админке, а не уезжала в промпт.
   */
  unknown: string[];
}

/**
 * Подставить подписи нужной локали.
 *
 * Фолбэк на русский НАМЕРЕННО отсутствует: смешанный текст («нажмите
 * „Живой вход“» посреди немецкой фразы) выглядит как ошибка перевода и
 * подрывает доверие ко всему совету. Лучше не показать запись вовсе —
 * подсказка без неё остаётся подсказкой.
 */
export function renderUiKeys(text: string, locale: string): RenderedText {
  const strings = WIZARD_UI_STRINGS[locale] ?? {};
  const unknown: string[] = [];
  const rendered = text.replace(UI_KEY_PATTERN, (_whole, key: string) => {
    const value = strings[key];
    if (value === undefined) {
      if (!unknown.includes(key)) unknown.push(key);
      return _whole;
    }
    return `«${value}»`;
  });
  return { text: rendered, unknown };
}

/**
 * Совпадают ли множества ключей источника и перевода (§6.7).
 *
 * Инструкция переводчику требует сохранять ключи, но полагаться на неё
 * нельзя: модель однажды «переведёт» и ключ тоже. Сверка множеств —
 * один регексп, и без неё правило «не называть кнопки» держится на
 * честном слове модели.
 */
export function sameUiKeys(source: string, translation: string): boolean {
  const a = [...uiKeysOf(source)].sort();
  const b = [...uiKeysOf(translation)].sort();
  return a.length === b.length && a.every((k, i) => k === b[i]);
}
