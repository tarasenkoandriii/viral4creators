/**
 * Что советник знает о каждом сценарии — «Тонкая красная линия» §5.6.
 *
 * Карточки шагов и факты состояния лежат ЗДЕСЬ, а не в общем корпусе
 * знаний: корпус собирается из словарей лендинга и описывает продукт
 * снаружи, а это — внутренности мастера. Смешать их значило бы заставить
 * `build-assistant-knowledge.ts` знать про состояние сессии.
 *
 * На этапе 6 сценарий один — обучалка. Greeting и товарка добавляются
 * волной D, и добавляются сюда же: отдельный список шагов для советника
 * разошёлся бы с тем, который рисует степпер.
 */

import { createHash } from 'crypto';
import type { FreeScenario } from '../../common/test-user-scenarios';
import { hintRules, type HintStepCard } from './hint-context';

export interface ScenarioHints {
  /** Цель сценария одной фразой — первый блок промпта. */
  goal: string;
  /** Карточки шагов; ключ совпадает с `stepId` степпера. */
  cards: Record<string, HintStepCard>;
}

/**
 * Обучалка по сайту заказчика.
 *
 * Надписи экрана в «ёлочках»: промпт запрещает их переводить и
 * переписывать, поэтому человек услышит ровно то, что видит.
 */
const CLIENT_SITE: ScenarioHints = {
  goal:
    'человек записывает обучающий ролик по СВОЕМУ сайту: вводит ссылку, ' +
    'проходит сценарий шаг за шагом в браузере на нашем сервере, потом ' +
    'смотрит записанные кадры и отправляет на проверку',
  cards: {
    url: {
      stepId: 'url',
      goal:
        'вводит адрес страницы, с которой начнётся обучалка. Записывать ' +
        'можно только свой сайт. Хороший старт — страница, с которой ' +
        'реальный посетитель начинает путь, а не главная.',
    },
    record: {
      stepId: 'record',
      goal:
        'проходит сценарий: заполняет поля и жмёт кнопки той страницы, ' +
        'которую видит на кадре. Каждый ответ сервера — один кадр ролика. ' +
        'Опасные кнопки помечены заранее. Вход на сайт — отдельной ' +
        'кнопкой живой сессии, где человек вводит логин сам.',
    },
    review: {
      stepId: 'review',
      goal:
        'смотрит ленту записанных кадров, даёт обучалке название и ' +
        'отправляет на проверку. Отсюда же можно продолжить запись или ' +
        'отменить последний шаг.',
    },
  },
};

export const SCENARIO_HINTS: Partial<Record<FreeScenario, ScenarioHints>> = {
  CLIENT_SITE,
};

/** Шаги сценария — тот же список, что рисует степпер (§5.7). */
export function stepIdsOf(scenario: FreeScenario): string[] {
  return Object.keys(SCENARIO_HINTS[scenario]?.cards ?? {});
}

/**
 * Штамп корпуса — часть ключа кеша (§5.5).
 *
 * СЧИТАЕТСЯ, а не пишется руками. Раньше здесь лежала строка вида
 * `'cards-1'`, и правка карточки без правки строки означала сутки
 * старых советов на новом тексте — ошибка, которую невозможно заметить
 * глазами и легко сделать. Хеш снимает вопрос: поменялась цель
 * сценария, карточка шага или сама преамбула правил — сменился штамп,
 * и весь кеш инвалидирован бесплатно и полностью.
 *
 * Язык и цель в `hintRules` подставляются фиктивные: меняется от них
 * подставленное значение, а не сам шаблон, и локаль в ключе кеша уже
 * есть отдельным полем.
 */
export function knowledgeStamp(): string {
  return createHash('sha256')
    .update(JSON.stringify(SCENARIO_HINTS))
    .update(hintRules('%LANG%', '%GOAL%'))
    .digest('hex')
    .slice(0, 12);
}
