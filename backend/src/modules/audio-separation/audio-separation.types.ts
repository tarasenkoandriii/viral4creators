/**
 * Разделение звуковой дорожки на стемы — контракт провайдера.
 *
 * ТЗ: `docs-tz/TZ-Voice-Replace-Keep-Background.md`. Нужно для того,
 * чтобы режим «дубляж» заменял ГОЛОС, а не весь звук: из исходной
 * дорожки убирается речь модели, а фон — шум улицы, музыка, лай —
 * возвращается в ролик под новую озвучку.
 *
 * Интерфейс отдельно от реализации по той же причине, что у
 * `TtsProvider`: провайдер разделения заведомо сменный (htdemucs
 * сегодня, что-то другое завтра), а вызывающий код про это знать не
 * должен.
 */

export interface SeparationRequest {
  /** Публичная ссылка на исходник. Провайдер скачивает сам. */
  sourceUrl: string;
  /** Для учёта расхода — чей вызов. */
  sessionId?: string;
}

export interface SeparationOutcome {
  ok: boolean;
  /**
   * `true` — провайдер не настроен: штатное состояние стенда, не сбой.
   * Ровно то же различение, что у синтеза речи (`SynthesisOutcome`):
   * «не подключено» и «сломалось» — разные новости, и для человека, и
   * для тревог.
   */
  skipped?: boolean;
  reason?: string;
  /**
   * Всё, кроме голоса. Обычно одна ссылка (двухстемный режим), но может
   * быть несколько, если модель отдала стемы по отдельности
   * (`drums`/`bass`/`other`) — тогда их надо сложить. Список, а не одна
   * строка, именно поэтому: форма ответа зависит от модели, и
   * вызывающий код не должен ломаться при её смене.
   */
  backgroundUrls?: string[];
  /**
   * Голос отдельно. Сам по себе не нужен — нужен ответ на вопрос
   * «говорила ли модель вообще»: если вокала нет, разделять было нечего
   * и исходник можно подмешивать целиком.
   */
  vocalsUrl?: string;
  /** Сколько заняло — для логов и замеров, не для оплаты. */
  seconds?: number;
}

export interface AudioSeparationProvider {
  /** Настроен ли провайдер. Не настроен — не ошибка. */
  configured(): boolean;
  separate(request: SeparationRequest): Promise<SeparationOutcome>;
}
