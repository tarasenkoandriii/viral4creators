/**
 * Что нельзя писать в служебный канал (ТЗ §28, этап 45).
 *
 * Текст тревоги собирается из сообщений об ошибках, а туда попадает
 * что угодно: кусок промпта, presigned-ссылка с подписью, заголовок
 * `Authorization`, адрес почты пользователя. Канал читают операторы, но
 * это всё-таки Telegram: пересланное сообщение, скриншот в переписке,
 * участник, которого забыли убрать. Секрет, попавший туда, считается
 * утёкшим.
 *
 * Поэтому текст проходит через один фильтр — и он же ограничивает
 * длину: Telegram режет сообщение на 4096 символах, и обрезанный
 * посередине стектрейс не читается вообще.
 *
 * Список намеренно узкий и грубый. Задача — не «распознать все секреты»
 * (это невозможно), а не пропустить те формы, которые в этом проекте
 * действительно встречаются.
 */

/** Telegram режет на 4096; оставляем запас на префикс и сводку. */
export const MAX_MESSAGE_LENGTH = 3500;

const PATTERNS: Array<[RegExp, string]> = [
  // Bearer / api-key в заголовках и в тексте ошибок провайдеров.
  [/\b(bearer\s+)[A-Za-z0-9._\-]{8,}/gi, '$1<секрет>'],
  // Имя переменной целиком, а не только его хвост: `\b` перед `token`
  // не срабатывает в `TELEGRAM_BOT_TOKEN=` — подчёркивание для регулярки
  // символ слова, границы там нет (этап 47, В-3.3). Захватываем весь
  // идентификатор, чтобы `GEMINI_API_KEY=…`, `CRON_SECRET=…` и
  // `x-goog-api-key: …` резались одинаково.
  [
    /([A-Za-z0-9_-]*(?:api[_-]?key|token|secret|password))["'\s:=]+[A-Za-z0-9._\-:]{8,}/gi,
    '$1=<секрет>',
  ],
  // Ключи известных провайдеров по их собственным префиксам.
  [/\bsk-[A-Za-z0-9]{16,}/g, '<секрет>'],
  [/\bAIza[0-9A-Za-z_\-]{20,}/g, '<секрет>'],
  [/\bvercel_blob_rw_[A-Za-z0-9_]+/g, '<секрет>'],
  // Подписанные ссылки: сама ссылка нужна, подпись — нет. `key=` — так
  // ключ Google уходит в query у части его же эндпоинтов.
  [/([?&](?:token|signature|sig|key|X-Amz-Signature)=)[^&\s]+/gi, '$1<секрет>'],
  // Почта пользователя — персональные данные, в канале ей не место.
  [/\b[\w.+-]+@[\w-]+\.[\w.]{2,}\b/g, '<почта>'],
];

export function redact(text: string): string {
  let out = text ?? '';
  for (const [re, to] of PATTERNS) out = out.replace(re, to);
  if (out.length > MAX_MESSAGE_LENGTH) {
    // Обрезаем с конца и говорим об этом: молча укороченный текст
    // выглядит как законченный, и по нему делают неверные выводы.
    out = `${out.slice(0, MAX_MESSAGE_LENGTH)}… (обрезано)`;
  }
  return out;
}
