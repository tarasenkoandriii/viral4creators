import { IsIn } from 'class-validator';

/**
 * Доп. запрос владельца продукта (ТЗ VEO-MODEL-VERSION-CHOICE-SPEC.md
 * §20.3/§20.4 п.3) — вызывается экраном генерации (`GenerationWizard.tsx`,
 * рядом с `PromptEditor`) при появлении готового промпта.
 *
 * Найдено при аудите: `brandColor` изначально был произвольным
 * клиентским параметром — §20.3 предполагал брать цвет из
 * `BrandManifestSnapshot`, но у него нет поля цвета вовсе (не
 * реализовано в схеме), так что клиент указывал ЛЮБОЙ hex-цвет по
 * своему усмотрению. Раз `brandColor` входит в хэш устаревания
 * карточки (`TextCardService`, §20.9), это был реальный вектор
 * злоупотребления: перебор цветов от клиента заставлял бы каждый раз
 * заново рендерить и заливать в Blob, минуя идемпотентность —
 * бесплатно для клиента, не бесплатно для инфраструктуры. Убран
 * целиком, не заменён на server-side вывод — заводить под это поле в
 * схеме бренда ради чисто косметического дефолта фона карточки того
 * не стоит, нейтральный `DEFAULT_BG` (`text-card-render.ts`) читаем
 * на любом фоне видео одинаково хорошо.
 */
export class EnsureTextCardsRequestDto {
  @IsIn(['9:16', '16:9', '1:1'])
  aspectRatio!: '9:16' | '16:9' | '1:1';
}
