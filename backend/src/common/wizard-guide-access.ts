/**
 * Когда чекбокс «использовать ИИ» ещё можно включить — «Тонкая красная
 * линия», §3.2 (docs-tz/TZ-Tonkaya-Krasnaya-Liniya.md).
 *
 * Правило асимметричное: **включить — только в начале сценария,
 * выключить — в любой момент**, и обратно в этом прогоне уже не
 * поставить.
 *
 * Причина не в удобстве, а в честности: линия либо проведена с начала,
 * либо её нет. Советник, подключённый на пятом шаге, не видел первых
 * четырёх — и его «до цели осталось» и «обо что тут спотыкаются»
 * опирались бы на путь, которого он не наблюдал. Пунктирная линия хуже
 * отсутствующей: ей верят так же, а держит она меньше.
 *
 * Проверка живёт ЗДЕСЬ, а не в интерфейсе: визард обходится прямым
 * запросом к API — тот же принцип, по которому пара (повод, тон)
 * проверяется на сервере (`greeting-brief.service.ts`), а не прячется в
 * визарде.
 */

/** Что известно о ходе сценария. Ровно то, по чему судим о «начале». */
export interface ScenarioProgress {
  /** Обучалка: сколько раундов уже записано. */
  clientSiteFrames?: number;
  /** Greeting и товарка: заведена ли сессия. */
  hasSession?: boolean;
  /** Товарка: начат ли разбор референса. */
  hasAnalysis?: boolean;
}

/**
 * Сценарий ещё не начат — значит чекбокс можно включить.
 *
 * Все признаки складываются через «ИЛИ»: любой из них означает, что путь
 * уже идёт. Ошибиться здесь можно только в сторону «поздно», и это
 * правильная сторона: лишний запрет объясним, а линия, начатая с
 * середины, — нет.
 */
export function canEnableAiGuide(progress: ScenarioProgress): boolean {
  if ((progress.clientSiteFrames ?? 0) > 0) return false;
  if (progress.hasSession) return false;
  if (progress.hasAnalysis) return false;
  return true;
}

