/**
 * Ключ внешнего API (docs-tz/TZ-Vneshnee-API.md, этап 144) — выпуск,
 * хеш и разбор заголовка. Чистый модуль: сеть и база снаружи.
 *
 * ## Почему хеш, если сессии лежат открытым текстом
 *
 * Разница не в аккуратности, а в сроке жизни и в том, где секрет
 * находится. Сессия живёт часы, привязана к устройству и к домену;
 * ключ живёт месяцами и лежит в чужом CI, в чужом `.env` и в чужой
 * истории команд. Утечка дампа базы с сессиями — это разлогинить всех;
 * утечка дампа с ключами — это чужие скрипты, которые продолжают
 * работать, и мы не знаем, чьи.
 *
 * Соли у хеша нет намеренно. Соль защищает от перебора по словарю —
 * от того, что пароль «qwerty» найдут в радужной таблице. Здесь
 * секрет не выбирает человек: это 32 случайных байта, перебирать их
 * нечем. Зато без соли хеш детерминированный, а значит по нему можно
 * искать одним запросом по уникальному индексу — и сравнение секретов
 * делает база, а не наш код в цикле по всем ключам.
 *
 * ## Почему у ключа есть открытый префикс
 *
 * Чтобы человек мог опознать СВОЙ ключ в списке, не имея его целиком.
 * Без префикса список выдач — это несколько строк «ключ от 12 марта», и
 * отозвать нужный можно только угадав.
 */

import { createHash, randomBytes } from 'crypto';

/** Видимое начало ключа: по нему он узнаётся в логах и в списке. */
export const API_KEY_PREFIX = 'v4c_';

/** Сколько символов ключа показываем в списке после выдачи. */
export const API_KEY_HINT_LENGTH = 8;

export interface IssuedApiKey {
  /** Секрет целиком. Показывается ОДИН раз и больше не существует. */
  secret: string;
  /** То, что ложится в базу вместо секрета. */
  keyHash: string;
  /** Открытая часть для опознания: `v4c_` плюс первые символы. */
  hint: string;
}

/** Выпустить новый ключ. 32 случайных байта — перебирать нечем. */
export function issueApiKey(): IssuedApiKey {
  const secret = `${API_KEY_PREFIX}${randomBytes(32).toString('base64url')}`;
  return { secret, keyHash: hashApiKey(secret), hint: hintOf(secret) };
}

export function hashApiKey(secret: string): string {
  return createHash('sha256').update(secret).digest('hex');
}

/** Открытая часть ключа. Ровно она и лежит в базе рядом с хешем. */
export function hintOf(secret: string): string {
  return secret.slice(0, API_KEY_PREFIX.length + API_KEY_HINT_LENGTH);
}

/**
 * Ключ из заголовка `Authorization: Bearer …`. `null` — заголовка нет
 * или он не той формы.
 *
 * Схема сравнивается без учёта регистра (так требует RFC 7235), а сам
 * ключ — как есть: он чувствителен к регистру, и «починить» его
 * приведением к нижнему значило бы принимать чужой ключ за свой.
 */
export function apiKeyFromHeader(header: string | undefined): string | null {
  const match = /^Bearer[ \t]+(\S+)$/i.exec((header ?? '').trim());
  if (!match) return null;
  const secret = match[1];
  // Чужой Bearer (админский, кроновый) сюда доходить не должен: без
  // этой проверки он ушёл бы в поиск по базе и дал бы 401 вместо
  // внятного «это не ключ API».
  return secret.startsWith(API_KEY_PREFIX) ? secret : null;
}

/**
 * Пора ли обновлять «последнее использование».
 *
 * Писать на каждый запрос — это запись в базу на каждый вызов API, то
 * есть плата за наблюдаемость на самом горячем пути. А нужна эта
 * отметка ровно для одного вопроса: «этим ключом ещё пользуются?» —
 * и ответ на него не меняется от того, час назад или пять минут.
 */
export const LAST_USED_GRANULARITY_MS = 60 * 60 * 1000;

export function shouldTouchLastUsed(
  lastUsedAt: Date | null | undefined,
  now: Date,
): boolean {
  if (!lastUsedAt) return true;
  return now.getTime() - lastUsedAt.getTime() >= LAST_USED_GRANULARITY_MS;
}
