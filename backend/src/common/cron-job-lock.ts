/**
 * Джоб-уровневый замок поверх поштучного claim строк (пятый аудит,
 * Д-3.3). Три крон-воркера (`catalog-batch-run`, `ab-test-run`,
 * `feed-import-run`) сами по себе безопасны построчно — `updateMany` с
 * условием на `lockedUntil` не даёт ДВУМ тикам обработать ОДНУ И ТУ ЖЕ
 * строку партии. Но ничто не мешало им обработать РАЗНЫЕ строки ОДНОЙ И
 * ТОЙ ЖЕ партии одновременно — оба тика проходят свою собственную
 * проверку дневного денежного лимита (`assertCanSpendUser`,
 * SELECT-агрегат без блокировки) для своей строки ДО того, как другой
 * успеет записать расход, и вместе превышают потолок. До этапа 69
 * источником перекрытия могло быть только совпадение расписания Vercel
 * Cron; этап 69 добавил человеческий триггер — кнопку ручного запуска в
 * админке — а с ней и двойной клик оператора как новый, куда более
 * вероятный путь к той же гонке.
 *
 * ## Почему не `pg_advisory_xact_lock` (как в publication/credit-ledger/billing)
 *
 * Проект уже использует advisory-локи транзакционной области
 * (`pg_advisory_xact_lock` внутри `$transaction`) для похожих гонок —
 * см. `publication.service.ts`, `credit-ledger.service.ts`,
 * `billing.service.ts`. Но там весь защищённый участок — считанные
 * быстрые запросы внутри одной транзакции, коммитящейся за миллисекунды.
 * Здесь под замком должен быть ЦЕЛЫЙ `runBatch()`/`runTick()` — цикл по
 * нескольким строкам с сетевыми вызовами к GPT-5/Veo, возможно не одну
 * секунду. Держать открытую транзакцию (а значит — единственное
 * соединение из пула PgBouncer) на всё это время — другой профиль
 * риска, чем у уже существующих коротких транзакционных локов, а
 * session-scoped `pg_advisory_lock`/`pg_advisory_unlock` здесь не
 * подходит по той же причине, по которой его нигде в проекте нет:
 * PgBouncer в режиме transaction pooling не гарантирует, что lock/unlock
 * попадут на одно и то же физическое соединение — замок рискует
 * зависнуть навсегда на случайном соединении пула.
 *
 * Вместо этого — тот же приём, что уже используется в этих же файлах на
 * уровне ОДНОЙ строки (`lockedUntil` + условный `updateMany`), только на
 * уровне всего джоба: одна строка `CronJobLock` на `jobKey`, TTL как
 * защита от «зависшего» замка, если процесс упал посередине (следующий
 * тик подхватит просроченный замок и продолжит работу), явное снятие в
 * `finally`.
 */

import { PrismaService } from '../prisma/prisma.service';

/** TTL — с запасом на самый долгий реалистичный прогон джоба (цикл по
 * `cronBatch` строкам, для каждой — сетевой вызов). Отдельная константа
 * от построчных `LOCK_MS`/`RUN_LOCK_MS` в самих воркерах — джоб-уровневый
 * замок должен пережить весь цикл, а не одну строку. */
export const JOB_LOCK_MS = 5 * 60 * 1000;

/**
 * Пытается захватить замок на `jobKey`. Возвращает `true`, если замок
 * захвачен ИМЕННО ЭТИМ вызовом (можно выполнять джоб), `false` — если
 * замок уже удерживает другой прогон (нужно пропустить тик, ничего не
 * трогая). Атомарно относительно параллельных вызовов: первый прогон
 * когда-либо для этого `jobKey` захватывает через `create()` (упадёт с
 * P2002 у конкурента, строка ещё не существовала); все последующие —
 * через условный `updateMany()`, который отдаёт `count > 0` только
 * ОДНОМУ из одновременных вызовов (строка либо свободна, либо её TTL
 * истёк). Конкурирующий вызов в обоих случаях корректно получает `false`.
 */
export async function tryAcquireJobLock(
  prisma: PrismaService,
  jobKey: string,
  ttlMs: number = JOB_LOCK_MS,
): Promise<boolean> {
  const lockedUntil = new Date(Date.now() + ttlMs);
  try {
    await prisma.cronJobLock.create({ data: { jobKey, lockedUntil } });
    return true;
  } catch (error) {
    // P2002 — строка для этого jobKey уже существует (обычный случай,
    // не первый прогон джоба вообще) — падаем на условный updateMany
    // ниже. Любая другая ошибка — не наша забота здесь, пробрасываем.
    const code =
      error && typeof error === 'object' && 'code' in error
        ? (error as { code?: string }).code
        : undefined;
    if (code !== 'P2002') throw error;
  }
  const claim = await prisma.cronJobLock.updateMany({
    where: {
      jobKey,
      OR: [{ lockedUntil: null }, { lockedUntil: { lt: new Date() } }],
    },
    data: { lockedUntil },
  });
  return claim.count > 0;
}

/** Снимает замок явно — вызывается из `finally` вызывающего кода, чтобы
 * следующий тик не ждал TTL, если джоб уже завершился (успешно или с
 * ошибкой) штатно, а не упал без возможности убраться за собой. */
export async function releaseJobLock(
  prisma: PrismaService,
  jobKey: string,
): Promise<void> {
  await prisma.cronJobLock
    .updateMany({ where: { jobKey }, data: { lockedUntil: null } })
    .catch(() => undefined);
}
