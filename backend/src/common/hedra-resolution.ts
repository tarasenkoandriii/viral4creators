import type { GreetingResolution } from './types/greeting.types';

/**
 * Разрешение поздравления → разрешение, которое понимает Hedra.
 *
 * Наборы не совпадают: у нас `480p | 720p | 1080p`, у Hedra
 * `540p | 720p | 1080p`. Совпадают два значения из трёх, и вся разница
 * — в младшем.
 *
 * 480p поднимается до 540p, а не опускается ниже: меньшего у Hedra
 * нет, и отказать пользователю PREMIUM за то, что он выбрал экономное
 * разрешение, было бы странно. Разница в цене между 540p и 720p у
 * Hedra есть, поэтому округляем к БЛИЖАЙШЕМУ доступному, а не к
 * верхнему: иначе выбор «подешевле» молча стоил бы как «получше».
 */
export function hedraResolution(
  resolution: GreetingResolution,
): '540p' | '720p' | '1080p' {
  return resolution === '480p' ? '540p' : resolution;
}
