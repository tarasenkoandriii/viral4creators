/**
 * Какую модель Gemini зовёт сервис (Б-5.4).
 *
 * Переменная `GEMINI_MODEL` читалась двумя вызовами из пяти
 * (`product-recognition`, `voice-transcription`), а разбор видео,
 * проверка релевантности и аудит ролика держали модель зашитой строкой.
 * Вкладка «Настройки» при этом подписывала переменную как «модель для
 * анализа видео» и показывала зелёное: оператор, поставивший
 * `gemini-2.5-pro`, был уверен, что платит за pro на самом дорогом из
 * этих вызовов, — а платил за flash.
 *
 * Теперь источник один. Значение читается при загрузке модуля, как и
 * раньше в двух других сервисах: смена модели требует рестарта, и это
 * честнее, чем менять её на лету посреди прогонов.
 *
 * Если поставить модель, которой нет в прайсе (`common/ai-pricing.ts`),
 * расход запишется как `unpriced` — с честной пометкой, а не молчаливым
 * нулём.
 */
export const GEMINI_MODEL = process.env.GEMINI_MODEL || 'gemini-2.5-flash';
