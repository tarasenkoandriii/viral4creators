/**
 * Софт-delete (этап 89) — единая константа грейс-периода для всех трёх
 * мест, где `DELETE .../:id` теперь ставит `deletedAt` вместо
 * немедленного удаления строки: `Project`, `ProductItem`, `Session`.
 *
 * Не сделан переменной окружения (в отличие от `SESSION_TTL_HOURS`,
 * который отдельно настраивают под нагрузочное тестирование —
 * `LOCAL-DEVELOPMENT.md`): здесь нет сценария, где грейс-период нужно
 * менять на живом стенде, а лишняя переменная — лишняя запись в
 * `env-settings.ts`/`DEPLOYMENT.md` и ещё один параметр, который надо
 * держать в голове. Если понадобится — завести по образцу
 * `SESSION_TTL_HOURS` несложно.
 *
 * 24 часа — то же число, что и дефолтный `SESSION_TTL_HOURS`: достаточно
 * времени заметить случайное удаление и попросить восстановить руками
 * (через БД — самообслуживаемого «отменить» пока нет), но не настолько
 * долго, чтобы Blob копился заметно дольше, чем раньше.
 */
export const SOFT_DELETE_GRACE_MS = 24 * 60 * 60 * 1000;

/**
 * Известный, сознательно не закрытый в этом заходе пробел (найдено доп.
 * аудитом, MEDIUM): READ-пути к Session — `SessionService.getSession`,
 * `AdminPanelService.getSession`, `postprod-video-summary.ts` и т. д. —
 * все фильтруют `deletedAt: null` (см. их доккомментарии). Но несколько
 * WRITE-путей к уже известному `sessionId` — `SessionService.
 * updateSession`/`claimWork`/`releaseWork`/`claimPostProduction`
 * (атомарные `$executeRaw`/`$queryRaw` UPDATE по одному только `id`,
 * ради конкурентной безопасности — см. их собственные доккомментарии) и
 * `SessionOwnerGuard`'а условная привязка анонимной сессии к
 * идентифицированному пользователю — НЕ проверяют `deletedAt`. Мягко
 * удалённая (но ещё не физически убранная краном) сессия в узком окне
 * гонки может получить запись в разгар уже начатого платного рендера,
 * который стартовал ДО удаления.
 *
 * Не исправлено намеренно, не забыто: каждый из этих путей — уже
 * тщательно обоснованный атомарный SQL под конкурентную защиту (гонки
 * между параллельными опросами Vercel, TTL-замки), и добавление
 * `deletedAt: null` в каждый WHERE — не локальная правка, а факт,
 * который надо продумать для каждого из них отдельно (что делать
 * PATCH-запросу к уже удалённой сессии — тихо игнорировать не то же,
 * что делает `updateSession` сейчас, возвращая обновлённую строку).
 * Цена ошибки — мала: доступ уже проверен выше по стеку (владелец
 * сессии или её анонимность), окно гонки — секунды между удалением и
 * последним ещё летящим запросом, а строка так и так исчезнет с концом
 * грейс-периода. Если гонка станет заметна на практике — чинить точечно
 * по каждому из перечисленных методов, не один общий патч.
 */

/**
 * Результат прохода `purgeSoftDeletedSessions()` — та же форма, что и у
 * `CleanupResult` (`session.service.ts`): пути собирает сервис, файлы в
 * Blob удаляет вызывающий (`CronJobsService`, у него есть `BlobService`).
 * `purgeSoftDeletedProjects`/`purgeSoftDeletedItems` устроены иначе — у
 * `ProjectService` `BlobService` уже есть (используется существующим
 * `deleteItemFiles`), поэтому они удаляют файлы сами, best-effort, и
 * возвращают только счётчики (`ProjectItemPurgeResult`).
 */
export interface SoftDeletePurgeResult {
  count: number;
  blobPathnames: string[];
  hasMore: boolean;
}

export interface ProjectItemPurgeResult {
  count: number;
  hasMore: boolean;
}
