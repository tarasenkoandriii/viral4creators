/**
 * Тексты отказов, которые ЧИТАЕТ ЧЕЛОВЕК.
 *
 * ## Зачем отдельный файл
 *
 * Фронтенд показывает текст отказа с сервера как есть: `errorMessage()`
 * в `frontend/src/services/projects-api.ts` берёт `error.message` из
 * конверта и подставляет свой переведённый текст только если сервер
 * промолчал. Значит каждая английская строка в пользовательском модуле
 * — это английская строка в русском интерфейсе, а `${sessionId}` внутри
 * неё — внутренний UUID на экране у человека: ни прочитать, ни что-то
 * по нему сделать нельзя, а светить идентификатор наружу незачем.
 *
 * Найдено сквозным аудитом обучалки 27.09.2026 (находка Д-5). Тогда же
 * посчитано: таких строк по бэкенду 273, и переписывать их разом нельзя
 * — слишком широкий мазок для одного прохода. Здесь закрыты две самые
 * частые и самые заметные семьи: «сессия не найдена» (47 мест) и
 * «проект не найден» (7 мест). Вместе это половина того, что человек
 * реально встречает в мастере: сессия истекает посреди работы чаще
 * всего остального.
 *
 * ## Почему константы, а не строки по месту
 *
 * Полсотни одинаковых отказов, набранных руками, разъедутся на первой
 * же правке формулировки. И шов `checkUserFacingErrorSeams()` в
 * `scripts/check-docs.mjs` умеет проверять именно этот файл: он
 * собирает отсюда имена констант с русским текстом и принимает их как
 * законный аргумент исключения наравне с литералом.
 *
 * ## Чего здесь НЕ должно быть
 *
 * Админских текстов. Оператору идентификатор строки как раз нужен —
 * он по нему ищет запись в базе, — и админка по построению русская.
 * Файлы `*-admin.*` и `admin-*` шов не проверяет, и сюда они не ходят.
 *
 * Отбор по ИМЕНИ файла надёжен не до конца, и это выяснилось на
 * рецензии этой же правки: `modules/actors/actors.service.ts` под
 * шаблон не подходит, а сервис admin-only целиком
 * (`@Controller('admin/actors')`, `AdminSessionGuard`, единственный
 * вызывающий), и четыре его отказа успели уехать сюда. Вернули им
 * идентификатор — но по-русски (`сессия ${sessionId} не найдена`), а
 * не откатом к английскому: оператору нужен id, а не язык.
 *
 * Перед тем как добавить сюда очередное место, стоит проверить, кто
 * зовёт метод: `grep -rl '<ИмяСервиса>' --include=*.controller.ts`.
 * Если все контроллеры начинаются с `admin/` — текст остаётся с
 * идентификатором.
 */

