/**
 * Общий предел размера фотографии товара — байты. Раньше жил только
 * приватной константой в `product-analog.service.ts` (флоу «фото →
 * аналоги»); вынесен сюда на этапе 68, потому что воркер импорта
 * товарного фида (`product-feed-import`) тоже скачивает картинку
 * (на этот раз — по ссылке из фида, а не из Vercel Blob) и должен
 * отбрасывать её по тому же лимиту, не заводя собственный, ничем не
 * обоснованный второй порог.
 */
export const MAX_PHOTO_BYTES = 10 * 1024 * 1024;

/**
 * Размер для текста «фото больше 10 МБ»: вверх до десятой и с запятой.
 * Обычное округление превращало 10 МБ + 1 байт в «10,0 МБ» — отказ,
 * который сам себе противоречит. Та же формула, что у товара и
 * бренд-бука (там она пока своя, приватная).
 */
export function photoSizeMb(bytes: number): string {
  return String(Math.ceil((bytes / 1024 / 1024) * 10) / 10).replace('.', ',');
}
