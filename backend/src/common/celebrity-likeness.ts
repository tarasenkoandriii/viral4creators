/**
 * Гейт на просьбы «сделай похожим на <конкретного человека>» — фича №35
 * компаньон-ТЗ, этап 5 плана
 * `docs-tz/AUDIT-Greeting-Landing-And-Upgrade-Plan.md`.
 *
 * ## Что этот модуль умеет и чего НЕ умеет
 *
 * Он **не знает, кто знаменитость**, и не пытается узнать. Списка имён
 * здесь нет намеренно: любой такой список устаревает за месяц, промахи
 * даёт в обе стороны и создаёт ложное чувство защищённости. Проверять
 * имя по внешнему сервису — отдельная интеграция с собственной ценой и
 * задержкой на каждом брифе.
 *
 * Он ловит другое, и это как раз то, что проверяемо: **просьбу сделать
 * похожим на названного человека**. Юридический риск создаёт не
 * упоминание имени («поздравь Марину»), а требование воспроизвести
 * чей-то образ или голос («в образе Пугачёвой», «голосом Хабенского»,
 * «looks like Tom Cruise»). Первое — обычное поздравление, второе —
 * ровно тот запрос, из-за которого на рынке уже идут судебные споры
 * (раздел 6 №35 компаньон-ТЗ).
 *
 * ## Почему пороги выставлены в сторону пропуска, а не блокировки
 *
 * Ошибка первого рода здесь дороже второго. Заблокированное
 * поздравление бабушке — сломанный продукт в самый неподходящий
 * момент; пропущенная экзотическая формулировка — риск, который
 * остаётся управляемым: кадр всё равно рисуется с явным запретом
 * узнаваемых людей в промпте (`greeting-frame-prompt.ts`), а готовый
 * ролик поздравления публикуется только через оператора.
 *
 * Поэтому триггеры узкие: слово «как» само по себе не считается
 * («поздравь как обычно», «как в детстве», «как Марина просила» —
 * всё это нормальный текст). Считается только явное указание на
 * ВНЕШНОСТЬ, ОБРАЗ или ГОЛОС рядом с именем собственным.
 */

/**
 * Имя собственное: слово с заглавной, ≥3 букв, кириллица или латиница.
 *
 * Заглавная буква — половина всей избирательности этого модуля,
 * поэтому у шаблонов ниже НЕТ флага `i`: он сделал бы `[A-ZА-Я]`
 * бессмысленным, и «голосом диктора» попало бы в отказ наравне с
 * «голосом Джигурды». Поймано собственным тестом, а не рассуждением.
 * Регистр первой буквы самого триггера разрешается явно (`[Гг]олос`) —
 * он может стоять в начале предложения.
 */
const NAME = "[A-ZА-ЯЁЇІЄҐ][a-zа-яёїієґ'’-]{2,}";

/**
 * Триггеры. Каждый — про воспроизведение конкретного человека, а не про
 * сравнение вообще. Порядок не важен, важен состав: добавляя сюда
 * строку, спросите себя, встретится ли она в обычном поздравлении.
 */
const PATTERNS: ReadonlyArray<{ re: RegExp; kind: string }> = [
  // ru/uk: внешность и образ
  { re: new RegExp(`[Пп]охож\\S*\\s+на\\s+(${NAME})`, 'u'), kind: 'likeness' },
  { re: new RegExp(`[Вв]\\s+образе\\s+(${NAME})`, 'u'), kind: 'likeness' },
  { re: new RegExp(`[Уу]\\s+образі\\s+(${NAME})`, 'u'), kind: 'likeness' },
  {
    re: new RegExp(`[Вв]игляда\\S*\\s+як\\s+(${NAME})`, 'u'),
    kind: 'likeness',
  },
  {
    re: new RegExp(`[Вв]ыгляд\\S*\\s+как\\s+(${NAME})`, 'u'),
    kind: 'likeness',
  },
  { re: new RegExp(`[Дд]войник\\S*\\s+(${NAME})`, 'u'), kind: 'likeness' },
  { re: new RegExp(`[Дд]війник\\S*\\s+(${NAME})`, 'u'), kind: 'likeness' },
  { re: new RegExp(`[Кк]осплей\\s+(${NAME})`, 'u'), kind: 'likeness' },
  // ru/uk: голос
  { re: new RegExp(`[Гг]олос(?:ом|у)\\s+(${NAME})`, 'u'), kind: 'voice' },
  // en
  { re: new RegExp(`[Ll]ooks?\\s+like\\s+(${NAME})`, 'u'), kind: 'likeness' },
  {
    re: new RegExp(`[Ll]ook-?alike\\s+of\\s+(${NAME})`, 'u'),
    kind: 'likeness',
  },
  {
    re: new RegExp(`[Ii]n\\s+the\\s+style\\s+of\\s+(${NAME})`, 'u'),
    kind: 'likeness',
  },
  {
    re: new RegExp(
      `(?:[Ii]mpersonat\\w*|[Dd]eepfake)\\s+(?:of\\s+)?(${NAME})`,
      'u',
    ),
    kind: 'likeness',
  },
  { re: new RegExp(`[Vv]oice\\s+of\\s+(${NAME})`, 'u'), kind: 'voice' },
];

export interface LikenessMatch {
  /** Что именно сработало — для сообщения человеку, а не для лога. */
  fragment: string;
  kind: string;
}

/**
 * Нашлась ли просьба воспроизвести конкретного человека.
 *
 * Возвращает первое совпадение: сообщение человеку всё равно одно, а
 * перечислять все найденные куски его текста обратно ему же — значит
 * превращать отказ в протокол.
 */
export function findCelebrityLikeness(
  text: string | null | undefined,
): LikenessMatch | null {
  const value = (text ?? '').trim();
  if (!value) return null;
  for (const { re, kind } of PATTERNS) {
    const m = re.exec(value);
    if (m) return { fragment: m[0].trim(), kind };
  }
  return null;
}

/**
 * Текст отказа. Здесь, а не на месте вызова: формулировка у гейта одна
 * на все точки применения, и менять её нужно в одном месте.
 *
 * Говорит, ЧТО убрать, и не читает нотаций: человек чаще всего не
 * задумывался о правах на образ, он просто хотел смешно.
 */
export function celebrityLikenessMessage(match: LikenessMatch): string {
  return (
    `Не получится сделать ролик, похожий на конкретного реального человека ` +
    `(«${match.fragment}») — это чужой образ, и права на него нам не принадлежат. ` +
    `Уберите это из текста, и всё остальное сгенерируется как обычно.`
  );
}
