/**
 * Тестовые пользователи: бесплатное использование по сценариям
 * (TODO §III п.37).
 *
 * ## Зачем
 *
 * Проверять продукт целиком должен живой человек живым аккаунтом — с
 * настоящим входом через Telegram, настоящими проектами и настоящими
 * вызовами провайдеров. Сегодня такому человеку мешает ровно одно:
 * суточный потолок расхода (`common/spend-limits.ts`). Один прогон
 * сценария поздравления с генерацией и аватаром съедает дневной лимит
 * Lite целиком, и дальше тестировать нечем до завтра.
 *
 * Обходить это переводом тестировщика в Premium неправильно: тариф
 * меняет ещё и НАБОР ФУНКЦИЙ, то есть проверяться будет не тот продукт,
 * который увидит пользователь. Нужен признак, который снимает потолок и
 * НЕ трогает ничего другого.
 *
 * ## Почему по сценариям, а не одним флагом
 *
 * Тестировщиков у продукта может быть несколько, и каждый ведёт свой
 * участок. Общий флаг «этому всё бесплатно» означает, что любой из них
 * может случайно сжечь бюджет на чужом сценарии — а узнаем мы об этом
 * из отчёта расходов через сутки. Чекбокс на сценарий ограничивает
 * ущерб тем участком, ради которого доступ и выдавался.
 *
 * ## Почему типы проектов 1 и 2 — один чекбокс
 *
 * Решение владельца продукта: `SINGLE` (один товар) и `LINE` (линейка)
 * — это один продуктовый сценарий, видеореклама товара. Разделять их в
 * интерфейсе значит спрашивать оператора о различии, которого для этой
 * задачи нет: тестируют их вместе и одним и тем же путём.
 */

/** Сценарий, на который выдаётся бесплатное использование. */
export type FreeScenario =
  /** Видеореклама товара: обычный проект и линейка (`SINGLE`, `LINE`). */
  | 'PRODUCT_VIDEO'
  /** Обучалка по сайту заказчика (`CLIENT_SITE`). */
  | 'CLIENT_SITE'
  /** Ролик-поздравление (`GREETING_VIDEO`). */
  | 'GREETING_VIDEO';

export const FREE_SCENARIOS: readonly FreeScenario[] = [
  'PRODUCT_VIDEO',
  'CLIENT_SITE',
  'GREETING_VIDEO',
];

/** Подписи для админки — там чекбоксы, а не коды. */
export const FREE_SCENARIO_LABELS: Record<FreeScenario, string> = {
  PRODUCT_VIDEO: 'Видеореклама товара (обычный проект и линейка)',
  CLIENT_SITE: 'Обучалка по сайту заказчика',
  GREETING_VIDEO: 'Ролик-поздравление',
};

/**
 * Тип проекта → сценарий.
 *
 * `null` означает «тип неизвестен», а не «сценария нет»: так отвечают
 * значения enum, появившиеся в схеме позже этого файла. Ответ `null`
 * ведёт к строгому правилу ниже, то есть новый тип проекта по умолчанию
 * НЕ становится бесплатным — забыть добавить его сюда безопасно.
 */
export function scenarioOfProjectType(
  type: string | null | undefined,
): FreeScenario | null {
  switch (type) {
    case 'SINGLE':
    case 'LINE':
      return 'PRODUCT_VIDEO';
    case 'CLIENT_SITE':
      return 'CLIENT_SITE';
    case 'GREETING_VIDEO':
      return 'GREETING_VIDEO';
    default:
      return null;
  }
}

/** Отбрасывает мусор и повторы; порядок — как в `FREE_SCENARIOS`. */
export function normalizeFreeScenarios(value: unknown): FreeScenario[] {
  if (!Array.isArray(value)) return [];
  const set = new Set(value.map((v) => String(v)));
  return FREE_SCENARIOS.filter((s) => set.has(s));
}

/** Есть ли в списке значения, которых мы не знаем (для отказа формы). */
export function unknownScenarios(value: unknown): string[] {
  if (!Array.isArray(value)) return [];
  const known = new Set<string>(FREE_SCENARIOS);
  return [...new Set(value.map((v) => String(v)))].filter((v) => !known.has(v));
}

/**
 * На что тратим. Три состояния, а не два, и третье добавлено аудитом
 * этапа 159.
 *
 *  - сценарий — операция принадлежит проекту известного типа;
 *  - `OUTSIDE_PROJECT` — проекта нет вовсе: клон голоса, озвучка,
 *    скетч, поиск на YouTube;
 *  - `UNKNOWN_PROJECT` — проект ЕСТЬ, но его тип коду ещё не знаком.
 *
 * Разница между двумя последними — не формальность. Свалив их в одно
 * `null`, мы сделали бы новый тип проекта бесплатным для всякого, у
 * кого стоит галочка «вне проекта», и потеряли бы свойство, записанное
 * у `scenarioOfProjectType`: забыть добавить туда новый тип безопасно.
 */
export type SpendTarget = FreeScenario | 'OUTSIDE_PROJECT' | 'UNKNOWN_PROJECT';

export interface TestAccess {
  isTestUser: boolean;
  freeScenarios: readonly string[];
  /**
   * Операции ВНЕ проекта: клон голоса, озвучка, ИИ-скетч, поиск на
   * YouTube (этап 159, §4.1 ТЗ на работу с тестировщиком).
   *
   * Отдельная галочка появилась вместо неявного правила «бесплатно,
   * только если отмечены ВСЕ три сценария». Само правило было верным
   * по происхождению — галочка на поздравлениях не должна открывать
   * бесплатный поиск референсов для товарки, — но тестировщику ОДНОГО
   * сценария оно означало, что половина его работы идёт за его счёт, и
   * узнавал он об этом в середине прогона.
   *
   * Галочка ничего не ослабляет: «все три» перестало быть неявным
   * условием и стало явным выбором оператора.
   */
  freeOutsideProject?: boolean;
  /**
   * До какого момента действует тестовый доступ (§4.2). `null` или
   * `undefined` — бессрочно, как было до приглашений.
   */
  testAccessUntil?: Date | null;
}

/** Действует ли тестовый доступ прямо сейчас. */
export function testAccessActive(
  access: TestAccess,
  now: Date = new Date(),
): boolean {
  if (!access.isTestUser) return false;
  // Срок гасит доступ САМ, строка при этом остаётся: по ней потом
  // видно, что человек тестировал и когда.
  return (
    !access.testAccessUntil || access.testAccessUntil.getTime() > now.getTime()
  );
}

/**
 * Снимается ли суточный потолок для этой операции.
 *
 * Три правила, и каждое — про то, чтобы ошибиться в сторону «платно»:
 *
 *  1. **Только тестовым.** Галочки сценариев без флага тестового
 *     пользователя не действуют. Иначе снятый флаг оставлял бы позади
 *     себя невидимое разрешение, которое однажды сработает на живом
 *     аккаунте.
 *  2. **Сценарий известен** — работает его галочка.
 *  3. **Сценарий неизвестен** (операция не привязана к проекту: клон
 *     голоса, озвучка, скетч, поиск на YouTube) — бесплатно по СВОЕЙ
 *     галочке `freeOutsideProject`. До этапа 159 условием было «все
 *     три сценария отмечены»: такую операцию нельзя отнести к участку,
 *     значит нельзя и списать на чей-то, а «хотя бы один» означал бы,
 *     что галочка на поздравления открывает бесплатный поиск
 *     референсов для товарки. Вывод верный, но для тестировщика ОДНОГО
 *     сценария он означал, что половина его работы идёт за его счёт —
 *     и узнавал он об этом в середине прогона. Теперь это явный выбор
 *     оператора, а не следствие трёх других галочек.
 *  4. **Срок вышел** — доступа нет, сколько бы галочек ни стояло
 *     (§4.2). Договорённость с тестировщиком срочная, и гаснуть она
 *     должна сама.
 */
export function isSpendFree(
  access: TestAccess,
  target: SpendTarget,
  now: Date = new Date(),
): boolean {
  if (!testAccessActive(access, now)) return false;
  // Switch, а не цепочка `if`, — чтобы разбор был ИСЧЕРПЫВАЮЩИМ
  // (аудит этапа 159). Проверка на `UNKNOWN_PROJECT` цепочкой `if`
  // пережила мутацию: без неё значение просто проваливалось в поиск по
  // списку сценариев и там не находилось. Ответ тот же, но по
  // случайности — он держался на том, что `'UNKNOWN_PROJECT'` не
  // совпадает ни с одним кодом сценария. Здесь же убрать ветку нельзя:
  // `never` ниже перестанет сходиться, и это увидит компилятор, а не
  // читатель.
  switch (target) {
    case 'UNKNOWN_PROJECT':
      // Проект ЕСТЬ, а сценария у него нет — это не «операция вне
      // проекта». Тип, о котором код ещё не знает, не должен
      // становиться бесплатным сам собой: «забыть добавить новый тип
      // сюда безопасно» — свойство, записанное у
      // `scenarioOfProjectType`, и галочка «вне проекта» не имеет
      // права его отменять.
      return false;
    case 'OUTSIDE_PROJECT':
      // Своя галочка, а не вывод из трёх других (этап 159). Пустой
      // список сценариев её не отменяет: «всё, что не привязано к
      // проекту» — самостоятельное разрешение, и человек, которому
      // дали только его, должен им пользоваться.
      return Boolean(access.freeOutsideProject);
    default:
      return normalizeFreeScenarios(access.freeScenarios as unknown[]).includes(
        exhaustive(target),
      );
  }
}

/** Сюда доходят только коды сценариев; иначе не сойдутся типы. */
function exhaustive(scenario: FreeScenario): FreeScenario {
  return scenario;
}
