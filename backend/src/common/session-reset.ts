/**
 * Что перестаёт быть верным при СМЕНЕ РЕФЕРЕНСА (этап 28).
 *
 * Половина состояния сессии описывает не товар и не бренд, а конкретный
 * референсный ролик: кастинг персонажей, снятые сцены и массовка, выбор
 * слотов референс-изображений и отчёт о релевантности. Стоит подставить
 * другой ролик — и всё это описывает уже не его.
 *
 * Раньше это соблюдалось только на одном из трёх путей (взять разбор из
 * библиотеки), а загрузка файла и ссылка на YouTube оставляли прежнее
 * состояние. Последствия были не косметические: отчёт о релевантности от
 * ПРОШЛОГО ролика продолжал уходить в бриф GPT секцией AUDIENCE FIT, то
 * есть в платную генерацию попадали советы про другое видео.
 *
 * Поэтому правило вынесено в одно место и применяется всеми тремя
 * путями. Что НЕ сбрасывается: товар, снимок манифеста бренда, сами
 * загруженные сцены (`scenes` — файлы пользователя, они переживают смену
 * референса и просто снова станут кандидатами) и готовый ролик, если он
 * уже был.
 */

import { Session } from './types/session.types';

/** Ключи сессии, привязанные к конкретному референсу. */
export const REFERENCE_DERIVED_KEYS = [
  'characterCasting',
  'analysisSelection',
  'referenceSelection',
  'relevance',
] as const;

/**
 * Патч для `updateSession`: сбрасывает всё, что описывало прежний
 * референс. `undefined` здесь — именно «очистить»: SessionService пишет
 * в JSON `session[key] ?? null`.
 */
export function referenceResetPatch(): Partial<Session> {
  return Object.fromEntries(
    REFERENCE_DERIVED_KEYS.map((key) => [key, undefined]),
  ) as Partial<Session>;
}
