/**
 * Категории поиска трендовых роликов для блога (§36 SPEC, этап 57).
 *
 * ## Почему это отдельный файл с двумя функциями, а не одна строка
 *
 * У списка категорий ДВЕ работы, и до 24.09.2026 они мешали друг другу.
 * Первая — сказать, что искать. Вторая — быть выключателем: пустой
 * список останавливал генератор целиком, и это была единственная
 * кнопка «выключить блог» во всём продукте.
 *
 * Владелец попросил умолчание (`viral,ai,voice`), чтобы блог заработал
 * без похода в настройки. Просто подставить его вместо пустоты значило
 * бы отобрать выключатель у фичи, которая тратит настоящие деньги:
 * квоту YouTube Search, вызовы Gemini на каждый кандидат и перевод
 * Grok на пять локалей. Поэтому различаются два РАЗНЫХ состояния
 * переменной:
 *
 *  - её нет вовсе — умолчание: ничего не настраивали, пусть работает;
 *  - она задана пустой (`BLOG_CATEGORIES=`) — выключено НАМЕРЕННО, и
 *    подставлять сюда своё мнение нельзя.
 *
 * Различие обычное для переменных окружения, но незаметное, поэтому оно
 * названо в обоих документах (`doc/DEPLOYMENT.md`, `.env.docker.example`)
 * и видно на экране кронов: выключенный генератор пишет «выключен
 * намеренно», а не «не задано».
 */

/** Умолчание владельца (24.09.2026): три темы, вокруг которых продукт. */
export const DEFAULT_BLOG_CATEGORIES: readonly string[] = [
  'viral',
  'ai',
  'voice',
];

/** Разбор списка: запятые, пробелы и пустые элементы человеку прощаем. */
function parse(raw: string): string[] {
  return raw
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);
}

export function blogCategories(env: NodeJS.ProcessEnv = process.env): string[] {
  const raw = env.BLOG_CATEGORIES;
  if (raw === undefined) return [...DEFAULT_BLOG_CATEGORIES];
  return parse(raw);
}

/**
 * Блог выключен решением человека, а не недосмотром.
 *
 * Нужно ровно для того, чтобы экран кронов говорил разное в двух
 * случаях: «выключен намеренно» и «не хватает ключа». Первое — не
 * проблема, второе — проблема, и путать их нельзя.
 */
export function blogDisabledExplicitly(
  env: NodeJS.ProcessEnv = process.env,
): boolean {
  const raw = env.BLOG_CATEGORIES;
  return raw !== undefined && parse(raw).length === 0;
}
