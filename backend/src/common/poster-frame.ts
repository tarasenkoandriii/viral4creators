/**
 * Кадр-постер опубликованного ролика: команда ffmpeg и её параметры.
 *
 * Зачем он нужен. У публичной страницы `/video/[id]` не было `og:image`
 * вовсе: у поздравления товарного фото нет по определению, а превью
 * самого ролика не существовало — `GeneratedVideo.thumbnailUrl` не
 * заполнял никто. Ссылка, присланная получателю, разворачивалась в
 * голую текстовую карточку — у типа проекта, весь смысл которого в
 * отправке ссылки.
 *
 * Откуда берётся кадр. Из УЖЕ ГОТОВОГО файла страницы — того, который
 * лежит в нашем Blob после постобработки. Это важно: к этому моменту
 * ролик уже обрезан под нужный формат, и в него уже вшиты титры,
 * наклейка и субтитры. Кадр, вынутый из исходника до постобработки, был
 * бы другого формата и без всего этого — то есть показывал бы не то,
 * что человек откроет по ссылке.
 *
 * Почему без масштабирования. Фильтры `scale` с выражениями вроде
 * `min(1280,iw)` требуют экранирования запятых, а команда уходит
 * строкой в чужой сервис, разбор которой мы не контролируем. Кадр в
 * родном разрешении — 200-400 КБ, это втрое меньше потолка любой
 * соцсети, и он же идёт в `poster` у `<video>`, где родное разрешение
 * как раз и нужно. Экономия не стоила бы риска сломать команду.
 */

/** Имя выходного файла в задаче ffmpeg. */
export const POSTER_OUTPUT_NAME = 'poster.jpg';

/**
 * С какой секунды берём кадр.
 *
 * Не нулевая: первый кадр у видеомоделей часто тёмный (сцена ещё
 * проявляется), и постером он выглядит как сломанная картинка. Секунда
 * есть у любого ролика продукта — самый короткий формат длится пять.
 */
export const POSTER_AT_SECOND = 1;

/** Качество JPEG в шкале ffmpeg `-q:v`: 2 — лучшее, 31 — худшее. */
export const POSTER_QUALITY = 3;

export interface PosterFramePlan {
  outputName: string;
  command: string;
}

export function planPosterFrame(opts?: {
  inputKey?: string;
  outputName?: string;
  atSecond?: number;
  quality?: number;
}): PosterFramePlan {
  const inputKey = opts?.inputKey?.trim() || 'video';
  const outputName = opts?.outputName?.trim() || POSTER_OUTPUT_NAME;
  // Отрицательная секунда развернулась бы в `-ss -1` и увела бы команду
  // в непредсказуемое поведение ffmpeg вместо понятного отказа.
  const at = Math.max(0, opts?.atSecond ?? POSTER_AT_SECOND);
  const quality = Math.min(31, Math.max(2, opts?.quality ?? POSTER_QUALITY));
  return {
    outputName,
    // `-ss` ПЕРЕД `-i` — быстрая перемотка по ключевым кадрам: ffmpeg не
    // декодирует всё до нужной секунды. Для одного кадра разница между
    // мгновенной задачей и полной раскруткой ролика.
    command:
      `-ss ${at} -i {{${inputKey}}} -frames:v 1 -q:v ${quality} ` +
      `{{${outputName}}}`,
  };
}
