/**
 * Какая сборка сейчас работает (этап 154, `docs-tz/TZ-Rabota-s-Testirovshchikom.md`
 * §8 этап 0).
 *
 * ## Зачем
 *
 * Первое, что спрашивают у любого баг-репорта, — «на какой сборке».
 * До этого этапа ответить было нечем: ни во фронтенде, ни в бэкенде не
 * было ни версии, ни штампа коммита. Тикет месячной давности не
 * отличался по смыслу от сегодняшнего — а именно это решает, чинить или
 * закрывать.
 *
 * ## Почему бэкенд не знает, КОГДА он собран
 *
 * На serverless нет «момента старта процесса», от которого можно
 * отсчитывать: `new Date()` при загрузке модуля — это время холодного
 * старта, и оно разное у каждого экземпляра. Дата сборки, посчитанная
 * так, врала бы убедительно. Поэтому бэкенд отвечает коммитом и только
 * им; дату несёт фронтенд, который собирается по-настоящему и знает её
 * (`frontend/src/lib/build-info.ts`).
 *
 * ## Почему это НЕ уходит в `/health`
 *
 * У `/health` в шапке записано прямо: «наружу отдаём только факт связи с
 * БД — ни версий, ни имён хостов». Коммит на анонимном маршруте говорит
 * постороннему, какой именно код сейчас работает. Решение это старше
 * нашей задачи, и отменять его мимоходом ради удобства нельзя: версия
 * видна оператору в админке и попадает в тикет, где она и нужна.
 */

export interface BuildInfo {
  /** Короткий хеш коммита или null, если его неоткуда взять. */
  commit: string | null;
  /** Человекочитаемая строка для показа и для тикета. */
  build: string;
}

/** Ровно семь символов: столько, сколько печатает `git log --oneline`. */
const SHORT = 7;

/**
 * Похоже ли значение на хеш коммита.
 *
 * Проверка нужна не от злого умысла, а от пустой строки и от `"undefined"`,
 * которое приезжает строкой, когда переменную подставили шаблоном.
 * Обрезать их до семи символов значило бы напечатать «undefi» и выдать
 * это за версию.
 */
function looksLikeSha(value: string): boolean {
  return /^[0-9a-f]{7,40}$/i.test(value);
}

export function describeBuild(env: NodeJS.ProcessEnv = process.env): BuildInfo {
  // `BUILD_ID` первым: он задаётся руками и должен побеждать
  // автоматический, иначе им нельзя было бы пометить нестандартную
  // сборку.
  const explicit = env.BUILD_ID?.trim();
  if (explicit) {
    return { commit: null, build: explicit };
  }
  const sha = env.VERCEL_GIT_COMMIT_SHA?.trim() ?? '';
  if (looksLikeSha(sha)) {
    const short = sha.slice(0, SHORT).toLowerCase();
    return { commit: short, build: short };
  }
  // Ни того, ни другого — это локальный запуск. `dev` честнее пустоты:
  // в тикете видно, что сборка неопознанная, а не что поле потеряли.
  return { commit: null, build: 'dev' };
}
