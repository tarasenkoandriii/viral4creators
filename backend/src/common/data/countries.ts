const BY_CODE: ReadonlyMap<string, CountryRef> = new Map(
  COUNTRIES.map((c) => [c.code, c]),
);

/** Страна по ISO-коду (регистронезависимо); undefined для неизвестного кода. */
export function findCountry(code: string): CountryRef | undefined {
  return BY_CODE.get(code.trim().toUpperCase());
}

/** Валюта страны по ISO-коду; undefined для неизвестного кода. */
export function currencyForCountry(code: string): string | undefined {
  return findCountry(code)?.currency;
}
