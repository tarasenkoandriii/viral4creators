/**
 * Справочник стран → валюта (ISO 3166-1 alpha-2 → ISO 4217) —
 * doc/PRODUCT-PROJECT-SPEC.md §6.3, этапы 3 и 6 плана реализации.
 *
 * Статические данные в репозитории, не таблица в БД: справочник не
 * меняется рантаймом (см. план, Этап 6). Сгенерировано из CLDR через
 * babel 2.18 (`Locale('en').territories` + `get_territory_currencies(
 * tender=True)`), т.е. это ОФИЦИАЛЬНЫЙ legal-tender маппинг Unicode
 * CLDR, а не набранный руками список. Отфильтрованы не-страны
 * (числовые регионы 001/150/…, EU/EZ/UN/QO/ZZ, XA/XB, XK без ISO-кода) и
 * территории без валюты (AQ, CP, CQ). Итого 253 стран.
 *
 * Правки поверх CLDR-снимка помечены `// override:` с причиной — CLDR в
 * babel отстаёт от реальности на несколько месяцев, и по состоянию на
 * сентябрь 2026 это критично ровно для одной страны (BG → EUR).
 *
 * Для стран с несколькими законными валютами (напр. ZW) берётся ПЕРВАЯ
 * по CLDR — для ценника этого достаточно; ручной override валюты
 * независимо от страны сознательно не заводится (ТЗ §7.2, решено).
 *
 * `language` — из тех же данных CLDR (likely subtags).
 *
 * Названия на двух языках — чтобы селектор с поиском на фронте (§6.3:
 * «не простой <select> на 190+ пунктов») искал и по «Украина», и по
 * «Ukraine», без Intl.DisplayNames на клиенте (в Telegram WebView его
 * поддержка/локали не гарантированы).
 */

export interface CountryRef {
  /** ISO 3166-1 alpha-2, напр. "UA". */
  code: string;
  /** ISO 4217, напр. "UAH" — валюта цены проекта, выводится из страны при создании (Project.currency). */
  currency: string;
  /**
   * ISO 639-1 — наиболее вероятный язык страны по CLDR likely-subtags
   * (`Locale.parse('und_UA').language` → "uk"). Используется как `hl`
   * в запросах к SerpApi Google Lens (§6.1): язык выдачи под рынок
   * проекта. Не «официальный язык», а «какой язык CLDR считает самым
   * вероятным для этой территории» — для KZ это "ru", для BE — "nl".
   */
  language: string;
  nameEn: string;
  nameRu: string;
}

