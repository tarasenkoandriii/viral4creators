/**
 * Ключевой фильтр текста — тот самый, на который опирается
 * `PromptService.moderateText()` и, через него, отказ рендерить
 * поздравление с `moderationStatus: FLAGGED`.
 *
 * ## Что было и почему это не работало
 *
 * До этой правки фильтр состоял из четырёх английских регулярок со
 * `\b`. Для продукта, у которого половина аудитории пишет по-русски и
 * по-украински, это означало ровно одно: гейт не ловил почти ничего.
 * Хуже того, `\b` в JS без флага `u` опирается на `\w` = `[A-Za-z0-9_]`,
 * то есть вокруг кириллицы он срабатывает не там, где кажется.
 *
 * ## Почему нельзя просто дописать русские слова
 *
 * У продукта есть повод СОБОЛЕЗНОВАНИЕ. Соболезнование по-русски — это
 * «смерть», «утрата», «похороны», «умер». Наивный список слов про
 * смерть заблокировал бы именно тот повод, ради которого его завели, и
 * человек получил бы отказ в самый неподходящий момент своей жизни.
 *
 * Поэтому насилие ловится не упоминанием смерти, а АДРЕСОВАННОЙ
 * угрозой: «убью тебя», «чтоб ты сдох». Связка «действие + адресат» —
 * то, что отличает угрозу от соболезнования, и отличает надёжнее
 * любого списка существительных.
 *
 * ## Обход
 *
 * Простейший обход списка слов — гомоглифы: латинская `a` вместо
 * кириллической `а` выглядит так же, а регуляркой не ловится. Плюс
 * невидимые символы и растянутые буквы. Всё это снимается
 * нормализацией ДО сопоставления — и той же нормализацией проходят
 * сами основы, иначе свёртка ломала бы английские слова.
 *
 * ## Чем это не является
 *
 * Это дешёвый первый гейт, а не модерация. Списком слов нельзя поймать
 * намёк, сарказм или свежий жаргон, и любой такой список устаревает.
 * Настоящий ответ — модерационный API или отдельный вызов модели; он
 * стоит денег на каждом промпте, поэтому это решение владельца, а не
 * умолчание.
 */

export type ModerationCategory =
  | 'sexual-content'
  | 'hate-speech'
  | 'threat'
  | 'illegal-content';

/** Пары «латиница → кириллица», неразличимые глазом. */
const HOMOGLYPHS: Record<string, string> = {
  a: 'а',
  c: 'с',
  e: 'е',
  o: 'о',
  p: 'р',
  x: 'х',
  y: 'у',
  k: 'к',
  m: 'м',
  t: 'т',
  h: 'н',
  b: 'в',
  i: 'і',
  '3': 'з',
  '0': 'о',
  '4': 'ч',
};

/**
 * Невидимые символы: нулевой ширины, управляющие направлением письма,
 * мягкий перенос. Регулярка собирается из строки с экранированием, а
 * не литералом: в литерале это буквально невидимые байты в исходнике —
 * прочитать их нельзя, а потерять при правке легко.
 */
const INVISIBLE = new RegExp(
  '[\\u200B-\\u200F\\u202A-\\u202E\\u2060\\uFEFF\\u00AD]',
  'g',
);

/**
 * Приводит текст к виду, в котором сопоставление имеет смысл.
 *
 * Порядок важен: сначала убираем невидимое, потом складываем
 * гомоглифы, потом схлопываем растянутые буквы. Иначе «у‌б‌и‌ю» с
 * нулевыми ширинами внутри не станет словом, а «уууубью» останется
 * непохожим на «убью».
 */
export function normalizeForModeration(text: string): string {
  if (!text) return '';
  return (
    text
      .toLowerCase()
      .normalize('NFKC')
      .replace(INVISIBLE, '')
      .replace(/[a-z0-9]/g, (ch) => HOMOGLYPHS[ch] ?? ch)
      // Три и больше одинаковых подряд — растягивание, а не слово. Две
      // оставляем: иначе «аллея» и «ссора» ломались бы на ровном месте.
      .replace(/(.)\1{2,}/gu, '$1')
  );
}

/** Экранирование литерала внутри регулярки. */
function escape(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Основы → регулярка с границей слева.
 *
 * Основы проходят ТУ ЖЕ нормализацию, что и текст: гомоглифная
 * свёртка, которая чинит подмену букв, иначе ломала бы английские
 * слова — «explicit» после свёртки перестаёт совпадать сам с собой.
 *
 * Граница слева обязательна: без неё основа ловилась бы в середине
 * чужого слова. Справа границы НЕТ намеренно — русский и украинский
 * склоняются, и основа должна ловить все окончания сразу.
 */
function stemPattern(stems: readonly string[]): RegExp {
  const body = stems.map((s) => escape(normalizeForModeration(s))).join('|');
  return new RegExp(`(?<![\\p{L}\\p{N}])(?:${body})`, 'iu');
}

/**
 * Угроза = действие + адресат. Хранится группами слов, а не готовой
 * регуляркой, по той же причине: группы нормализуются вместе с
 * текстом, а синтаксис регулярки нормализовать нельзя — `\p{L}` после
 * свёртки гомоглифов перестал бы быть классом букв.
 */
function phrasePattern(groups: readonly (readonly string[])[]): RegExp {
  const body = groups
    .map(
      (group) =>
        `(?:${group.map((v) => escape(normalizeForModeration(v))).join('|')})`,
    )
    .join('\\s+');
  return new RegExp(`(?<![\\p{L}\\p{N}])${body}`, 'iu');
}

