const COMPILED: Array<{ category: ModerationCategory; pattern: RegExp }> = [
  ...(
    Object.entries(CATEGORY_STEMS) as Array<
      [Exclude<ModerationCategory, 'threat'>, readonly string[]]
    >
  ).map(([category, stems]) => ({
    category: category as ModerationCategory,
    pattern: stemPattern(stems),
  })),
  ...THREAT_PHRASES.map((groups) => ({
    category: 'threat' as ModerationCategory,
    pattern: phrasePattern(groups),
  })),
];

/**
 * Категории, сработавшие на тексте. Пустой массив — чисто.
 *
 * Одна категория встречается в ответе один раз, даже если сработало
 * несколько её выражений: вызывающему нужно «что не так», а не
 * «сколько раз».
 */
export function findModerationFlags(text: string): ModerationCategory[] {
  if (!text?.trim()) return [];
  const normalized = normalizeForModeration(text);
  const found = new Set<ModerationCategory>();
  for (const { category, pattern } of COMPILED) {
    if (pattern.test(normalized)) found.add(category);
  }
  return [...found];
}
