/**
 * Граница бесплатного — «Условно бесплатный Lite» §4, §8, этап 132.
 *
 * ## Что здесь и чего здесь нет
 *
 * Здесь чистые правила и чтение настроек: ни Prisma, ни сервисов, ни
 * знания о том, как устроена сессия. Решение «пускать или нет»
 * принимает `RenderAccessService`, а проверить САМО ПРАВИЛО — то есть
 * прочитать три строки и убедиться, что в них нет дыры, — можно здесь,
 * не держа в голове половину продукта.
 *
 * ## Почему рубильник — переменная окружения
 *
 * Фича способна остановить генерацию всем новым пользователям разом,
 * поэтому включается отдельно от деплоя. Настройки платформы с
 * карточкой в админке (как у советника в мастере) здесь нарочно нет:
 * у советника настройку крутят регулярно — бюджет, лимит, пороги, — а
 * этот рубильник переключают один раз в жизни. Ровно так же держит
 * выключенной целую подсистему оплаты `PLANS_BILLING_ENABLED`.
 */

/** Причины бесплатных начислений. Совпадают с `CreditLedgerReason`. */
export type FreeGrantReason =
  /** Первая генерация новому пользователю, без условий (§4.1). */
  | 'WELCOME'
  /** За подтверждённую подписку на канал — этап 133. */
  | 'SUBSCRIPTION'
  /** За подтверждённое приглашение — этап 134. */
  | 'REFERRAL'
  /** Приглашённому, в тот же момент, что и пригласившему — этап 134. */
  | 'REFERRAL_INVITEE';

export const FREE_GRANT_REASONS: readonly FreeGrantReason[] = [
  'WELCOME',
  'SUBSCRIPTION',
  'REFERRAL',
  'REFERRAL_INVITEE',
];

/** Рубильник. Выключен — продукт ведёт себя ровно как до этапа 132. */
export function wallEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  return env.FREE_TIER_WALL_ENABLED === 'true';
}

/**
 * Потолок бесплатных начислений в сутки на ВСЮ программу.
 *
 * Это предохранитель против нашей же ошибки, а не против мошенника
 * (от накрутки защищает цена накрутки — §5.4 ТЗ). Одна опечатка в
 * условии засчёта дороже любого злоумышленника, и стоит она ровно
 * столько, сколько успеет начислить до того, как её заметят.
 *
 * Ноль — законное значение («приостановить начисления»), мусор и
 * отрицательное дают умолчание: сломанная настройка не должна молча
 * выключать программу.
 */
export const DEFAULT_FREE_GRANT_DAILY_CAP = 50;

export function freeGrantDailyCap(
  env: NodeJS.ProcessEnv = process.env,
): number {
  const raw = env.FREE_GRANT_DAILY_CAP;
  if (!raw) return DEFAULT_FREE_GRANT_DAILY_CAP;
  const n = Number(raw);
  return Number.isInteger(n) && n >= 0 ? n : DEFAULT_FREE_GRANT_DAILY_CAP;
}

/**
 * Дата, до которой зарегистрированные сохраняют прежний доступ.
 *
 * Не `now()` и не день включения рубильника, а ровно та дата, что
 * стоит в пункте 6.9.3 оферты: код и документ, обещающий человеку
 * сохранение доступа, обязаны называть одну дату. Разойдись они — спор
 * выиграет документ, а объясняться придётся нам.
 */
export const GRANDFATHER_BEFORE = new Date('2026-09-24T00:00:00.000Z');

/** Из чего может взяться снятая стена. Совпадает с `LiteUnlockSource`. */
export type LiteUnlockSource = 'EARNED' | 'GRANDFATHERED' | 'OPERATOR';

/** Ровно те поля пользователя, которые нужны правилу. */
export interface RenderRightInput {
  /** Стена снята: заработано, сохранено или выдано оператором. */
  liteUnlockedAt?: Date | null;
  /** Отозвано оператором — с причиной, а не молчаливым NULL. */
  liteRevokedAt?: Date | null;
  /** Есть действующая ОПЛАЧЕННАЯ подписка. */
  hasActiveSubscription?: boolean;
}

/**
 * Есть ли у человека право рендерить без кредитов.
 *
 * Два «почему», оба оплачены аудитом:
 *
 *  1. **Подписка читается строкой `Subscription`, а НЕ `users.plan`.**
 *     Пока `PLANS_BILLING_ENABLED !== 'true'`, пользователь ставит себе
 *     любой режим сам (`planSelfService`), и стена, глядящая на режим,
 *     снималась бы одной кнопкой в интерфейсе.
 *  2. **Отзыв сильнее разблокировки, но только если он позже её.**
 *     Из этого само собой работает повторное открытие доступа: оператор
 *     разблокирует заново, не стирая историю отзыва.
 */
export function hasRenderRight(input: RenderRightInput): boolean {
  if (input.hasActiveSubscription) return true;
  const unlocked = input.liteUnlockedAt;
  if (!unlocked) return false;
  const revoked = input.liteRevokedAt;
  return !revoked || revoked.getTime() < unlocked.getTime();
}
