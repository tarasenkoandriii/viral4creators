/**
 * Проверочный набор распознавания реплик мастера поздравления — приёмка
 * §8.3 ТЗ docs-tz/TZ-Greeting-2.0-Adaptive-Persona-Landing.md: «не меньше
 * 100 фраз на русском и 100 на украинском, с именами, датами, возрастом и
 * суржиком». Пороги ошибки — по базовой цифре на этом наборе (§8.3), здесь
 * их нет.
 *
 * Реплики — те, что человек говорит мастеру: значение поля (имя, дата,
 * возраст), команда, просьба к тексту (§4А.2, §4А.7).
 *
 * Поля фразы:
 * - `text` — ЧТО ПРОИЗНОСИТСЯ и главный эталон: числа словами, как их
 *   говорят (это же уходит в синтез речи);
 * - `alt` — допустимые записи того же (цифрами: «12 марта»): распознавание
 *   вправе вернуть любую, WER — по ближайшей;
 * - `names` — имена в той форме, в какой они стоят в тексте (с падежом):
 *   по ним считается точность имён;
 * - `hints` — имена брифа в именительном (получатель, отправитель) —
 *   уходят подсказкой распознаванию, как в продукте
 *   (`GreetingVoiceService.transcribe`: `names: [recipientName,
 *   senderName]`). Нет — берётся `DEFAULT_HINTS` языка;
 * - `tags` — чем фраза трудна. `surzhyk` — смешанная речь: она исключается
 *   из «совпадения языка» (§8.3: «где говорящий не переключал язык»).
 *
 * Имена — распространённые, без фамилий; фразы выдуманы.
 */

export type SpeechLanguage = 'ru' | 'uk';
export type SpeechTag =
  | 'name'
  | 'date'
  | 'age'
  | 'surzhyk'
  | 'command'
  | 'field';

export interface SpeechPhrase {
  id: string;
  lang: SpeechLanguage;
  text: string;
  alt?: string[];
  names?: string[];
  hints?: string[];
  tags: SpeechTag[];
}

/** Имена брифа по умолчанию — подсказка распознаванию у фраз без своих. */
export const DEFAULT_HINTS: Record<SpeechLanguage, string[]> = {
  ru: ['Марина', 'Андрей'],
  uk: ['Мирослава', 'Тарас'],
};

type Row = [
  id: number,
  text: string,
  tags: SpeechTag[],
  extra?: Omit<SpeechPhrase, 'id' | 'lang' | 'text' | 'tags'>,
];

function phrases(lang: SpeechLanguage, rows: Row[]): SpeechPhrase[] {
  return rows.map(([n, text, tags, extra]) => ({
    id: `${lang}-${String(n).padStart(3, '0')}`,
    lang,
    text,
    tags,
    ...(extra ?? {}),
  }));
}

