-- Отметка о вычитке реплик оператором (§3-бис.5 ТЗ
-- docs-tz/TZ-Tutorial-Video-Voiced.md, этап D).
--
-- Приставка `narration` в именах обязательна и не косметическая: у
-- `TutorialVideoAsset` уже есть `reviewed` — «ролик можно показывать
-- людям», а у самого сценария `approved` — «можно тратить деньги на
-- его платные шаги». Голое `reviewedBy` смешало бы три разных решения
-- в одно слово; схема эту пару старательно разводит в доккомментарии
-- к `approved`, и третье значение обязано называться своим именем.
--
-- Строка сценария своя на каждую локаль (@@unique([subjectKey,
-- locale]), этап C), поэтому отметка тоже своя: видно, какие языки
-- человек действительно смотрел, а не «прочитал русский — считаем
-- прочитанными все пять».
--
-- Обе колонки необязательные, без умолчания и без индекса: читаются
-- они только вместе со строкой сценария, которую и так выбирают по
-- (subjectKey, locale) или по id. Сценарии, сгенерированные до этого
-- этапа, остаются с NULL — «не вычитано», и это верно: их никто не
-- вычитывал.
ALTER TABLE "tutorial_scenarios"
  ADD COLUMN IF NOT EXISTS "narrationReviewedBy" TEXT,
  ADD COLUMN IF NOT EXISTS "narrationReviewedAt" TIMESTAMP(3);
