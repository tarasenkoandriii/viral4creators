-- Отпечаток входов сборки (ТЗ docs-tz/TZ-Tutorial-Video-Voiced.md §7.2:
-- «Величина разовая: ролики пересобираются, когда меняется интерфейс
-- или текст шага, а не по расписанию»).
--
-- До этой колонки обещание не выполнялось: ночной прогон отправлял
-- платную задачу ffmpeg на КАЖДЫЙ успешный сценарий каждую ночь — те
-- же кадры, та же (закешированная) дорожка, тот же mp4. Сравнить было
-- не с чем: кадры транзитные и удаляются сразу после сборки, а
-- `blobUrl` — это результат, а не вход.
--
-- Колонка необязательная и без индекса намеренно: читается она ровно
-- одной выборкой «последний собранный ролик этой пары», которая и так
-- идёт по `@@index([subjectKey, locale, createdAt])`. Старые строки
-- остаются с NULL — для них отпечаток неизвестен, и первая же ночь
-- пересоберёт ролик один раз, заполнив колонку.
ALTER TABLE "tutorial_video_assets" ADD COLUMN IF NOT EXISTS "contentHash" TEXT;
