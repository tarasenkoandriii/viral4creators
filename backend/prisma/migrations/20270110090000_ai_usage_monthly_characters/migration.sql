-- Символы синтезированной речи в свёртке журнала расходов (этап F ТЗ
-- docs-tz/TZ-Tutorial-Video-Voiced.md, приёмка §11 п.22: «расход виден
-- отдельной операцией, с числом символов»).
--
-- Сырая строка `ai_usage` символы хранит с этапа 35, а свёртка — нет:
-- в неё ложились только деньги и число вызовов. Отчёт «за всё время»
-- собирается из обеих таблиц, и без этой колонки символы по месяцу
-- пропадали бы в момент свёртки — молча и безвозвратно, потому что
-- сырые строки после неё удаляются.
--
-- Потерь на уже свёрнутых месяцах нет: журнал ведётся с 06.09.2026,
-- срок хранения сырых строк — 90 дней, и первый месяц станет пригоден
-- к свёртке не раньше конца декабря 2026. То есть умолчание 0 здесь
-- ни одной существующей строки не касается; появись такие строки,
-- 0 значил бы «не знаем», и заниженное число это было бы честно
-- названо в доккомментарии `RollupBucket.characters`.
--
-- INTEGER, а не BIGINT, как у денег: месяц одного пользователя на
-- одной модели в два миллиарда символов — это счёт синтеза на
-- полмиллиона долларов. И главное отличие от денег — переполнение
-- здесь ГРОМКОЕ, а не молчаливое: `sum()` отдаёт bigint, вставка
-- больше 2^31 в эту колонку падает с «integer out of range», и
-- транзакция свёртки откатывается целиком, оставляя сырые строки
-- месяца на месте (проверено на Postgres 16). Потерять данные так
-- нельзя, только не свернуть месяц. Суммы по многим месяцам в
-- отчёте Postgres и так возвращает как bigint.
ALTER TABLE "ai_usage_monthly"
  ADD COLUMN IF NOT EXISTS "characters" INTEGER NOT NULL DEFAULT 0;
