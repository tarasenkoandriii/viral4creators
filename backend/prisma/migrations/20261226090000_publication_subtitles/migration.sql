-- Субтитры в заявке на публикацию (этап 137,
-- docs-tz/TZ-Multilingual-YouTube.md).
--
-- `.srt` кладётся в снимок заявки рядом с заголовком и описанием, а не
-- читается из сессии в момент выгрузки: заявка переживает TTL-очистку
-- сессий, и перечитать реплики потом будет неоткуда. У ролика,
-- собранного с выключенными субтитрами (умолчание), файла `.srt` не
-- существует вовсе — текст собирается из реплик при постановке в
-- очередь, без ffmpeg: субтитры это текст, а не картинка.
--
-- Две служебные колонки рядом — чтобы «субтитры не загрузились» имело
-- ответ в базе, а не только в логе: у канала могло не быть расширенного
-- согласия, или площадка могла отказать.
ALTER TABLE "publication_requests"
  ADD COLUMN "subtitlesSrt" TEXT,
  ADD COLUMN "captionsUploadedAt" TIMESTAMP(3),
  ADD COLUMN "captionsError" TEXT;
