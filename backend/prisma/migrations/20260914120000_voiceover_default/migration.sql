-- Доп. запрос владельца продукта (14.09.2026): модели (Veo и Grok
-- одинаково) читают кириллицу с неверными ударениями, поэтому свой
-- синтез поверх ролика (voiceover) становится режимом по умолчанию, а
-- голос модели — осознанным исключением, которое выбирают вручную
-- (в манифесте бренда или переключателем на шаге генерации).
--
-- Две части, намеренно раздельные:
--  1. Новые бренды — через DEFAULT колонки.
--  2. Существующие бренды, у которых режим остался заводским 'veo',
--     переводятся на 'voiceover'. Это единственный способ, чтобы НОВЫЕ
--     сессии таких брендов сразу шли со своим голосом — снимок сессии
--     замораживает режим бренда при создании (snapshot.ts). Уже
--     созданные сессии (Session.data.brandManifestSnapshot) не трогаем:
--     их режим — часть отснятого ролика.
--     Если на стенде есть бренды, где 'veo' выбран осознанно, — уберите
--     UPDATE перед применением.
ALTER TABLE "brand_manifests" ALTER COLUMN "voiceMode" SET DEFAULT 'voiceover';

UPDATE "brand_manifests" SET "voiceMode" = 'voiceover' WHERE "voiceMode" = 'veo';
