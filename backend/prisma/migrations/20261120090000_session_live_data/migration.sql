-- Этап 122 — горячие ключи сессии в отдельную колонку (В-4.2 третьего
-- аудита).
--
-- Написана руками — сеть до binaries.prisma.sh недоступна в песочнице
-- разработки (doc/CI.md); применена и проверена на настоящем
-- PostgreSQL 16 в песочнице вместе со всеми предыдущими 59 миграциями.
--
-- ## Почему колонка, а не индекс и не `jsonb_set`
--
-- jsonb — неизменяемый датум: точечная правка порождает новое значение
-- и переписывает TOAST целиком. Замер третьего аудита это показал
-- (`jsonb_set` не дешевле полной перезаписи), повторный замер на PG 16
-- подтвердил: 1000 правок статуса рендера в общей колонке — 8,4 МБ WAL,
-- те же 1000 правок в отдельной маленькой колонке — 0,16 МБ.
--
-- ## Почему КОПИЯ, а не перенос
--
-- Миграции применяются на сборке, то есть ДО того, как новый код
-- начнёт обслуживать запросы: несколько минут старый код работает с
-- новой схемой. Если бы эта миграция вырезала ключи из `data`, старый
-- код в это окно видел бы сессию без `generatedVideo` — и хуже всего,
-- что он бы ПИСАЛ по этому пустому месту: `generationStatus` стал бы
-- NULL, а суточная уборка удаляет всё, что не `complete`, вместе с уже
-- оплаченными роликами. Поэтому здесь только копия; лишние копии из
-- `data` убирает сам новый код при первой же записи в сессию (см.
-- `SessionService.updateSession`), а окончательная зачистка колонки —
-- отдельной миграцией, когда в проде не останется сессий со старой
-- раскладкой.
--
-- Отсюда же идемпотентность: строка, которую новый код уже переписал,
-- ключей в `data` не имеет, условие `?|` её не выбирает, и повторный
-- прогон миграции не затрёт свежий `liveData` старой копией.
ALTER TABLE "sessions" ADD COLUMN IF NOT EXISTS "liveData" JSONB NOT NULL DEFAULT '{}';

UPDATE "sessions"
SET "liveData" = "liveData" || (
      SELECT COALESCE(jsonb_object_agg(k, v), '{}'::jsonb)
      FROM jsonb_each("data") AS e(k, v)
      WHERE k IN ('generatedVideo', 'relevance')
    )
WHERE "data" ?| ARRAY['generatedVideo', 'relevance'];
