-- Этап D ТЗ docs-tz/TZ-Greeting-2.0-Adaptive-Persona-Landing.md (§3.4,
-- «Открыто осознанно» §12): ответ человека о настроении «Особого повода»
-- хранится отдельно от итогового регистра.
--
-- До этой миграции бриф OTHER хранил только ПОБЕДИВШИЙ сигнал
-- (occasionRegister + registerSource). Когда ключевые слова или
-- классификатор поднимали регистр выше ответа человека, сам ответ
-- терялся: интерфейс после перезагрузки задавал вопрос заново, правка без
-- повторного ответа получала 400 OTHER_MOOD_REQUIRED, а если человек
-- переписывал описание и подъём снимался, серверу не на что было
-- вернуться, кроме умолчания.
--
-- Аддитивная миграция: колонка NULL-допустимая. Бэкфилл переносит ответ
-- там, где он известен, — у брифов, где победил сам человек
-- (registerSource = 'user'). У поднятых словами или классификатором ответ
-- уже потерян, восстановить его не из чего: такие брифы остаются с NULL,
-- и вопрос будет задан один раз, как и было.

ALTER TABLE "greeting_briefs" ADD COLUMN "userOccasionRegister" "GreetingRegister";

UPDATE "greeting_briefs"
SET "userOccasionRegister" = "occasionRegister"
WHERE "registerSource" = 'user' AND "occasion" = 'OTHER';
