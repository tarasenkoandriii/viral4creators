-- Съёмочные кадры раундов обучалки по сайту заказчика (вариант А,
-- 29.09.2026, §11-квиндециес ТЗ docs-tz/TZ-Tutorial-Video-Voiced.md).
--
-- У кадра раунда два потребителя с противоположными требованиями.
-- Предпросмотр едет в JSON-ответ и в колонку `roundScreenshots` и
-- потому снимается лёгким (390×844, JPEG q60, без плотности). Ролик
-- собирается тем же сборщиком, что и ролик мастера, на холсте
-- 720×1560 — и тот же кадр он растягивал почти вдвое, то есть мылил.
--
-- Здесь лежат ССЫЛКИ на кадры в Blob, а не сами кадры: тяжёлое место —
-- Blob, где оно дёшево, а не `jsonb`, правка которого переписывает
-- колонку целиком вместе с TOAST.
--
-- Nullable и без значения по умолчанию: у черновиков, созданных до
-- этой миграции, съёмочных кадров нет и взять их неоткуда. Backfill
-- невозможен по той же причине — пиксели не восстановить из уже
-- сжатого предпросмотра. Такие черновики собирают ролик из
-- предпросмотров, как и раньше; выравнивание длины массива делает
-- `toRoundsState`.
ALTER TABLE "client_site_tutorial_drafts"
  ADD COLUMN "roundVideoFrames" JSONB;
