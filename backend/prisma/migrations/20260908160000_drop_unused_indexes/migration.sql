-- Миграция 21 (этап 44, находки Б-1.5 и Б-1.6).
--
-- Два индекса, за которые платят все вставки, а пользуется ими никто.
--
-- 1. `ai_usage_anonymous_createdAt_idx` (этап 40). Задумывался под
--    `spentToday(null)` — потолок анонимных, который считается на каждом
--    платном вызове. Планировщик его НЕ БЕРЁТ: измерено на 800 тыс.
--    строк — 24–30 мс по `ai_usage_createdAt_idx` с фильтром против
--    10,6 мс принудительно по этому индексу, при 43 МБ его размера. То
--    есть выигрыш есть только в теории, а налог на вставку (24,9 мкс
--    против 13,3 мкс на строку) платится всегда.
--
--    Правильный ответ — ЧАСТИЧНЫЙ индекс `("createdAt") WHERE anonymous`
--    (5,0 мс, 4,4 МБ, планировщик берёт сам). Он не выражается в
--    `schema.prisma`, а CI сверяет базу со схемой (`migrate diff
--    --exit-code`) — исключение в этой проверке дороже, чем выигрыш:
--    именно она ловит расхождение руками написанных миграций. Поэтому
--    честнее снять неработающий индекс, чем держать его ради вида;
--    когда журнал начнёт болеть на этом запросе, решение вернётся уже
--    вместе со свёрткой (Б-1.7).
--
-- 2. `analysis_library_visibility_idx` — левый префикс составного
--    `(visibility, usageCount DESC, createdAt DESC)`, добавленного той
--    же миграцией 19. Проверено: после DROP тот же запрос идёт
--    `Index Only Scan` по составному.

DROP INDEX IF EXISTS "ai_usage_anonymous_createdAt_idx";
DROP INDEX IF EXISTS "analysis_library_visibility_idx";
