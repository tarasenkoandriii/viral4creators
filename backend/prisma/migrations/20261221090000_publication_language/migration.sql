-- Язык ролика в заявке на публикацию (этап 137,
-- docs-tz/TZ-Multilingual-YouTube.md).
--
-- YouTube не угадывает язык: без `snippet.defaultLanguage` площадка не
-- принимает локализованные заголовки и описания вовсе
-- (`defaultLanguageNotSet`), а зритель из Германии видит украинский
-- заголовок без пометки, что это другой язык. Язык берётся из локали
-- сессии и кладётся в снимок заявки рядом с заголовком — по той же
-- причине, по которой там лежит и заголовок: заявка переживает
-- TTL-очистку сессий, и перечитать язык потом будет неоткуда.
--
-- 'ru' по умолчанию — не «заглушка», а честное значение для уже
-- существующих строк: это DEFAULT_LOCALE продукта (common/locale.ts),
-- и вся текущая аудитория русскоязычная.
ALTER TABLE "publication_requests"
  ADD COLUMN "language" TEXT NOT NULL DEFAULT 'ru';
