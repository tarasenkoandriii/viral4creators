-- Кадр-постер публичной страницы ролика (приёмка плана
-- docs-tz/AUDIT-Greeting-Landing-And-Upgrade-Plan.md, раздел 3).
--
-- До этой колонки у страницы поздравления не было `og:image` ВООБЩЕ:
-- товарного фото у неё нет по определению, а превью самого ролика не
-- существовало — `GeneratedVideo.thumbnailUrl` не заполнял никто.
-- Ссылка, присланная получателю, разворачивалась в голую текстовую
-- карточку у типа проекта, весь смысл которого в отправке ссылки.
--
-- Обе колонки NULLABLE и без значения по умолчанию, поэтому миграция
-- аддитивная и ничего не переписывает: у всех уже опубликованных
-- страниц постера нет, и это их нормальное состояние — лендинг
-- подставит им запасную картинку. Заполняться поля начинают у страниц,
-- опубликованных после выката.
--
-- `posterPathname` хранится рядом с `posterUrl` по той же причине, что
-- и у видео с фото товара: по нему блоб удаляется вместе со страницей
-- (`SharedVideoService.withdraw`), иначе картинка пережила бы отзыв.

ALTER TABLE "SharedVideoPage" ADD COLUMN "posterUrl" TEXT;
ALTER TABLE "SharedVideoPage" ADD COLUMN "posterPathname" TEXT;
