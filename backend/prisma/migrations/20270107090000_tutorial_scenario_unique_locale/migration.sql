-- Одна строка сценария на пару (шаг, локаль) — этап C ТЗ
-- docs-tz/TZ-Tutorial-Video-Voiced.md §3-бис.6.
--
-- До этой миграции генератор делал `create` каждый суточный прогон:
-- строки копились, исполнитель брал их ВСЕ (`where` без дедупликации)
-- и снимал по ролику на каждую. С пятью локалями этапа C это
-- умножилось бы на пять.
--
-- Написана руками — сеть до binaries.prisma.sh недоступна в песочнице
-- разработки (doc/CI.md), `prisma migrate diff --exit-code` в CI
-- проверит, что она не разошлась со schema.prisma.

-- 1. Схлопываем накопившиеся дубли. Единственная миграция проекта,
--    которая УДАЛЯЕТ строки, поэтому правило отбора выписано явно:
--
--    - сперва одобренные (`approved DESC`). Одобрение — решение
--      человека о конкретных платных шагах, и потерять его, оставив
--      «самую свежую» неодобренную строку, значило бы остановить
--      исполнение платного сценария молча;
--    - затем самые свежие (`createdAt DESC`) — генератор улучшался,
--      последний ответ модели ближе к сегодняшнему интерфейсу;
--    - затем по `id` — чтобы порядок был определён и на строках,
--      созданных в одну миллисекунду.
--
--    Данные восстановимы: генератор пересоздаёт сценарии ночью.
--    Ссылка `tutorial_video_assets.scenarioId` — мягкая (не FK, §2.7),
--    каскада нет, уже снятые ролики не пострадают.
DELETE FROM "tutorial_scenarios"
 WHERE "id" IN (
   SELECT "id"
     FROM (
       SELECT "id",
              row_number() OVER (
                PARTITION BY "subjectKey", "locale"
                ORDER BY "approved" DESC, "createdAt" DESC, "id" DESC
              ) AS rn
         FROM "tutorial_scenarios"
     ) ranked
    WHERE rn > 1
 );

-- 2. Само ограничение. `IF NOT EXISTS` — чтобы все три шага были
--    идемпотентны одинаково: шаги 1 и 3 повторный накат переживают, и
--    обрываться на середине из-за второго было бы странно (прод
--    дважды не накатит, а ручное восстановление стенда — запросто).
CREATE UNIQUE INDEX IF NOT EXISTS "tutorial_scenarios_subjectKey_locale_key"
  ON "tutorial_scenarios" ("subjectKey", "locale");

-- 3. Прежний индекс больше не нужен: он начинался с той же пары, а в
--    паре теперь ровно одна строка — сортировать внутри неё нечего.
DROP INDEX IF EXISTS "tutorial_scenarios_subjectKey_locale_createdAt_idx";
