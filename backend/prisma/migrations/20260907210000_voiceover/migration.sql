-- Этап 35 (ТЗ §15): настоящая озвучка.
--
-- Две несвязанные на первый взгляд правки живут в одной миграции
-- сознательно: обе появляются вместе с озвучкой и по отдельности не
-- имеют смысла — режим озвучки без счётчика символов нечем считать, а
-- счётчик без режима некому наполнять.

-- 1. Режим озвучки и голос — на манифесте бренда (§12): голос это часть
--    бренда, а не настройка одной сессии. Значение по умолчанию
--    сохраняет поведение до этапа 35 для всех существующих манифестов.
ALTER TABLE "brand_manifests"
  ADD COLUMN "voiceMode" TEXT NOT NULL DEFAULT 'veo',
  ADD COLUMN "ttsVoiceId" TEXT,
  ADD COLUMN "ttsModel" TEXT;

-- 2. Символы синтеза — в журнале расходов (§26): у TTS счёт идёт за
--    символы, и записывать их в колонку токенов значило бы врать в
--    отчёте о деньгах.
ALTER TABLE "ai_usage"
  ADD COLUMN "characters" INTEGER NOT NULL DEFAULT 0;
