-- причине: на serverless он случается на каждом холодном запуске, и
-- «идемпотентная» вставка превратилась бы в лишний запрос к базе на
-- каждый такой старт. Миграция выполняется один раз по построению, в
-- том же `prisma migrate deploy`, которым едут остальные.
--
-- Идентификатор фиксированный, а не сгенерированный: только так повторный
-- прогон (например, после восстановления базы из дампа, снятого до
-- этой миграции) не заводит вторую копию.
--
-- Статус DRAFT намеренно: причину подтверждает владелец кнопкой
-- «Опубликовать» (§15 п.1). Миграция ничего не публикует — публикация
-- человеком и есть модерация §6.5.
