-- Сборка полного звука альтернативной дорожки (этап 138, вторая
-- половина; docs-tz/TZ-Multilingual-YouTube.md §5).
--
-- Дорожка для YouTube — это ВЕСЬ звук ролика на другом языке, а не один
-- голос: она заменяет оригинальную целиком. Собирается тем же рецептом
-- ffmpeg, что и оригинальный звук, с подменой одного входа, — то есть
-- задачей у хостед-сервиса, с опросом готовности. Отсюда `mixJobId`
-- рядом с готовым файлом.
--
-- Отдельного статуса «собирается» намеренно нет: «задача есть, файла
-- нет» — то же самое, и ровно так же устроена постобработка ролика.
-- Значение enum'а добавлять не пришлось, а это отдельная головная боль
-- в Postgres (ALTER TYPE ADD VALUE и транзакция миграции).
ALTER TABLE "video_audio_tracks"
  ADD COLUMN "mixJobId" TEXT,
  ADD COLUMN "trackPathname" TEXT,
  ADD COLUMN "trackUrl" TEXT,
  ADD COLUMN "mixError" TEXT;
